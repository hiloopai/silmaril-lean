tvar $a term x $.
$( Zero. $)
t0 $a term 0 $.
$( Successor. $)
tS $a term S t $.
$( Addition. $)
tpl $a term [ t + u ] $.
$( Multiplication. $)
tmu $a term [ t x. u ] $.

$( Negation. $)
wn $a wff -. ph $.
$( Implication. $)
wi $a wff ( ph -> ps ) $.
$( Biconditional. $)
wb $a wff ( ph <-> ps ) $.
$( Conjunction. $)
wa $a wff ( ph /\ ps ) $.
$( Number quantifier. $)
wal $a wff A. x ph $.
$( Existential number quantifier. $)
wex $a wff E. x ph $.
$( Set quantifier. $)
wsal $a wff A. X ph $.
$( Existential set quantifier. $)
