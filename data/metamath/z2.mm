   https://creativecommons.org/publicdomain/zero/1.0/

   Written for the Silmaril formalization of Metamath
   (Silmaril/Logic/Metamath/SecondOrder).  It follows the conventions of
   set.mm: a Tarski-Megill style predicate calculus with disjoint-variable
   conditions, schemes over wff and term metavariables, and definitions as
   axioms.

   The language is two-sorted (Simpson, Subsystems of Second Order
   Arithmetic, 2nd ed., Section I.2).  Number variables ` x y z w ` have the
   typecode ` nvar ` and set variables ` X Y Z ` the typecode ` svar ` .
   Terms are built from number variables, ` 0 ` , ` S ` , ` + ` and ` x. ` ;
   atomic formulas are ` t = u ` , ` t < u ` and ` t e. X ` .  Formulas are
   closed under ` -. ` , ` -> ` , ` <-> ` , ` /\ ` and quantification over
   numbers and over sets.  Set equality ` X = Y ` is defined by extension.
   Terms use square brackets and formulas round ones, so that the grammar is
   LL(1) (an LL certificate is checked in Lean).

   Syntactic classes of formulas are the provable typecodes ` bnd `
   (bounded, Sigma^0_0), ` sig1 ` (Sigma^0_1), ` pi1 ` (Pi^0_1) and ` arith `
   (arithmetical: no set quantifiers).  Each reads as ` wff ` , and its
   theorems are generated by the formation rules below, so ` bnd ph ` says
   that ` ph ` is a bounded formula.  Coercions between classes are the rules
   ~ sig1-bnd , ~ pi1-bnd , ~ arith-sig1 and ~ arith-pi1 .  The schemes of the
   subsystems restrict their formula metavariable with a class hypothesis.

   The named axiom sets (defined in Lean, SecondOrder/Systems.lean) are:
     Base  = logic, definitions, class formation rules, basic arithmetic;
     RCA0  = Base + ax-ind-sig1 + ax-dcomp;
     WKL0  = RCA0 + ax-sep1;
     ACA0  = Base + ax-ind-sig1 + ax-acomp;
     Z2    = ACA0 + ax-ind + ax-comp.
   Weak Koenig's lemma is stated as Sigma^0_1 separation ( ~ ax-sep1 ), which
   is equivalent to it over RCA0 (Simpson, Lemma IV.4.4); the tree form needs
   a coding of finite sequences that the language does not have as a
   primitive.  The theorems at the end derive Delta^0_1 comprehension in
   ACA0 and the restricted schemes from the full ones.
$)

$c ( ) -> -. <-> /\ A. E. = < e. $.
$c 0 S [ ] + x. $.
$c wff term nvar svar |- bnd sig1 pi1 arith $.

