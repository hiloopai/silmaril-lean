$(
  Propositional calculus
$)

${
  min $e |- ph $.
  maj $e |- ( ph -> ps ) $.
  $( Modus ponens. $)
  ax-mp $a |- ps $.
$}

$( Axiom Simp. $)
ax-1 $a |- ( ph -> ( ps -> ph ) ) $.
$( Axiom Frege. $)
ax-2 $a |- ( ( ph -> ( ps -> ch ) ) -> ( ( ph -> ps ) -> ( ph -> ch ) ) ) $.
$( Axiom Transp. $)
ax-3 $a |- ( ( -. ph -> -. ps ) -> ( ps -> ph ) ) $.

$( The biconditional implies the forward implication. $)
df-bi1 $a |- ( ( ph <-> ps ) -> ( ph -> ps ) ) $.
$( The biconditional implies the reverse implication. $)
df-bi2 $a |- ( ( ph <-> ps ) -> ( ps -> ph ) ) $.
$( Two implications give the biconditional. $)
df-bi3 $a |- ( ( ph -> ps ) -> ( ( ps -> ph ) -> ( ph <-> ps ) ) ) $.
$( Conjunction. $)
df-an $a |- ( ( ph /\ ps ) <-> -. ( ph -> -. ps ) ) $.

$(
  Quantifiers over numbers
$)

${
  ax-g.1 $e |- ph $.
  $( Generalization. $)
  ax-gen $a |- A. x ph $.
$}

$( Quantified implication. $)
ax-4 $a |- ( A. x ( ph -> ps ) -> ( A. x ph -> A. x ps ) ) $.
${
  $d x ph $.
  $( Vacuous quantification. $)
  ax-5 $a |- ( ph -> A. x ph ) $.
$}
$( Existence of a number equal to a variable. $)
ax-6 $a |- -. A. x -. x = y $.
$( Equality is transitive and symmetric. $)
ax-7 $a |- ( t = u -> ( t = v -> u = v ) ) $.
$( Quantified negation. $)
ax-10 $a |- ( -. A. x ph -> A. x -. A. x ph ) $.
$( Quantifier commutation. $)
ax-11 $a |- ( A. x A. y ph -> A. y A. x ph ) $.
$( Substitution. $)
ax-12 $a |- ( x = y -> ( A. y ph -> A. x ( x = y -> ph ) ) ) $.
$( Quantified equality. $)
ax-13 $a |- ( -. x = y -> ( y = z -> A. x y = z ) ) $.
${
  $d x t $.
  $( Every term denotes a number. $)
  ax-tex $a |- -. A. x -. x = t $.
$}
$( Existential quantification. $)
df-ex $a |- ( E. x ph <-> -. A. x -. ph ) $.

$(
  Quantifiers over sets
$)

${
  ax-sg.1 $e |- ph $.
  $( Generalization. $)
  ax-sgen $a |- A. X ph $.
$}

$( Quantified implication. $)
ax-s4 $a |- ( A. X ( ph -> ps ) -> ( A. X ph -> A. X ps ) ) $.
${
  $d X ph $.
  $( Vacuous quantification. $)
  ax-s5 $a |- ( ph -> A. X ph ) $.
$}
$( Existence of a set equal to a variable. $)
ax-s6 $a |- -. A. X -. X = Y $.
$( Set equality is transitive and symmetric. $)
ax-s7 $a |- ( X = Y -> ( X = Z -> Y = Z ) ) $.
$( Quantified negation. $)
ax-s10 $a |- ( -. A. X ph -> A. X -. A. X ph ) $.
$( Quantifier commutation. $)
ax-s11 $a |- ( A. X A. Y ph -> A. Y A. X ph ) $.
$( Substitution. $)
ax-s12 $a |- ( X = Y -> ( A. Y ph -> A. X ( X = Y -> ph ) ) ) $.
$( Quantified equality. $)
ax-s13 $a |- ( -. X = Y -> ( Y = Z -> A. X Y = Z ) ) $.
$( Commutation of a number and a set quantifier. $)
ax-ns11 $a |- ( A. x A. X ph -> A. X A. x ph ) $.
$( Commutation of a set and a number quantifier. $)
ax-sn11 $a |- ( A. X A. x ph -> A. x A. X ph ) $.
$( Existential set quantification. $)
df-sex $a |- ( E. X ph <-> -. A. X -. ph ) $.
$( Extensionality: sets with the same members are equal. $)
df-seq $a |- ( X = Y <-> A. x ( x e. X <-> x e. Y ) ) $.

$(
  Equality
$)

$( Successor respects equality. $)
ax-eqS $a |- ( t = u -> S t = S u ) $.
$( Addition respects equality on the left. $)
ax-eqpl1 $a |- ( t = u -> [ t + v ] = [ u + v ] ) $.
$( Addition respects equality on the right. $)
ax-eqpl2 $a |- ( t = u -> [ v + t ] = [ v + u ] ) $.
$( Multiplication respects equality on the left. $)
ax-eqmu1 $a |- ( t = u -> [ t x. v ] = [ u x. v ] ) $.
$( Multiplication respects equality on the right. $)
ax-eqmu2 $a |- ( t = u -> [ v x. t ] = [ v x. u ] ) $.
$( Order respects equality on the left. $)
ax-eqlt1 $a |- ( t = u -> ( t < v -> u < v ) ) $.
$( Order respects equality on the right. $)
ax-eqlt2 $a |- ( t = u -> ( v < t -> v < u ) ) $.
$( Membership respects equality of numbers. $)
ax-eqel1 $a |- ( t = u -> ( t e. X -> u e. X ) ) $.
$( Membership respects equality of sets. $)
ax-eqel2 $a |- ( X = Y -> ( t e. X -> t e. Y ) ) $.

$(
  Basic axioms of arithmetic (Simpson, Definition I.2.4 (i))
$)

$( Zero is not a successor. $)
ax-S0 $a |- -. S t = 0 $.
$( Successor is injective. $)
ax-Sinj $a |- ( S t = S u -> t = u ) $.
$( Addition of zero. $)
ax-pl0 $a |- [ t + 0 ] = t $.
$( Addition of a successor. $)
ax-plS $a |- [ t + S u ] = S [ t + u ] $.
$( Multiplication by zero. $)
ax-mu0 $a |- [ t x. 0 ] = 0 $.
$( Multiplication by a successor. $)
ax-muS $a |- [ t x. S u ] = [ [ t x. u ] + t ] $.
$( Nothing is below zero. $)
ax-lt0 $a |- -. t < 0 $.
$( Below a successor: ` t < S u ` exactly when ` t < u ` or ` t = u ` . $)
ax-ltS $a |- ( t < S u <-> ( -. t < u -> t = u ) ) $.

$(
  Bounded formulas
$)

$( An equation is bounded. $)
bnd-eq $a bnd t = u $.
$( An inequality is bounded. $)
bnd-lt $a bnd t < u $.
$( A membership is bounded. $)
bnd-el $a bnd t e. X $.
${
  bnd-n.1 $e bnd ph $.
  $( Bounded formulas are closed under negation. $)
  bnd-n $a bnd -. ph $.
$}
${
  bnd-2.1 $e bnd ph $.
  bnd-2.2 $e bnd ps $.
  $( Bounded formulas are closed under implication. $)
  bnd-i $a bnd ( ph -> ps ) $.
  $( Bounded formulas are closed under the biconditional. $)
  bnd-b $a bnd ( ph <-> ps ) $.
  $( Bounded formulas are closed under conjunction. $)
  bnd-a $a bnd ( ph /\ ps ) $.
$}
${
  $d x t $.
  bnd-q.1 $e bnd ph $.
  $( Bounded universal quantification. $)
  bnd-ral $a bnd A. x ( x < t -> ph ) $.
  $( Bounded existential quantification. $)
  bnd-rex $a bnd E. x ( x < t /\ ph ) $.
$}

$(
  Sigma^0_1 and Pi^0_1 formulas
$)

${
  sig1-bnd.1 $e bnd ph $.
  $( A bounded formula is Sigma^0_1. $)
  sig1-bnd $a sig1 ph $.
  $( An existentially quantified bounded formula is Sigma^0_1. $)
  sig1-ex $a sig1 E. x ph $.
  $( A bounded formula is Pi^0_1. $)
  pi1-bnd $a pi1 ph $.
  $( A universally quantified bounded formula is Pi^0_1. $)
  pi1-al $a pi1 A. x ph $.
$}

$(
  Arithmetical formulas
$)

$( An equation is arithmetical. $)
arith-eq $a arith t = u $.
$( An inequality is arithmetical. $)
arith-lt $a arith t < u $.
$( A membership is arithmetical. $)
arith-el $a arith t e. X $.
$( An equality of sets is arithmetical. $)
arith-seq $a arith X = Y $.
${
  arith-n.1 $e arith ph $.
  $( Arithmetical formulas are closed under negation. $)
  arith-n $a arith -. ph $.
  $( Arithmetical formulas are closed under number quantification. $)
  arith-al $a arith A. x ph $.
  $( Arithmetical formulas are closed under existential number
     quantification. $)
  arith-ex $a arith E. x ph $.
$}
${
  arith-2.1 $e arith ph $.
  arith-2.2 $e arith ps $.
  $( Arithmetical formulas are closed under implication. $)
  arith-i $a arith ( ph -> ps ) $.
  $( Arithmetical formulas are closed under the biconditional. $)
  arith-b $a arith ( ph <-> ps ) $.
  $( Arithmetical formulas are closed under conjunction. $)
  arith-a $a arith ( ph /\ ps ) $.
$}
${
  arith-sig1.1 $e sig1 ph $.
  $( A Sigma^0_1 formula is arithmetical. $)
  arith-sig1 $a arith ph $.
$}
${
  arith-pi1.1 $e pi1 ph $.
  $( A Pi^0_1 formula is arithmetical. $)
  arith-pi1 $a arith ph $.
$}

$(
  Induction and comprehension
$)

${
  $d x y $.  $d y ph $.
  ax-ind-sig1.1 $e sig1 ph $.
  $( Sigma^0_1 induction: ` A. x ( x = y -> ph ) ` is ` ph ` at ` y ` . $)
  ax-ind-sig1 $a |- ( A. x ( x = 0 -> ph ) ->
      ( A. y ( A. x ( x = y -> ph ) -> A. x ( x = S y -> ph ) ) ->
        A. x ph ) ) $.
$}

${
  $d X ph $.  $d X ps $.
  ax-dcomp.1 $e sig1 ph $.
  ax-dcomp.2 $e pi1 ps $.
  $( Delta^0_1 comprehension. $)
  ax-dcomp $a |- ( A. x ( ph <-> ps ) -> E. X A. x ( x e. X <-> ph ) ) $.
$}

${
  $d X ph $.  $d X ps $.
  ax-sep1.1 $e sig1 ph $.
  ax-sep1.2 $e sig1 ps $.
  $( Sigma^0_1 separation, the form of weak Koenig's lemma used here. $)
  ax-sep1 $a |- ( A. x -. ( ph /\ ps ) ->
      E. X A. x ( ( ph -> x e. X ) /\ ( ps -> -. x e. X ) ) ) $.
$}

${
  $d X ph $.
  ax-acomp.1 $e arith ph $.
  $( Arithmetical comprehension. $)
  ax-acomp $a |- E. X A. x ( x e. X <-> ph ) $.
$}

${
  $d x y $.  $d y ph $.
  $( Full induction. $)
  ax-ind $a |- ( A. x ( x = 0 -> ph ) ->
      ( A. y ( A. x ( x = y -> ph ) -> A. x ( x = S y -> ph ) ) ->
        A. x ph ) ) $.
$}

${
  $d X ph $.
  $( Full comprehension. $)
  ax-comp $a |- E. X A. x ( x e. X <-> ph ) $.
$}

$(
  Theorems
$)

${
  a1i.1 $e |- ph $.
  $( Inference form of ~ ax-1 . $)
  a1i $p |- ( ps -> ph ) $=
      wph wps wph wi a1i.1 wph wps ax-1 ax-mp $.
$}

${
  $d X ph $.  $d X ps $.
  dcomp-aca.1 $e sig1 ph $.
  dcomp-aca.2 $e pi1 ps $.
  $( Delta^0_1 comprehension holds in ACA0: ~ ax-dcomp follows from
     ~ ax-acomp by the coercion ~ arith-sig1 . $)
  dcomp-aca $p |- ( A. x ( ph <-> ps ) -> E. X A. x ( x e. X <-> ph ) ) $=
      vX vx tvar wel wph wb vx wal vX wsex wph wps wb vx wal wph vx vX wph
      dcomp-aca.1 arith-sig1 ax-acomp a1i $.
$}

${
  $d x y $.  $d y ph $.
  ind-sig1-ind.1 $e sig1 ph $.
  $( Sigma^0_1 induction is an instance of full induction ~ ax-ind . $)
  ind-sig1-ind $p |- ( A. x ( x = 0 -> ph ) ->
      ( A. y ( A. x ( x = y -> ph ) -> A. x ( x = S y -> ph ) ) ->
        A. x ph ) ) $=
      wph vx vy ax-ind $.
$}

${
  $d X ph $.
  acomp-comp.1 $e arith ph $.
  $( Arithmetical comprehension is an instance of full comprehension
     ~ ax-comp . $)
  acomp-comp $p |- E. X A. x ( x e. X <-> ph ) $=
      wph vx vX ax-comp $.
$}
