       common but ambiguous notation, " ` ph ( t ) ` is the wff that results
       when ` t ` is properly substituted for ` x ` in ` ph ( x ) ` ".  For
       example, if the original ` ph ( x ) ` is ` x = t ` , then ` ph ( t ) `
