#!/usr/bin/env bash
# The Lean blob modules of the pinned ladder executables.
#
#   examples/elf-ladder/pin.sh           # regenerate Silmaril/X86/Ladder/Pinned/<Module>.lean
#                                        # from <rung>/pinned/<executable>
#   examples/elf-ladder/pin.sh --check   # the committed modules match the pinned files and
#                                        # their .sha256 (byte-exact; no compiler needed)
#
# Each module holds one `Silmaril.X86.Link.Blob`: the file as one little-endian natural number
# and its length. `Silmaril.X86.Ladder.Pinned.Thms` proves by kernel evaluation that each
# transcribed code literal is a slice of a loaded segment of `ELFImage.parse` of that blob;
# `--check` ties the blob to the committed file. Needs only coreutils. Untrusted tooling.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
OUTDIR=$ROOT/Silmaril/X86/Ladder/Pinned
MODE=${1:-write}

# rung-directory executable Lean-module-suffix
RUNGS=(
  "02-mem-loops mem-loops MemLoops"
  "03-zlib-checksums zlib-checksums ZlibChecksums"
)

render() { # rung exe suffix
  local rung=$1 exe=$2 suffix=$3 file=$HERE/$1/pinned/$2 size sha hex
  size=$(stat -c %s "$file")
  sha=$(sha256sum "$file" | cut -d' ' -f1)
  # little-endian: the last byte of the file is the most significant digit pair
  hex=$(od -An -v -tx1 "$file" | tr -s ' \n' '\n' | sed '/^$/d' | tac | tr -d '\n' | sed 's/^0*//')
  cat <<LEAN
module

public import Silmaril.X86.Link.Blob.Defs

/-! # Pinned ladder executable: $rung -O2 ($exe)

Generated by \`examples/elf-ladder/pin.sh\`; do not edit. Source file:
\`examples/elf-ladder/$rung/pinned/$exe\` (built by \`examples/elf-ladder/$rung/build.sh\` at
\`-O2\` with GCC 13.3.0 and GNU ld 2.42; check with \`examples/elf-ladder/pin.sh --check\`).

* \`exe\` = \`$exe\`, $size bytes, SHA-256 \`$sha\`
-/

@[expose] public section

namespace Silmaril.X86.Ladder.Pinned.$suffix

open Silmaril.X86.Link

/-- \`$exe\` -/
def exe : Blob := ⟨0x${hex:-0}, $size⟩

end Silmaril.X86.Ladder.Pinned.$suffix
LEAN
}

status=0
for row in "${RUNGS[@]}"; do
  read -r rung exe suffix <<<"$row"
  (cd "$HERE/$rung/pinned" && sha256sum --quiet -c "$exe.sha256") || status=1
  out=$OUTDIR/$suffix.lean
  case $MODE in
    write) mkdir -p "$OUTDIR"; render "$rung" "$exe" "$suffix" >"$out"; echo "wrote $out" ;;
    --check)
      if render "$rung" "$exe" "$suffix" | cmp -s - "$out"; then echo "ok $suffix"
      else echo "error: $out does not match $rung/pinned/$exe" >&2; status=1; fi ;;
    *) echo "usage: $0 [--check]" >&2; exit 2 ;;
  esac
done
exit $status
