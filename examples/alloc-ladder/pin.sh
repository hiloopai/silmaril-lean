#!/usr/bin/env bash
# The Lean blob modules of the pinned allocator-ladder executables (after
# silmaril-lean examples/elf-ladder/pin.sh).
#   pin.sh           regenerate Silmaril/Libc/X86Alloc/Pinned/<Module>.lean
#   pin.sh --check   the committed modules match the pinned files and their .sha256
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$HERE/../.." && pwd)
OUTDIR=$ROOT/Silmaril/Libc/X86Alloc/Pinned
MODE=${1:-write}
RUNGS=("01-never Never" "02-bump Bump" "03-bump-align BumpAlign" "04-pool Pool" "05-firstfit FirstFit" "06-coalesce Coalesce" "07-sizeclass SizeClass" "08-boundary Boundary" "08t-boundary-textbook BoundaryTextbook")
render() { # rung suffix
  local rung=$1 suffix=$2 file=$HERE/$1/pinned/alloc size sha hex
  size=$(stat -c %s "$file"); sha=$(sha256sum "$file" | cut -d' ' -f1)
  hex=$(od -An -v -tx1 "$file" | tr -s ' \n' '\n' | sed '/^$/d' | tac | tr -d '\n' | sed 's/^0*//')
  cat <<LEAN
module

public import Silmaril.X86.Link.Blob.Defs

/-! # Pinned allocator-ladder executable: $rung -O2

Generated by \`examples/alloc-ladder/pin.sh\`; do not edit. Source file:
\`examples/alloc-ladder/$rung/pinned/alloc\` (built by \`examples/alloc-ladder/$rung/build.sh\` at
\`-O2\` with GCC 13.3.0 and GNU ld 2.42; check with \`examples/alloc-ladder/pin.sh --check\`).

* \`alloc\`, $size bytes, SHA-256 \`$sha\`
-/

@[expose] public section

namespace Silmaril.Libc.X86Alloc.Pinned.$suffix

open Silmaril.X86.Link

/-- \`examples/alloc-ladder/$rung/pinned/alloc\` -/
def exe : Blob := ⟨0x${hex:-0}, $size⟩

end Silmaril.Libc.X86Alloc.Pinned.$suffix
LEAN
}
status=0
for row in "${RUNGS[@]}"; do
  read -r rung suffix <<<"$row"
  (cd "$HERE/$rung/pinned" && sha256sum --quiet -c alloc.sha256) || status=1
  out=$OUTDIR/$suffix.lean
  case $MODE in
    write) mkdir -p "$OUTDIR"; render "$rung" "$suffix" >"$out"; echo "wrote $out" ;;
    --check) if render "$rung" "$suffix" | cmp -s - "$out"; then echo "ok $suffix"
             else echo "error: $out does not match $rung/pinned/alloc" >&2; status=1; fi ;;
    *) echo "usage: $0 [--check]" >&2; exit 2 ;;
  esac
done
exit $status
