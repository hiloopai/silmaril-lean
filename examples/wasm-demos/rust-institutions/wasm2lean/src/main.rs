//! `wasm2lean`: bring compiled `.wasm` binaries into Lean.
//!
//! ```text
//! wasm2lean wat FILE.wasm                       # print WAT (custom sections dropped)
//! wasm2lean lean OUT.lean NAMESPACE name=FILE.wasm ...
//! ```
//!
//! `lean` writes a Lean module defining, for each `name=FILE.wasm`, `def name : Module :=
//! wat3! r#"..."#` with the module printed by `wasmprinter`, so that silmaril-lean's `wat3!`
//! quotation turns it into an ordinary `Silmaril.Wasm.Module` term. The printed text is trusted
//! to denote the binary (`wasmprinter` and `wat3!` are not verified against silmaril-lean's
//! binary decoder).
use std::fmt::Write as _;
use std::process::ExitCode;

const USAGE: &str =
    "usage: wasm2lean wat FILE.wasm\n       wasm2lean lean OUT.lean NAMESPACE name=FILE.wasm ...";

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let r = match args.as_slice() {
        [cmd, file] if cmd == "wat" => wat_of_file(file).map(|w| print!("{w}")),
        [cmd, out, ns, items @ ..] if cmd == "lean" && !items.is_empty() => lean(out, ns, items),
        _ => Err(USAGE.to_string()),
    };
    match r {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("wasm2lean: {e}");
            ExitCode::from(2)
        }
    }
}

fn wat_of_file(path: &str) -> Result<String, String> {
    let bytes = std::fs::read(path).map_err(|e| format!("{path}: {e}"))?;
    wat(&bytes).map_err(|e| format!("{path}: {e}"))
}

/// Print a binary module as WAT, without its custom sections.
fn wat(bytes: &[u8]) -> Result<String, String> {
    let stripped = strip_custom(bytes)?;
    let mut out = String::new();
    let mut cfg = wasmprinter::Config::new();
    cfg.name_unnamed(false);
    cfg.print(&stripped, &mut wasmprinter::PrintFmtWrite(&mut out))
        .map_err(|e| e.to_string())?;
    Ok(out)
}

fn lean(out: &str, ns: &str, items: &[String]) -> Result<(), String> {
    let mut s = String::new();
    let mut defs = String::new();
    let mut table = String::new();
    for item in items {
        let (name, path) = item
            .split_once('=')
            .ok_or_else(|| format!("expected name=FILE: {item}"))?;
        let bytes = std::fs::read(path).map_err(|e| format!("{path}: {e}"))?;
        let w = wat(&bytes)?;
        if w.contains("\"#") {
            return Err(format!("{path}: the WAT contains \"#"));
        }
        let file = std::path::Path::new(path)
            .file_name()
            .map_or(path.into(), |f| f.to_string_lossy());
        let _ = writeln!(
            table,
            "* `{name}`: `{file}` ({} bytes, FNV-1a 64 `{:016x}`)",
            bytes.len(),
            fnv1a(&bytes)
        );
        let _ = write!(
            defs,
            "/-- `{file}`, as printed by `wasm2lean`. -/\ndef {name} : Module := wat3! r#\"\n{w}\"#\n\n"
        );
    }
    let _ = write!(
        s,
        "module\n\npublic import Silmaril.Wasm.Modules\npublic meta import Silmaril.Wasm.Wat\n\n\
@[expose] public section\n\n/-!\n# Compiled Wasm modules\n\n\
Generated by `examples/wasm-demos/rust-institutions/wasm2lean` (`wasm2lean lean`) from the\n\
release builds of the Rust demo crates (`rustc` 1.98.1, `wasm32-unknown-unknown`); do not edit.\n\
Each binary is printed as WAT by `wasmprinter` (custom sections dropped) and quoted with\n\
silmaril-lean's `wat3!`. That the quoted module is the one the binary decodes to is trusted, not\n\
proved.\n\n{table}-/\n\nnamespace {ns}\n\nopen Silmaril.Wasm\n\n{defs}end {ns}\n"
    );
    std::fs::write(out, s).map_err(|e| format!("{out}: {e}"))
}

/// FNV-1a, 64-bit: a fingerprint of the binary for the generated documentation.
fn fnv1a(b: &[u8]) -> u64 {
    b.iter().fold(0xcbf2_9ce4_8422_2325, |h, &x| {
        (h ^ x as u64).wrapping_mul(0x100_0000_01b3)
    })
}

/// Drop every custom section (id 0) from a binary module.
fn strip_custom(b: &[u8]) -> Result<Vec<u8>, String> {
    if b.len() < 8 {
        return Err("not a Wasm binary".into());
    }
    let mut out = b[..8].to_vec();
    let mut i = 8;
    while i < b.len() {
        let id = b[i];
        let (len, n) = leb(&b[i + 1..]).ok_or("truncated section header")?;
        let end = i + 1 + n + len;
        if end > b.len() {
            return Err("truncated section".into());
        }
        if id != 0 {
            out.extend_from_slice(&b[i..end]);
        }
        i = end;
    }
    Ok(out)
}

fn leb(b: &[u8]) -> Option<(usize, usize)> {
    let mut v = 0usize;
    for (k, &x) in b.iter().enumerate().take(5) {
        v |= ((x & 0x7f) as usize) << (7 * k);
        if x & 0x80 == 0 {
            return Some((v, k + 1));
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strips_custom_sections() {
        // header, a custom section "a" with one byte, an empty type section
        let b = [0, 0x61, 0x73, 0x6d, 1, 0, 0, 0, 0, 3, 1, b'a', 7, 1, 1, 0];
        assert_eq!(
            strip_custom(&b).unwrap(),
            [0, 0x61, 0x73, 0x6d, 1, 0, 0, 0, 1, 1, 0]
        );
        assert_eq!(wat(&b).unwrap().trim(), "(module)");
    }
}
