#!/usr/bin/env python3
"""Build the example programs with `gcc -static`, run each in a fresh temporary directory
under `strace` on a concrete input, and print the observed LPS observations as a Lean
module (`Silmaril/Compile/Examples/LPS/Observed.lean`).

LPS observes byte-granular reads of stdin (`readEv 0 b`), writes to stdout and stderr
(`writeEv 1 b`, `writeEv 2 b`), and the exit status with the final file system (`exitEv`).
`strace` records the same: the bytes of `read(0, …)` and `write(1|2, …)` as returned (short
reads and writes included), `exit_group(n)`, and the directory contents after exit.

Usage: observe.py OUT.lean   (run from anywhere; sources are next to this script)
"""

import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))

# label, program, argv (after the program name), stdin bytes, initial files (relative
# path -> bytes), address-space limit in bytes (None: unlimited). The limited `malloc` run
# exercises the allocation-refusal path (LPS: the allocation budget refuses mmap/brk).
CASES = [
    ("exit42", "exit42", [], b"", {}, None),
    ("hello", "hello", [], b"", {}, None),
    ("helloCore", "hello-core", [], b"", {}, None),
    ("cat", "cat", [], b"abc\nxyz\n", {}, None),
    ("wc", "wc", [], b"one two\nthree\n", {}, None),
    ("crc32", "crc32", [], b"123456789", {}, None),
    ("cp", "cp", ["a.txt", "b.txt"], b"", {"a.txt": b"data\n"}, None),
    ("cpMissing", "cp", ["missing.txt", "b.txt"], b"", {"a.txt": b"data\n"}, None),
    ("malloc", "malloc", [], b"", {}, None),
    ("mallocOom", "malloc", [], b"", {}, 2000000),
]

CALL = re.compile(r'^(read|write)\((\d+), "((?:[^"\\]|\\.)*)"(?:\.\.\.)?, \d+\)\s+= (-?\d+)')
EXIT = re.compile(r'^exit_group\((-?\d+)\)')


def unescape(s):
    out = bytearray()
    i = 0
    while i < len(s):
        if s[i] == "\\" and s[i + 1] == "x":
            out.append(int(s[i + 2:i + 4], 16))
            i += 4
        else:
            raise ValueError("unexpected strace escape: " + s[i:i + 4])
    return bytes(out)


def observe(label, name, args, stdin, files, limit, build):
    exe = os.path.join(build, name)
    subprocess.run(["gcc", "-O1", "-static", "-o", exe, os.path.join(HERE, name + ".c")],
                   check=True)
    with tempfile.TemporaryDirectory() as run:
        for path, data in files.items():
            with open(os.path.join(run, path), "wb") as f:
                f.write(data)
        log = os.path.join(build, label + ".strace")
        cmd = [exe] if limit is None else ["prlimit", f"--as={limit}", exe]
        proc = subprocess.run(
            ["strace", "-qq", "-xx", "-s", "1000000", "-o", log,
             "-f", "-e", "trace=read,write,exit_group"] + cmd + args,
            input=stdin, capture_output=True, cwd=run)
        events = []
        code = None
        with open(log) as f:
            for line in f:
                line = re.sub(r"^\d+ +", "", line)  # `-f` prefixes the pid
                m = CALL.match(line)
                if m:
                    call, fd, data, ret = m.group(1), int(m.group(2)), m.group(3), int(m.group(4))
                    if ret <= 0:
                        continue
                    bs = unescape(data)[:ret]
                    if call == "read" and fd == 0:
                        events += [("readEv", 0, b) for b in bs]
                    elif call == "write" and fd in (1, 2):
                        events += [("writeEv", fd, b) for b in bs]
                    continue
                m = EXIT.match(line)
                if m:
                    code = int(m.group(1))
        assert code == proc.returncode, (name, code, proc.returncode)
        assert bytes(b for (k, fd, b) in events if k == "writeEv" and fd == 1) == proc.stdout, (name, events, proc.stdout)
        final = {}
        for path in sorted(os.listdir(run)):
            with open(os.path.join(run, path), "rb") as f:
                final[path] = f.read()
    return events, code, final


def lean_bytes(bs):
    return "[" + ", ".join(str(b) for b in bs) + "]"


def lean_fs(files):
    # LPS keys are relative paths; `Fs.sorted` orders them by `pathLtb` (bytewise).
    items = sorted((p.encode(), d) for p, d in files.items())
    return "[" + ", ".join(f"({lean_bytes(p)}, {lean_bytes(d)})" for p, d in items) + "]"


def main():
    out = sys.argv[1]
    lines = [
        "module",
        "",
        "public import Silmaril.Compile.Examples.LPS.Obs",
        "",
        "/-! # Observed runs of the example programs (generated)",
        "",
        "Generated by `examples/compilers-on-lps/observe.py`: each program built with",
        "`gcc -O1 -static`, run in a fresh temporary directory under `strace`, its stdin reads,",
        "stdout/stderr writes, exit status and final directory contents transcribed as LPS events.",
        "Do not edit by hand. -/",
        "",
        "@[expose] public section",
        "",
        "namespace Silmaril.Compile.Examples.LPS.Observed",
        "",
        "open Silmaril.Process.LPS",
        "",
    ]
    with tempfile.TemporaryDirectory() as build:
        for label, name, args, stdin, files, limit in CASES:
            events, code, final = observe(label, name, args, stdin, files, limit, build)
            limited = "" if limit is None else f", address space limited to {limit} bytes"
            argv = [name.encode()] + [a.encode() for a in args]
            lines.append(f"/-- `{name}` on stdin {stdin!r}, argv {[name] + args}, files {sorted(files)}{limited}. -/")
            lines.append(f"def {label}Stdin : List Byte := {lean_bytes(stdin)}")
            lines.append(f"def {label}Argv : List (List Byte) := [{', '.join(lean_bytes(a) for a in argv)}]")
            lines.append(f"def {label}Fs : Fs.FileSystem := {lean_fs(files)}")
            evs = ", ".join(f".{k} {fd} {b}" for (k, fd, b) in events)
            lines.append(f"def {label}Trace : List Event :=")
            lines.append(f"  [{evs}] ++ [.exitEv {code} {lean_fs(final)}]")
            lines.append("")
    lines += ["end Silmaril.Compile.Examples.LPS.Observed", ""]
    with open(out, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
