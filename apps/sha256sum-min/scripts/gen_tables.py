# Generates src/gen_tables.h: glibc strerror strings (via os.strerror on this
# host's glibc) and the GNU sha256sum 9.4 --help / --version texts captured from
# /usr/bin/sha256sum under env -i (C locale). Run: python3 -I gen_tables.py OUT
import os, subprocess, sys
out = sys.argv[1]
def cstr(b):
    s = '"'
    for c in b:
        if c == 0x22 or c == 0x5c: s += '\\' + chr(c)
        elif 0x20 <= c < 0x7f: s += chr(c)
        elif c == 10: s += '\\n"\n  "'
        else: s += '\\%03o' % c
    return s + '"'
lines = ['/* generated by scripts/gen_tables.py; do not edit */']
lines.append('static const char *const errtab[134] = {')
lines.append('  0,')
for i in range(1, 134):
    m = os.strerror(i)
    lines.append('  0,' if m == 'Unknown error %d' % i else '  %s,' % cstr(m.encode()))
lines.append('};')
P = b'@@PROG@@'
# argv0 replacement: run through bash exec -a
h = subprocess.run(['/bin/bash', '-c', 'exec -a "$0" /usr/bin/sha256sum --help', P.decode()], capture_output=True, check=True, env={}).stdout
parts = h.split(P)
assert len(parts) == 2, parts
lines.append('static const char help_pre[] = %s;' % cstr(parts[0]))
lines.append('static const char help_post[] = %s;' % cstr(parts[1]))
v = subprocess.run(['/usr/bin/sha256sum', '--version'], capture_output=True, check=True, env={}).stdout
lines.append('static const char version_text[] = %s;' % cstr(v))
open(out, 'w').write('\n'.join(lines) + '\n')
