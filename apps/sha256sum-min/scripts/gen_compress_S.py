# Emits an assembler file whose .text is the pilot's clang 18.1.3 -O2
# sha256_compress (tests/x86/sha256_compress_clang_O2.hex, 459 bytes) with its
# one R_X86_64_PC32 relocation (function offset 0xb7, addend -4, against K)
# re-expressed as an assembler expression, and whose .rodata is K (256 bytes,
# little-endian uint32, FIPS 180-4). Usage: python3 -I gen_compress_S.py HEX OUT
import hashlib, sys
raw = bytes.fromhex(''.join(open(sys.argv[1]).read().split()))
assert len(raw) == 459 and hashlib.sha256(raw).hexdigest() == 'b40a9bb4fe1c44697d153444180bf4e534b8c7b28b0ee5223f8c61fc66d07d44'
assert raw[0xb4:0xb7] == bytes([0x48, 0x8d, 0x0d]) and raw[0xb7:0xbb] == b'\0\0\0\0'
K = [0x428a2f98,0x71374491,0xb5c0fbcf,0xe9b5dba5,0x3956c25b,0x59f111f1,0x923f82a4,0xab1c5ed5,
0xd807aa98,0x12835b01,0x243185be,0x550c7dc3,0x72be5d74,0x80deb1fe,0x9bdc06a7,0xc19bf174,
0xe49b69c1,0xefbe4786,0x0fc19dc6,0x240ca1cc,0x2de92c6f,0x4a7484aa,0x5cb0a9dc,0x76f988da,
0x983e5152,0xa831c66d,0xb00327c8,0xbf597fc7,0xc6e00bf3,0xd5a79147,0x06ca6351,0x14292967,
0x27b70a85,0x2e1b2138,0x4d2c6dfc,0x53380d13,0x650a7354,0x766a0abb,0x81c2c92e,0x92722c85,
0xa2bfe8a1,0xa81a664b,0xc24b8b70,0xc76c51a3,0xd192e819,0xd6990624,0xf40e3585,0x106aa070,
0x19a4c116,0x1e376c08,0x2748774c,0x34b0bcb5,0x391c0cb3,0x4ed8aa4a,0x5b9cca4f,0x682e6ff3,
0x748f82ee,0x78a5636f,0x84c87814,0x8cc70208,0x90befffa,0xa4506ceb,0xbef9a3f7,0xc67178f2]
kb = b''.join(k.to_bytes(4, 'little') for k in K)
assert hashlib.sha256(kb).hexdigest() == '74ef7306e7452d6859b6463ce496b8df30925f69e1b2969e1f3f34bbc9c6af04'
def bytes_lines(b):
    return ['\t.byte ' + ','.join('0x%02x' % x for x in b[i:i+16]) for i in range(0, len(b), 16)]
o = ['/* generated by scripts/gen_compress_S.py from tests/x86/sha256_compress_clang_O2.hex',
     '   (silmaril origin/main); the pilot-proved clang 18.1.3 -O2 bytes. */',
     '\t.section .text.sha256_compress,"ax",@progbits', '\t.globl sha256_compress',
     '\t.type sha256_compress,@function', '\t.p2align 4', 'sha256_compress:']
o += bytes_lines(raw[:0xb7])
o.append('\t.long sha256_compress_K - (. + 4)')
o += bytes_lines(raw[0xbb:])
o += ['\t.size sha256_compress, .-sha256_compress',
      '\t.section .rodata.sha256_compress_K,"a",@progbits', '\t.p2align 4',
      '\t.type sha256_compress_K,@object', 'sha256_compress_K:']
o += bytes_lines(kb)
o += ['\t.size sha256_compress_K, 256', '\t.section .note.GNU-stack,"",@progbits', '']
open(sys.argv[2], 'w').write('\n'.join(o))
