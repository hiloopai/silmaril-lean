#!/usr/bin/env bash
# Regenerate the pinned runs of tests/seg-runs.txt: the random input with locals, the Binaryen
# outputs, the Lean modules tests/wasm/auto/ESeg/Tv*.lean, the corpus module
# tests/wasm/auto/ESeg/Corpus.lean, the pass-3 corpus module tests/wasm/auto/ESeg/SelectCorpus.lean
# (select, renumbered locals), the summary tests/seg-expected.txt and the per-function
# tables tests/tables/seg-*.md.
#
# Binaryen wasm-opt version_123 (skipped with a message when absent; the pinned outputs are
# kept), pinned with its SHA-256 in tools/wasm-tools/tests/pins.sh (install it with
# tools/wasm-tools/tests/fetch-pins.sh binaryen; $BINARYEN_WASM_OPT overrides the path, the hash
# is checked either way).
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
repo="$(cd "$here/../.." && pwd)"
cd "$here"
cargo build --offline --release --quiet
B="$here/target/release/wasm-egraph"
W_OVERRIDE="${BINARYEN_WASM_OPT:-}"
# shellcheck source=../../wasm-tools/tests/pins.sh
source "$repo/tools/wasm-tools/tests/pins.sh"
W="${W_OVERRIDE:-$BINARYEN_WASM_OPT}"
want=$BINARYEN_WASM_OPT_SHA256
have_w=0
if [[ -x $W ]] && [[ $(sha256sum "$W" | cut -d' ' -f1) == "$want" ]]; then have_w=1; else
  echo "gen-tv-seg: Binaryen wasm-opt version_123 (sha256 $want) not found at $W; keeping the pinned outputs"
fi
"$B" gen-random-locals 40 11 corpus/locals40.wasm
"$B" bench-seg corpus/locals.sexp --lean "$repo/tests/wasm/auto/ESeg/Corpus.lean" --module ESegCorpus \
  --table tests/tables/seg-corpus.md 2>/dev/null || true
sed -i 's|^Generated by .*|Generated by `tools/wasm-egraph` (`wasm-egraph bench-seg tools/wasm-egraph/corpus/locals.sexp`);|' \
  "$repo/tests/wasm/auto/ESeg/Corpus.lean"
# `select` and renumbered locals (Lean's Silmaril.Wasm.Auto.ESeg)
"$B" bench-seg corpus/select.sexp --lean "$repo/tests/wasm/auto/ESeg/SelectCorpus.lean" --module ESegSelectCorpus \
  --table tests/tables/segx-corpus.md 2>/dev/null || true
sed -i 's|^Generated by .*|Generated by `tools/wasm-egraph` (`wasm-egraph bench-seg tools/wasm-egraph/corpus/select.sexp`);|' \
  "$repo/tests/wasm/auto/ESeg/SelectCorpus.lean"
: > tests/seg-expected.txt
grep -v '^#' tests/seg-runs.txt | while read -r in flags out mod; do
  [[ -z $in ]] && continue
  if (( have_w )); then "$W" "corpus/$in" $flags -o "corpus/$out"; fi
  lean=(); [[ $mod != - ]] && lean=(--lean "$repo/tests/wasm/auto/ESeg/$mod.lean" --module "$mod")
  "$B" tv-seg "corpus/$in" "corpus/$out" "${lean[@]}" --table "tests/tables/seg-$out.md" 2>/dev/null || true
  [[ $mod != - ]] && sed -i "s|^Generated by .*|Generated by \`tools/wasm-egraph\` (\`wasm-egraph tv-seg\`, Binaryen \`$flags\` on \`$in\`);|" \
    "$repo/tests/wasm/auto/ESeg/$mod.lean"
  printf '%s %s %s\n' "$in" "$flags" "$(awk -F'|' 'NR>2{gsub(/ /,"",$3); print $3}' "tests/tables/seg-$out.md" | sort | uniq -c | tr -s ' ' | tr '\n' ' ')" >> tests/seg-expected.txt
done
cat tests/seg-expected.txt
