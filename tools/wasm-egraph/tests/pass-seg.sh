#!/usr/bin/env bash
# E-graph certificates with locals in `wasm-check pass` (docs/projects/wasm-binaryen-tooling.md).
#
#   tools/wasm-egraph/tests/pass-seg.sh [--certs] [--regen]
#
# 1. `wasm-egraph emit-seg corpus/pass-seg.sexp` rewrites the two pinned modules
#    corpus/pass-seg.{a,b}.wasm byte for byte (the `(mode func)` cases, export `f<k>`);
# 2. `wasm-egraph tv-seg --func` proves every pair from function entry and regenerates the
#    committed module tests/wasm/auto/ESeg/TvPassSeg.lean byte for byte;
# 3. `wasm-check pass A B --egraph-tv-seg tests/wasm/auto/ESeg/TvPassSeg.lean` gives the
#    expected summary (4 proved by its own stages, 1 unknown lifted from the e-graph
#    certificate; since the pass-3 integration the trapping body `f4` is proved by the front
#    track's trap-guard summaries, stage `equivx`, where the e-graph alone left it unknown;
#    `f1` (`divu-pow2-merged`: `rem_u 4` against `and 3`) is proved by stage `equivv`, so all 5
#    are proved without a segment lift);
# 4. with --certs, the written certificate is checked with `lake env lean` (needs
#    tests.wasm.auto.ESeg.TvPassSeg built).
#
# Step 3 and 4 are skipped with a message when the wasm-check executable is absent (the
# build command is $WT_BUILD_HINT of tools/wasm-tools/tests/pins.sh). --regen rewrites the pinned files instead of
# comparing them. Exit status 0 when everything matches (or is skipped), 1 otherwise.
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
repo="$(cd "$here/../.." && pwd)"
certs=0
regen=0
for a in "$@"; do
  case $a in
    --certs) certs=1 ;;
    --regen) regen=1 ;;
    *) echo "usage: $0 [--certs] [--regen]" >&2; exit 2 ;;
  esac
done
# shellcheck source=../../wasm-tools/tests/pins.sh
source "$repo/tools/wasm-tools/tests/pins.sh"
cd "$here"
cargo build --offline --release --quiet
B="$here/target/release/wasm-egraph"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
mod="$repo/tests/wasm/auto/ESeg/TvPassSeg.lean"
if (( regen )); then
  "$B" emit-seg corpus/pass-seg.sexp corpus/pass-seg.a.wasm corpus/pass-seg.b.wasm
  "$B" tv-seg corpus/pass-seg.a.wasm corpus/pass-seg.b.wasm --func --lean "$mod" --module TvPassSeg \
    --table tests/tables/pass-seg.md 2>/dev/null
  sed -i 's|^Generated by .*|Generated by `tools/wasm-egraph` (`wasm-egraph tv-seg --func` on `corpus/pass-seg.{a,b}.wasm`);|' "$mod"
  echo "regenerated"
  exit 0
fi
"$B" emit-seg corpus/pass-seg.sexp "$tmp/a.wasm" "$tmp/b.wasm"
cmp corpus/pass-seg.a.wasm "$tmp/a.wasm" && cmp corpus/pass-seg.b.wasm "$tmp/b.wasm" \
  || { echo "FAIL: corpus/pass-seg.{a,b}.wasm are stale (pass-seg.sh --regen)"; exit 1; }
"$B" tv-seg corpus/pass-seg.a.wasm corpus/pass-seg.b.wasm --func --lean "$tmp/TvPassSeg.lean" \
  --module TvPassSeg --table "$tmp/pass-seg.md" 2>/dev/null \
  || { echo "FAIL: tv-seg --func did not prove every pair"; exit 1; }
sed -i 's|^Generated by .*|Generated by `tools/wasm-egraph` (`wasm-egraph tv-seg --func` on `corpus/pass-seg.{a,b}.wasm`);|' "$tmp/TvPassSeg.lean"
diff -u "$mod" "$tmp/TvPassSeg.lean" || { echo "FAIL: $mod is stale (pass-seg.sh --regen)"; exit 1; }
echo "tv-seg --func: $(grep -c '| proved |' "$tmp/pass-seg.md") of $(grep -c '^| `' "$tmp/pass-seg.md") pairs proved"
exe="${SIL_WASM_CHECK:-$repo/.lake/build/bin/wasm-check}"
wt_require_ours "$exe" wasm-check
cd "$repo"
"$exe" pass tools/wasm-egraph/corpus/pass-seg.a.wasm tools/wasm-egraph/corpus/pass-seg.b.wasm \
  --egraph-tv-seg tests/wasm/auto/ESeg/TvPassSeg.lean --lean "$tmp/PassSeg.lean" > "$tmp/pass.json"
summary=$(grep '"summary"' "$tmp/pass.json")
echo "$summary"
want='"exports":5,"proved":5,"refuted":0,"unknown":0,"egraphLifts":0,"egraphSegLifts":0'
[[ $summary == *"$want"* ]] || { echo "FAIL: expected $want"; exit 1; }
if (( certs )); then
  timer=()
  if [[ -x /usr/bin/time ]]; then timer=(/usr/bin/time -f '%e s, %M KiB'); fi
  "${timer[@]}" lake env lean "$tmp/PassSeg.lean" || { echo "FAIL: certificate"; exit 1; }
  echo "certificate checked"
fi
echo "pass-seg: ok"
