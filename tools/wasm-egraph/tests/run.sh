#!/usr/bin/env bash
# Regression test of tools/wasm-egraph: unit tests, the pinned corpus, and the rule text
# shared with Lean. Needs only cargo (offline). The Lean side is checked by building
# tests.wasm.auto.EGraph.Corpus and tests.wasm.auto.Rules.Tests (lean_lib WasmAutoTests).
set -euo pipefail
here="$(cd "$(dirname "$0")/.." && pwd)"
repo="$(cd "$here/../.." && pwd)"
cd "$here"
cargo test --offline --quiet
cargo build --offline --release --quiet
bin="$here/target/release/wasm-egraph"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

# 1. The corpus: every case meets its expectation, and the generated Lean module is the
#    committed one (certificates are deterministic).
"$bin" bench corpus/regression.sexp --lean "$tmp/Corpus.lean" --module Corpus \
  --table "$tmp/table.md" 2>"$tmp/log" || { cat "$tmp/log"; echo "FAIL: corpus expectations"; exit 1; }
sed -i 's|^Generated by .*|Generated by `tools/wasm-egraph` (`wasm-egraph bench tools/wasm-egraph/corpus/regression.sexp`); do not edit. Every|' "$tmp/Corpus.lean"
diff -u "$repo/tests/wasm/auto/EGraph/Corpus.lean" "$tmp/Corpus.lean" \
  || { echo "FAIL: tests/wasm/auto/EGraph/Corpus.lean is stale (regenerate with gen-corpus.sh)"; exit 1; }

# 2. Translation validation of the pinned optimizer runs (inputs and outputs are committed
#    under corpus/; tests/gen-tv.sh regenerates them with the pinned optimizers).
tv() { # IN OUT MODULE [--names CORPUS]
  local in=$1 out=$2 mod=$3; shift 3
  "$bin" tv "corpus/$in" "corpus/$out" "$@" --lean "$tmp/$mod.lean" --module "$mod" \
    --table "$tmp/$mod.md" >/dev/null || true
  diff -u "$repo/tests/wasm/auto/EGraph/$mod.lean" "$tmp/$mod.lean" \
    || { echo "FAIL: tests/wasm/auto/EGraph/$mod.lean is stale (regenerate with gen-tv.sh)"; exit 1; }
}
tv opt-in.wasm opt-in.binaryen-O2.wasm TvBinaryen --names corpus/regression.sexp
tv opt-in.wasm opt-in.peep.wasm TvPeep --names corpus/regression.sexp
tv rand60.wasm rand60.binaryen-O3.wasm TvRandom

# 3. Code with locals (effect summaries): the corpus and the pinned Binaryen runs of
#    tests/seg-runs.txt regenerate the committed Lean modules and the summary
#    tests/seg-expected.txt (tests/gen-tv-seg.sh regenerates them with the pinned Binaryen).
"$bin" bench-seg corpus/locals.sexp --lean "$tmp/ESegCorpus.lean" --module ESegCorpus \
  --table "$tmp/seg-corpus.md" 2>"$tmp/seglog" || { cat "$tmp/seglog"; echo "FAIL: locals corpus expectations"; exit 1; }
sed -i 's|^Generated by .*|Generated by `tools/wasm-egraph` (`wasm-egraph bench-seg tools/wasm-egraph/corpus/locals.sexp`);|' "$tmp/ESegCorpus.lean"
diff -u "$repo/tests/wasm/auto/ESeg/Corpus.lean" "$tmp/ESegCorpus.lean" \
  || { echo "FAIL: tests/wasm/auto/ESeg/Corpus.lean is stale (regenerate with gen-tv-seg.sh)"; exit 1; }
# `select` and renumbered locals (Lean's Silmaril.Wasm.Auto.ESeg)
"$bin" bench-seg corpus/select.sexp --lean "$tmp/ESegSelectCorpus.lean" --module ESegSelectCorpus \
  --table "$tmp/segx-corpus.md" 2>"$tmp/segxlog" || { cat "$tmp/segxlog"; echo "FAIL: select corpus expectations"; exit 1; }
sed -i 's|^Generated by .*|Generated by `tools/wasm-egraph` (`wasm-egraph bench-seg tools/wasm-egraph/corpus/select.sexp`);|' "$tmp/ESegSelectCorpus.lean"
diff -u "$repo/tests/wasm/auto/ESeg/SelectCorpus.lean" "$tmp/ESegSelectCorpus.lean" \
  || { echo "FAIL: tests/wasm/auto/ESeg/SelectCorpus.lean is stale (regenerate with gen-tv-seg.sh)"; exit 1; }
: > "$tmp/seg-expected.txt"
while read -r in flags out mod; do
  [[ -z $in || $in == \#* ]] && continue
  lean=(); [[ $mod != - ]] && lean=(--lean "$tmp/$mod.lean" --module "$mod")
  "$bin" tv-seg "corpus/$in" "corpus/$out" "${lean[@]}" --table "$tmp/seg-$out.md" 2>/dev/null || true
  if [[ $mod != - ]]; then
    sed -i "s|^Generated by .*|Generated by \`tools/wasm-egraph\` (\`wasm-egraph tv-seg\`, Binaryen \`$flags\` on \`$in\`);|" "$tmp/$mod.lean"
    diff -u "$repo/tests/wasm/auto/ESeg/$mod.lean" "$tmp/$mod.lean" \
      || { echo "FAIL: tests/wasm/auto/ESeg/$mod.lean is stale (regenerate with gen-tv-seg.sh)"; exit 1; }
  fi
  printf '%s %s %s\n' "$in" "$flags" "$(awk -F'|' 'NR>2{gsub(/ /,"",$3); print $3}' "$tmp/seg-$out.md" | sort | uniq -c | tr -s ' ' | tr '\n' ' ')" >> "$tmp/seg-expected.txt"
done < tests/seg-runs.txt
diff -u tests/seg-expected.txt "$tmp/seg-expected.txt" || { echo "FAIL: tv-seg results changed"; exit 1; }

# 4. The rule library text agrees with Lean's `tests.wasm.auto.Rules.Tests.expected`.
"$bin" rules | sed 's/^[0-9]* //' > "$tmp/rules.txt"
grep -o '^  "[^"]*"' "$repo/tests/wasm/auto/Rules/Tests.lean" | sed 's/^  "//; s/"$//' > "$tmp/lean-rules.txt"
diff -u "$tmp/lean-rules.txt" "$tmp/rules.txt" || { echo "FAIL: rule library out of sync"; exit 1; }

echo "wasm-egraph: unit tests, corpus ($(grep -c '^| `' "$tmp/table.md") cases), translation validation ($(cat "$tmp"/Tv*.md | grep -c '| proved |') of $(cat "$tmp"/Tv*.md | grep -c '^| `') functions proved), locals corpus ($(grep -c '^| `' "$tmp/seg-corpus.md") cases), select and renumbered-locals corpus ($(grep -c '^| `' "$tmp/segx-corpus.md") cases), tv-seg ($(cat "$tmp"/seg-*.wasm.md | grep -c '| proved |') of $(cat "$tmp"/seg-*.wasm.md | grep -c '^| `') functions proved in $(grep -c . tests/seg-expected.txt) runs) and rule sync: ok"
