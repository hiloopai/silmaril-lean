//! The Lean data module (`Silmaril/X86/MemoryModel/Litmus/Corpus/Defs.lean`).

use std::fmt::Write as _;

use crate::asm::Assembled;
use crate::checker::Verdict;
use crate::insn::{EvKind, Fence, GPR64, MemEv};
use crate::litmus::Error;
use crate::litmus::Quant;
use crate::model::{Atom, Cond, Model};

/// Coverage class of a test (corpus index column 2).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Coverage {
    Tso,
    Xl,
}

/// Everything the emitter needs about one test.
pub struct Entry {
    pub path: String,
    pub model: Model,
    pub code: Assembled,
    pub coverage: Coverage,
    pub tso: Option<Verdict>,
    pub xl: Verdict,
    pub sc: Option<Verdict>,
    pub basis: String,
}

fn lean_str(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            c if c.is_ascii() && !c.is_ascii_control() => o.push(c),
            c => {
                let _ = write!(o, "\\u{{{:x}}}", c as u32);
            }
        }
    }
    o.push('"');
    o
}

fn verdict(v: Verdict) -> &'static str {
    match v {
        Verdict::Allowed => ".allowed",
        Verdict::Forbidden => ".forbidden",
    }
}

fn opt_verdict(v: Option<Verdict>) -> String {
    match v {
        Some(v) => format!("some {}", verdict(v)),
        None => "none".into(),
    }
}

fn cond(c: &Cond) -> String {
    match c {
        Cond::True => ".tt".into(),
        Cond::Not(a) => format!(".not ({})", cond(a)),
        Cond::And(a, b) => format!(".and ({}) ({})", cond(a), cond(b)),
        Cond::Or(a, b) => format!(".or ({}) ({})", cond(a), cond(b)),
        Cond::Atom(Atom::Reg {
            thread,
            reg,
            bits,
            value,
        }) => {
            format!(
                ".atom (.reg {thread} .{} {bits} 0x{value:x})",
                GPR64[*reg as usize]
            )
        }
        Cond::Atom(Atom::Mem { addr, size, value }) => {
            format!(".atom (.mem 0x{addr:x} {size} 0x{value:x})")
        }
    }
}

fn event(e: &MemEv) -> String {
    let k = match e.kind {
        EvKind::Load => ".load",
        EvKind::Store => ".store",
        EvKind::Rmw => ".rmw",
        EvKind::Fence(Fence::M) => "(.fence .mfence)",
        EvKind::Fence(Fence::L) => "(.fence .lfence)",
        EvKind::Fence(Fence::S) => "(.fence .sfence)",
    };
    format!("⟨{k}, 0x{:x}, {}, {}⟩", e.addr, e.size, e.locked)
}

/// An instruction's recorded events: `some [..]`, or `none` without a `MemEvent` form.
fn events(es: Option<&[MemEv]>) -> String {
    match es {
        None => "none".into(),
        Some(es) => {
            let v: Vec<String> = es.iter().map(event).collect();
            format!("some [{}]", v.join(", "))
        }
    }
}

/// The Lean identifier of a test.
pub fn ident(name: &str) -> String {
    format!("«{name}»")
}

/// Render the module.
pub fn render(entries: &[Entry], provenance: &[String]) -> Result<String, Error> {
    let mut s = String::new();
    s.push_str("module\n\npublic import Silmaril.X86.MemoryModel.Litmus.Defs\n\n");
    s.push_str("/-!\n# The x86 litmus corpus (generated)\n\n");
    s.push_str(
        "GENERATED by `tools/litmus-x86` (`cargo run --release -- generate`); do not edit.\n",
    );
    s.push_str("`cargo run --release -- --check` regenerates it and compares byte for byte.\n\n");
    for p in provenance {
        let _ = writeln!(s, "* {p}");
    }
    s.push_str(
        "\nPer test: the source file, the fixed location layout, each thread's instructions with \
         the bytes GNU `as` produced for them and the memory events the tool's checker reads them \
         as (`none` for forms with no `MemEvent` counterpart), the initial registers, the final condition \
         resolved to System V registers and absolute addresses, and the verdicts. See \
         `Silmaril.X86.MemoryModel.Litmus.Test` for the meaning of each field and \
         `tools/litmus-x86/README.md` for the verdict provenance.\n-/\n\n",
    );
    s.push_str("@[expose] public section\n\nnamespace Silmaril.X86.MemoryModel.Litmus.Corpus\n\n");
    s.push_str("open Silmaril.X86.MemoryModel.Litmus\n\nset_option maxRecDepth 4096\n\n");
    for e in entries {
        let m = &e.model;
        let _ = writeln!(s, "/-- `{}` ({}). -/", m.name, e.path);
        let _ = writeln!(s, "def {} : Test where", ident(&m.name));
        let _ = writeln!(s, "  name := {}", lean_str(&m.name));
        let _ = writeln!(s, "  source := {}", lean_str(&e.path));
        let _ = writeln!(s, "  doc := {}", lean_str(m.doc.as_deref().unwrap_or("")));
        s.push_str("  locs := [");
        for (i, l) in m.locs.iter().enumerate() {
            if i > 0 {
                s.push_str(", ");
            }
            let _ = write!(
                s,
                "⟨{}, 0x{:x}, {}, 0x{:x}⟩",
                lean_str(&l.name),
                l.addr,
                l.size,
                l.init
            );
        }
        s.push_str("]\n  threads := [");
        let addrs = m.addrs();
        for (t, ((insns, regs), code)) in m.threads.iter().zip(&e.code).enumerate() {
            s.push_str(if t == 0 { "\n" } else { ",\n" });
            s.push_str("    { insns := [");
            if insns.len() != code.len() {
                return Err(Error(format!(
                    "{}: thread {t}: code length mismatch",
                    m.name
                )));
            }
            for (k, (ins, (g, bytes))) in insns.iter().zip(code).enumerate() {
                s.push_str(if k == 0 { "\n" } else { ",\n" });
                let bs: Vec<String> = bytes.iter().map(|b| format!("0x{b:02x}")).collect();
                let _ = write!(
                    s,
                    "        ⟨{}, [{}], {}⟩",
                    lean_str(g),
                    bs.join(", "),
                    events(ins.events(&addrs)?.as_deref())
                );
            }
            s.push_str("]\n      regs := [");
            for (k, (r, v)) in regs.iter().enumerate() {
                if k > 0 {
                    s.push_str(", ");
                }
                let _ = write!(s, "(.{}, 0x{v:x})", GPR64[*r as usize]);
            }
            s.push_str("] }");
        }
        s.push_str("]\n");
        let q = match m.quant {
            Quant::Exists => ".exists_",
            Quant::NotExists => ".notExists",
            Quant::Forall => ".forall_",
        };
        let _ = writeln!(s, "  quant := {q}");
        let _ = writeln!(s, "  cond := {}", cond(&m.cond));
        let cov = match e.coverage {
            Coverage::Tso => ".tso",
            Coverage::Xl => ".xl",
        };
        let _ = writeln!(s, "  coverage := {cov}");
        let _ = writeln!(s, "  tso := {}", opt_verdict(e.tso));
        let _ = writeln!(s, "  xl := {}", verdict(e.xl));
        let _ = writeln!(s, "  sc := {}", opt_verdict(e.sc));
        let _ = writeln!(s, "  basis := {}\n", lean_str(&e.basis));
    }
    s.push_str("/-- The whole corpus, in index order. -/\ndef all : List Test := [");
    for (i, e) in entries.iter().enumerate() {
        s.push_str(if i == 0 { "\n  " } else { ",\n  " });
        s.push_str(&ident(&e.model.name));
    }
    s.push_str("]\n\nend Silmaril.X86.MemoryModel.Litmus.Corpus\n");
    Ok(s)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn strings_and_conditions() {
        assert_eq!(lean_str("a\"b\\c"), "\"a\\\"b\\\\c\"");
        let c = Cond::And(
            Box::new(Cond::Atom(Atom::Reg {
                thread: 1,
                reg: 3,
                bits: 32,
                value: 0,
            })),
            Box::new(Cond::Not(Box::new(Cond::Atom(Atom::Mem {
                addr: 0x10000,
                size: 4,
                value: 2,
            })))),
        );
        assert_eq!(
            cond(&c),
            ".and (.atom (.reg 1 .rbx 32 0x0)) (.not (.atom (.mem 0x10000 4 0x2)))"
        );
        assert_eq!(ident("SB+mfences"), "«SB+mfences»");
    }
}
