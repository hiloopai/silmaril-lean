//! Lean, records and report emission.
//!
//! The Lean header states facts the kernel checks at build time (the object's bytes, the
//! decoder's listing, the C ↔ Core point locators) and the goals as `def Task.… : Prop`
//! (rows of the `silmaril.shapes.c.*` shapes). It never states a goal for a segment the
//! correspondence marked unsupported.

use std::fmt::Write as _;

use crate::corr::{FnCorr, PointKind};

/// One compilation of the C file (an optimisation level).
pub struct Build {
    /// `O0`, `O2`, …
    pub tag: String,
    pub obj_bytes: Vec<u8>,
    pub obj_path: String,
    pub obj_sha256: String,
    pub text: Vec<u8>,
    pub fns: Vec<FnCorr>,
    /// Lean listing per function: `(offset, instr term, length, asm)`.
    pub listings: Vec<Vec<(u64, String, u64, String)>>,
    pub flags: Vec<String>,
}

pub struct Header<'a> {
    pub module: String,
    pub c_path: String,
    pub c_text: &'a str,
    pub ail_text: Option<String>,
    pub core_doc: Option<String>,
    pub core_error: Option<String>,
    pub compiler: String,
    pub image: String,
    pub base: u64,
    pub builds: Vec<Build>,
    pub tool_rev: String,
}

pub fn lean_string(s: &str) -> String {
    let mut o = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => o.push_str("\\\""),
            '\\' => o.push_str("\\\\"),
            '\n' => o.push_str("\\n"),
            '\t' => o.push_str("\\t"),
            c => o.push(c),
        }
    }
    o.push('"');
    o
}

fn bytes_lit(bs: &[u8]) -> String {
    let mut o = String::from("[");
    for (i, b) in bs.iter().enumerate() {
        if i > 0 {
            o.push_str(if i % 16 == 0 { ",\n    " } else { ", " });
        }
        let _ = write!(o, "0x{b:02x}");
    }
    o.push(']');
    o
}

fn blob_lit(bs: &[u8]) -> String {
    // little-endian Nat
    let mut hex = String::new();
    for b in bs.iter().rev() {
        let _ = write!(hex, "{b:02x}");
    }
    let hex = hex.trim_start_matches('0');
    format!(
        "⟨0x{}, {}⟩",
        if hex.is_empty() { "0" } else { hex },
        bs.len()
    )
}

pub fn camel(s: &str) -> String {
    let mut o = String::new();
    let mut up = true;
    for c in s.chars() {
        if c == '_' || c == '-' {
            up = true;
        } else if up {
            o.extend(c.to_uppercase());
            up = false;
        } else {
            o.push(c);
        }
    }
    o
}

fn scalar_term(s: &str) -> String {
    format!(".{s}")
}

/// The Lean library the examples belong to (`lakefile.toml`, source directory
/// [`LIB_DIR`]).
pub const LIB: &str = "CompilesToExamples";
/// The source directory of [`LIB`], relative to `--root`.
pub const LIB_DIR: &str = "examples/compiles-to";

/// The functions of the file that have goals in some build, in order, with their signature.
fn goal_functions<'b>(h: &'b Header) -> Vec<(&'b str, &'b (Vec<&'static str>, &'static str))> {
    let mut out: Vec<(&str, &(Vec<&'static str>, &'static str))> = Vec::new();
    if h.core_doc.is_none() {
        return out;
    }
    for b in &h.builds {
        for f in &b.fns {
            if f.function_unsupported.is_none()
                && !out.iter().any(|(n, _)| *n == f.name)
                && let Some(sig) = &f.sig
            {
                out.push((&f.name, sig));
            }
        }
    }
    out
}

fn sig_term(sig: &(Vec<&str>, &str)) -> String {
    format!(
        "⟨[{}], some {}⟩",
        sig.0
            .iter()
            .map(|s| scalar_term(s))
            .collect::<Vec<_>>()
            .join(", "),
        scalar_term(sig.1)
    )
}

pub fn header(h: &Header) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "module\n");
    let _ = writeln!(
        o,
        "-- GENERATED by tools/c-tv ({}). Do not edit by hand; regenerate with",
        h.tool_rev
    );
    let _ = writeln!(o, "--   tools/c-tv/regen.sh");
    let _ = writeln!(o, "-- source:   {}", h.c_path);
    let _ = writeln!(o, "-- compiler: {} ({})", h.compiler, h.image);
    for b in &h.builds {
        let _ = writeln!(
            o,
            "-- {}: {} sha256 {} flags {}",
            b.tag,
            b.obj_path,
            b.obj_sha256,
            b.flags.join(" ")
        );
    }
    o.push('\n');
    o.push_str("public import Silmaril.Project.Shapes.CompilesTo.Defs\n");
    o.push_str("public import Silmaril.Project.Shapes.SysV.Thms\n");
    o.push_str("public import Silmaril.Cerberus.Core.Quote.Defs\n");
    o.push_str("public import Silmaril.Cerberus.Ail.Quote.Defs\n");
    o.push_str("public import Silmaril.X86.Lift.Transcript\n");
    o.push_str("public meta import Silmaril.Project.CompilesTo.Probe.Defs\n\n");
    let _ = writeln!(
        o,
        "/-!\n# `{}`: compiler-explorer correspondences as Lean goals\n",
        h.c_path
    );
    let _ = writeln!(
        o,
        "The C file compiled by {} at {} (`{}`), its typed Ail and Cerberus Core from the Lean\n\
         port (`Silmaril.Project.Shapes.C.FrontendAil`, `ElabAil`), and for every function its\n\
         Core (`CFn`) and, per build, its correspondence `FnData`: the bytes, the program points\n\
         and the boundary relations read from DWARF. Generated by `tools/c-tv`;\n\
         `docs/projects/compiles-to.md` explains the statements.\n",
        h.compiler,
        h.builds
            .iter()
            .map(|b| b.tag.as_str())
            .collect::<Vec<_>>()
            .join(", "),
        h.image
    );
    o.push_str("Checked here (by the kernel unless noted): the object's code for each function\n");
    o.push_str(
        "(`SysV.objectCodeN`, `decide +kernel`), the decoder's listing (`decodesAs`), each point's\n",
    );
    o.push_str(
        "Core fragment (`StmtAt`/`RetAt`, `rfl`), and, by compiled evaluation only (`#guard`), that\n",
    );
    o.push_str("the frontend gives the quoted typed Ail (its typing pass is `partial`).\n\n");
    o.push_str(
        "Goals (`def Task.… : Prop`): per function, C ↔ Core (`c.elaborates_to`), its safety\n",
    );
    o.push_str(
        "on some argument tuple from every entry (`_safe`, which `c.compiles_to` needs) and from\n",
    );
    o.push_str(
        "its canonical entry (`_canonical_safe`), and every build (`c.compiles_to.builds`); per\n",
    );
    o.push_str("build, each segment (`c.compiles_to.segment`, and from C), the function\n");
    o.push_str(
        "(`c.compiles_to`) and its canonical-entry reading (`c.compiles_to.canonical_entry`).\n\n",
    );
    o.push_str("## Goals\n\n| build | function | granularity | segments | unsupported |\n|---|---|---|---|---|\n");
    for b in &h.builds {
        for f in &b.fns {
            let segs = if f.function_unsupported.is_some() {
                0
            } else {
                f.points.len()
            };
            let _ = writeln!(
                o,
                "| {} | `{}` | {} | {} | {} |",
                b.tag,
                f.name,
                f.granularity,
                segs,
                f.unsupported.len()
            );
        }
    }
    o.push_str("-/\n\n");
    let ns = &h.module;
    let _ = writeln!(o, "namespace {ns}\n");
    o.push_str("open Silmaril.Project.CompilesTo\nopen Silmaril.Project.Shapes.CompilesTo\nopen Silmaril.Project.Shapes.C (CFn ElaboratesTo FrontendAil)\nopen Silmaril.X86.Ext (Mem)\nopen Silmaril.X86.Lift\n\n");
    o.push_str("@[expose] public section\n\n");
    let _ = writeln!(
        o,
        "/-- The C source, verbatim. -/\ndef cText : String :=\n  {}\n",
        lean_string(h.c_text)
    );
    let have_core = h.ail_text.is_some() && h.core_doc.is_some();
    if let Some(ail) = &h.ail_text {
        let _ = writeln!(
            o,
            "set_option maxRecDepth 100000 in\n/-- Its typed Ail (the Lean Cerberus frontend's output, quoted). -/\ndef ail : Silmaril.Cerberus.Ail.TypedProgram := ail_program% {}\n",
            lean_string(ail)
        );
        o.push_str("-- C → typed Ail: the frontend, run by compiled evaluation (its typing pass is `partial`,\n-- so no kernel theorem can state it), gives exactly the quoted `ail`.\n");
        o.push_str(
            "#guard (FrontendAil cText).toOption.map Silmaril.Project.CompilesTo.Probe.ailText ==\n  some (Silmaril.Project.CompilesTo.Probe.ailText ail)\n\n",
        );
    }
    if let Some(doc) = &h.core_doc {
        let _ = writeln!(
            o,
            "set_option maxRecDepth 100000 in\n/-- Its Cerberus Core (`ElabAil ail`), quoted from the probe's document. -/\ndef doc : Silmaril.Cerberus.Codec.Document := core_document% {}\n",
            lean_string(doc)
        );
        o.push_str("/-- The quoted Core with the return labels named as the elaborator names them\n(`fixRet`); `Task.elaborates_*` states that it is `ElabAil ail`. -/\ndef core : Silmaril.Cerberus.Codec.FileBindings := fixRet doc.bindings\n\n");
    }
    if let Some(e) = &h.core_error {
        let _ = writeln!(o, "/-! C → Core failed: {} -/\n", e.replace("-/", "- /"));
    }
    // The C side of every function, shared by the builds.
    for (n, sig) in goal_functions(h) {
        let _ = writeln!(o, "/-! ## `{n}` -/\n");
        let _ = writeln!(
            o,
            "/-- `{n}` as Cerberus Core: the procedure `{n}` of `core`. -/\ndef {n}Fn : CFn {} where\n  file := core.toFile\n  params := paramsOf core {}\n  body := (procParts core {}).2\n",
            sig_term(sig),
            lean_string(n),
            lean_string(n)
        );
        let _ = writeln!(
            o,
            "/-- **C ↔ Core** for `{n}`: the elaborator takes `ail` to `{n}Fn`. -/\ndef Task.elaborates_{n} : Prop := ElaboratesTo ail {} {n}Fn\n",
            lean_string(n)
        );
        let _ = writeln!(
            o,
            "/-- **`{n}` is safe** on some argument tuple, from every Core entry (the non-vacuity of\n`c.compiles_to`). -/\ndef Task.{n}_safe : Prop := {n}Fn.meaning.Inhabited\n"
        );
        let _ = writeln!(
            o,
            "/-- **`{n}` is safe from its canonical entry** on some argument tuple (the non-vacuity\nof `c.compiles_to.canonical_entry`). -/\ndef Task.{n}_canonical_safe : Prop :=\n  ∃ a, ({n}Fn.source []).Safe ({n}Fn.canonicalEntry a)\n"
        );
    }
    for b in &h.builds {
        let _ = writeln!(
            o,
            "/-! ## Build `{}`: `{}` -/\n\nnamespace {}\n",
            b.tag,
            b.flags.join(" "),
            b.tag
        );
        let _ = writeln!(
            o,
            "/-- `{}` (sha256 `{}`), as a `Blob`. -/\ndef objBlob : Silmaril.X86.Link.Blob :=\n  {}\n",
            b.obj_path,
            b.obj_sha256,
            blob_lit(&b.obj_bytes)
        );
        for (fi, f) in b.fns.iter().enumerate() {
            let code = &b.text[f.off as usize..(f.off + f.size) as usize];
            let n = &f.name;
            let addr = h.base + f.off;
            let _ = writeln!(o, "/-! ### `{n}` -/\n");
            let _ = writeln!(
                o,
                "/-- `{n}`'s bytes: `.text` `[{:#x}, {:#x})`, placed at `{addr:#x}` in the goals. -/\ndef {n}Code : List (BitVec 8) :=\n  {}\n",
                f.off,
                f.off + f.size,
                bytes_lit(code)
            );
            let _ = writeln!(
                o,
                "/-- The object's `.text` holds them at the symbol `{n}`, with no relocation. -/\ntheorem {n}_code : Silmaril.Project.Shapes.SysV.objectCodeN objBlob {} {} {n}Code = true := by\n  decide +kernel\n",
                lean_string(n),
                f.off
            );
            let listing = &b.listings[fi];
            if !listing.is_empty() {
                let _ = writeln!(
                    o,
                    "/-- The model's decoder (`Ext.decode`) reads these instructions. -/\ndef {n}Listing : List (Nat × Silmaril.X86.Ext.Instr × Nat) := ["
                );
                for (i, (off, term, len, asm)) in listing.iter().enumerate() {
                    let sep = if i + 1 == listing.len() { "" } else { "," };
                    let _ = writeln!(o, "    ({off:#x}, {term}, {len}){sep}  -- {asm}");
                }
                o.push_str("  ]\n\n");
                let _ = writeln!(
                    o,
                    "theorem {n}_decodes : decodesAs {n}Code 0 {n}Listing = true := by decide +kernel\n"
                );
            }
            if f.function_unsupported.is_some() || !have_core {
                let _ = writeln!(
                    o,
                    "/-! `{n}`: no goals: {} -/\n",
                    f.function_unsupported
                        .clone()
                        .unwrap_or("no Core".into())
                        .replace("-/", "- /")
                );
                continue;
            }
            let sig = f.sig.clone().unwrap();
            let _ = writeln!(
                o,
                "/-- `{n}`: its Core, its bytes at `{addr:#x}`, its {} program points ({} granularity). -/\ndef {n} : FnData where",
                f.points.len(),
                f.granularity
            );
            let _ = writeln!(o, "  sig := {}", sig_term(&sig));
            let _ = writeln!(o, "  cfn := {n}Fn");
            let _ = writeln!(o, "  addr := {addr:#x}");
            let _ = writeln!(o, "  code := {n}Code");
            let _ = writeln!(o, "  frame := {}", f.frame);
            o.push_str("  points := [\n");
            let body = format!("(procParts core {}).2", lean_string(n));
            for (i, p) in f.points.iter().enumerate() {
                let sep = if i + 1 == f.points.len() { "" } else { "," };
                let (frag, kind) = match &p.kind {
                    PointKind::Entry => (body.clone(), ".entry".to_string()),
                    PointKind::Ret => {
                        (format!("retFrag {body}"), format!(".ret (retParam {body})"))
                    }
                    PointKind::Slots(objs) => {
                        let objs: Vec<String> = objs
                            .iter()
                            .map(|s| {
                                format!(
                                    "{{ name := {}, sym := {}, ty := {}, kind := {}, off := {}, size := {}, defined := {} }}",
                                    lean_string(&s.name),
                                    s.sym.as_ref().unwrap().lean(),
                                    if s.signed { "intTy" } else { "uintTy" },
                                    if s.signed { ".int32" } else { ".uint32" },
                                    s.off,
                                    s.size,
                                    s.defined
                                )
                            })
                            .collect();
                        (
                            format!("stmtFrag {body} {}", p.line),
                            format!(
                                ".slots (stmtCont {body} {}) [\n        {}]",
                                p.line,
                                objs.join(",\n        ")
                            ),
                        )
                    }
                };
                let _ = writeln!(
                    o,
                    "    -- point {i}: line {}, {addr:#x} + {:#x}",
                    p.line, p.off
                );
                let _ = writeln!(o, "    ⟨{frag}, {:#x}, {kind}⟩{sep}", p.off);
            }
            o.push_str("  ]\n\n");
            let _ = writeln!(
                o,
                "/-- `{n}` placed at `{addr:#x}`, entered at its first byte. -/\ndef {n}Placement : Silmaril.Project.Shapes.Placement := {n}.placement\n"
            );
            let _ = writeln!(
                o,
                "/-- The build of `{n}`: the compiler and flags, the placement, the stack it may write. -/\ndef {n}Build : Silmaril.Project.Shapes.C.Build :=\n  ⟨{}, {n}Placement, {}⟩\n",
                lean_string(&format!("{} {}", h.compiler, b.flags.join(" "))),
                f.frame
            );
            // C ↔ Core point facts (checked).
            for (i, p) in f.points.iter().enumerate() {
                let _ = writeln!(
                    o,
                    "/-- Point {i} of `{n}` is the Core of line {} (C ↔ Core, segment). -/",
                    p.line
                );
                let proof = match p.kind {
                    PointKind::Ret => "⟨_, rfl, _, rfl⟩",
                    PointKind::Slots(_) => "⟨_, rfl, rfl, rfl⟩",
                    PointKind::Entry => "⟨_, rfl, rfl⟩",
                };
                let _ = writeln!(
                    o,
                    "theorem {n}_point_{i} : PointOf {n} {i} {} := {proof}\n",
                    p.line
                );
            }
            // Goals.
            for (i, p) in f.points.iter().enumerate() {
                let _ = writeln!(
                    o,
                    "/-- **Core ↔ x86**, segment {i} of `{n}` (line {}, from `{addr:#x} + {:#x}`). -/\ndef Task.{n}_seg_{i} : Prop := SegmentSim Silmaril.X86.Open.isa {n} {i}\n",
                    p.line, p.off
                );
                let _ = writeln!(
                    o,
                    "/-- **C ↔ x86**, segment {i} of `{n}` (line {}). -/\ndef Task.{n}_seg_{i}_from_c : Prop :=\n  SegmentFromC Silmaril.X86.Open.isa ail {} {n} {i} {}\n",
                    p.line,
                    lean_string(n),
                    p.line
                );
            }
            let _ = writeln!(
                o,
                "/-- **`{n}` compiles to `{n}Code`** at `{}` (`c.compiles_to` on `Open.isa`). -/\ndef Task.{n}_compiles_to : Prop :=\n  Silmaril.Project.Shapes.C.CompilesTo Silmaril.X86.Open.isa {n}Placement {} {n}Fn\n",
                b.tag, f.frame
            );
            let _ = writeln!(
                o,
                "/-- **`{n}` compiles to `{n}Code` from its canonical entry** at `{}`\n(`c.compiles_to.canonical_entry` on `Open.isa`). -/\ndef Task.{n}_canonical : Prop :=\n  CompilesToCanonical Silmaril.X86.Open.isa {n}Placement {} {n}Fn\n",
                b.tag, f.frame
            );
        }
        let _ = writeln!(o, "end {}\n", b.tag);
    }
    // Same source, every build.
    for (n, _) in goal_functions(h) {
        let builds: Vec<String> = h
            .builds
            .iter()
            .filter(|b| {
                b.fns
                    .iter()
                    .any(|f| f.name == n && f.function_unsupported.is_none())
            })
            .map(|b| format!("{}.{n}Build", b.tag))
            .collect();
        let _ = writeln!(
            o,
            "/-- The builds of `{n}`. -/\ndef {n}Builds : List Silmaril.Project.Shapes.C.Build := [{}]\n",
            builds.join(", ")
        );
        let _ = writeln!(
            o,
            "/-- **Every build of `{n}` implements it** (`c.compiles_to.builds` on `Open.isa`). -/\ndef Task.{n}_builds : Prop :=\n  Silmaril.Project.Shapes.C.CompilesToBuilds Silmaril.X86.Open.isa {n}Fn {n}Builds\n"
        );
    }
    o.push_str("end\n\n");
    let _ = writeln!(o, "end {ns}");
    o
}

/// The Godbolt-style report.
pub fn markdown(h: &Header) -> String {
    let mut o = String::new();
    let _ = writeln!(o, "# `{}`: compiler-explorer correspondences\n", h.c_path);
    let _ = writeln!(
        o,
        "Generated by `tools/c-tv`. Compiler: {} (`{}`). Lean module: `{}`.\n",
        h.compiler, h.image, h.module
    );
    if let Some(e) = &h.core_error {
        let _ = writeln!(o, "**C → Core failed**: {e}\n");
    }
    for b in &h.builds {
        let _ = writeln!(
            o,
            "## `{}`: `{}`\n\nObject `{}` (sha256 `{}`).\n",
            b.tag,
            b.flags.join(" "),
            b.obj_path,
            b.obj_sha256
        );
        for f in &b.fns {
            let _ = writeln!(
                o,
                "### `{}` (`.text` `[{:#x}, {:#x})`, granularity: {})\n",
                f.name,
                f.off,
                f.off + f.size,
                f.granularity
            );
            if let Some(u) = &f.function_unsupported {
                let _ = writeln!(o, "No goals: {u}\n");
            }
            o.push_str(
                "| line | source | code | instructions | Lean point |\n|---:|---|---|---|---|\n",
            );
            let src: Vec<&str> = h.c_text.lines().collect();
            for r in &f.ranges {
                let point = f
                    .points
                    .iter()
                    .find(|p| p.off == r.start && p.line == r.line);
                let p = match point {
                    Some(p) => format!(
                        "{} ({})",
                        p.index,
                        match p.kind {
                            PointKind::Entry => "entry",
                            PointKind::Ret => "return label",
                            PointKind::Slots(_) => "statement",
                        }
                    ),
                    None => match f.unsupported.iter().find(|u| u.start == r.start) {
                        Some(u) => format!("unsupported: {}", u.reason),
                        None => "inside the function segment".into(),
                    },
                };
                let line_src = src
                    .get(r.line.saturating_sub(1) as usize)
                    .copied()
                    .unwrap_or("")
                    .trim();
                let _ = writeln!(
                    o,
                    "| {} | `{}` | `[{:#x}, {:#x})` | `{}` | {} |",
                    r.line,
                    line_src.replace('|', "\\|"),
                    r.start,
                    r.end,
                    r.asm.join("; ").replace('|', "\\|"),
                    p
                );
            }
            o.push('\n');
        }
    }
    while o.ends_with("\n\n") {
        o.pop();
    }
    o
}

/// A proof file the tool can write: its path relative to [`LIB_DIR`]`/`[`LIB`] (`File/Proofs/…`),
/// its content, and the goals it proves.
pub struct ProofFile {
    pub rel: String,
    pub content: String,
    pub proves: Vec<String>,
}

/// The module of a proof file (`CompilesToExamples.File.Proofs.X`).
fn proof_module(rel: &str) -> String {
    format!("{LIB}.{}", rel.trim_end_matches(".lean").replace('/', "."))
}

/// The mechanical proofs: the C ↔ Core equation (`cbv`, kernel-checked) and, for every return
/// label whose code is `pop %rbp; ret`, its segment (`FnData.segment_ret`) and the segment's
/// C ↔ x86 composition.
pub fn proofs(h: &Header, file: &str) -> Vec<ProofFile> {
    let mut out = Vec::new();
    if h.core_doc.is_none() {
        return out;
    }
    let ns = &h.module;
    // C ↔ Core.
    let mut c = String::new();
    let _ = writeln!(
        c,
        "module\n\n-- GENERATED by tools/c-tv. Do not edit by hand.\n\npublic import {ns}.Defs\n"
    );
    let _ = writeln!(
        c,
        "/-! `{}`: C ↔ Core. The Lean Cerberus elaborator takes the quoted typed Ail to the quoted\nCore (`cbv`, then the kernel checks the proof), and each function's procedure is its `CFn`. -/\n",
        h.c_path
    );
    let _ = writeln!(
        c,
        "namespace {ns}\n\nopen Silmaril.Project.CompilesTo Silmaril.Project.Shapes.C\n"
    );
    c.push_str("set_option maxRecDepth 16384\nset_option maxHeartbeats 8000000\n\n");
    c.push_str(
        "attribute [local cbv_eval] Silmaril.Cerberus.Elaboration.Expressions.expression.eq_def\n",
    );
    c.push_str("attribute [local cbv_eval] List.mergeSort_pair List.mergeSort_nil List.mergeSort_singleton\n\n");
    c.push_str("/-- **The elaborator's output is the quoted Core** (with the return labels named as it names\nthem, `fixRet`). -/\npublic theorem elab_eq : ElabAil ail = .ok core := by\n  cbv\n\n");
    let mut proves = vec![];
    for (n, _) in goal_functions(h) {
        let _ = writeln!(
            c,
            "/-- **C ↔ Core** for `{n}`. -/\npublic theorem elaborates_{n} : Task.elaborates_{n} :=\n  ⟨core, elab_eq, rfl, _, _, _, _, rfl, _, rfl, rfl⟩\n"
        );
        proves.push(format!("{ns}.Task.elaborates_{n}"));
    }
    let _ = writeln!(c, "end {ns}");
    out.push(ProofFile {
        rel: format!("{file}/Proofs/Elaborates.lean"),
        content: c,
        proves,
    });
    // Return-label segments.
    for b in &h.builds {
        for f in &b.fns {
            if f.function_unsupported.is_some() {
                continue;
            }
            let code = &b.text[f.off as usize..(f.off + f.size) as usize];
            for (i, p) in f.points.iter().enumerate() {
                if !matches!(p.kind, PointKind::Ret) {
                    continue;
                }
                let o = p.off as usize;
                if code.get(o) != Some(&0x5d) || code.get(o + 1) != Some(&0xc3) || f.frame < 8 {
                    continue;
                }
                let n = &f.name;
                let mut c = String::new();
                let _ = writeln!(
                    c,
                    "module\n\n-- GENERATED by tools/c-tv. Do not edit by hand.\n\npublic import {ns}.Defs\npublic import {ns}.Proofs.Elaborates\npublic import Silmaril.Project.CompilesTo.Thms\n"
                );
                let _ = writeln!(
                    c,
                    "/-! `{}`, `{}`, `{n}`, segment {i} (line {}: `pop %rbp; ret`): the return label, by\n`FnData.segment_ret` (Core ↔ x86), and its composition with C ↔ Core (C ↔ x86). -/\n",
                    h.c_path, b.tag, p.line
                );
                let _ = writeln!(
                    c,
                    "namespace {ns}.{}\n\nopen Silmaril.Project.CompilesTo Silmaril.Project.Shapes.CompilesTo\n",
                    b.tag
                );
                let _ = writeln!(
                    c,
                    "/-- **Core ↔ x86**, segment {i} of `{n}`. -/\npublic theorem {n}_seg_{i} : Task.{n}_seg_{i} :=\n  FnData.segment_ret {n} (k := {i}) rfl rfl rfl (by decide) (by decide) (by decide) (by decide)\n    (by decide) (by decide) (by decide)\n"
                );
                let _ = writeln!(
                    c,
                    "/-- **C ↔ x86**, segment {i} of `{n}`: C ↔ Core (function and point) and Core ↔ x86. -/\npublic theorem {n}_seg_{i}_from_c : Task.{n}_seg_{i}_from_c :=\n  ⟨elaborates_{n}, {n}_point_{i}, {n}_seg_{i}⟩\n"
                );
                let _ = writeln!(c, "end {ns}.{}", b.tag);
                out.push(ProofFile {
                    rel: format!("{file}/Proofs/{}{}Seg{i}.lean", b.tag, camel(n)),
                    content: c,
                    proves: vec![
                        format!("{ns}.{}.Task.{n}_seg_{i}", b.tag),
                        format!("{ns}.{}.Task.{n}_seg_{i}_from_c", b.tag),
                    ],
                });
            }
        }
    }
    out
}

/// The supported functions of a build (those with goals).
fn goal_fns<'b>(h: &Header, b: &'b Build) -> Vec<&'b FnCorr> {
    if h.core_doc.is_none() {
        return vec![];
    }
    b.fns
        .iter()
        .filter(|f| f.function_unsupported.is_none())
        .collect()
}

/// The registry name of the C source (`silmaril/artifacts.toml`).
pub fn source_artifact(name: &str) -> String {
    format!("silmaril.compiles_to.{name}.source")
}

/// The registry name of a build's object file (`silmaril/artifacts.toml`).
pub fn object_artifact(name: &str, tag: &str) -> String {
    format!("silmaril.compiles_to.{name}.{}.object", tag.to_lowercase())
}

/// One row of the records: its name, the shape, the TOML `args`, its title, the `Task` it states
/// (with the namespace, `None` for a row the rows module proves directly) and its proof in the
/// rows module when it has one without a `Task`.
struct Row {
    name: String,
    of: &'static str,
    args: String,
    title: String,
    task: Option<String>,
    direct: Option<String>,
}

fn rows(h: &Header, name: &str) -> Vec<Row> {
    let ns = &h.module;
    let mut out = Vec::new();
    let base = format!("silmaril.compiles_to.{name}");
    for (n, _) in goal_functions(h) {
        out.push(Row {
            name: format!("{base}.{n}.elaborates"),
            of: "silmaril.shapes.c.elaborates_to",
            args: format!(
                "{{ ail = \"{ns}.ail\", name = {{ str = \"{n}\" }}, F = \"{ns}.{n}Fn\" }}"
            ),
            title: format!("{n} elaborates to its Core"),
            task: Some(format!("{ns}.Task.elaborates_{n}")),
            direct: None,
        });
    }
    for b in &h.builds {
        let fns = goal_fns(h, b);
        let tag = b.tag.to_lowercase();
        for f in &fns {
            let n = &f.name;
            let fb = format!("{base}.{tag}.{n}");
            let ft = format!("{ns}.{}", b.tag);
            out.push(Row {
                name: format!("{fb}.code"),
                of: "silmaril.shapes.elf.object_fn",
                args: format!(
                    "{{ obj = \"{base}.{tag}.obj\", fn = {{ str = \"{n}\" }}, code = \"{ft}.{n}Code\" }}"
                ),
                title: format!("the {} object defines {n} with its bytes", b.tag),
                task: None,
                direct: Some(format!(
                    "Silmaril.Project.Shapes.SysV.ObjectFn.of_blob {}\n    (Silmaril.Project.Shapes.blob_of_decode (B := {ft}.objBlob) rfl (by decide +kernel))\n    {ft}.{n}_code",
                    f.off
                )),
            });
            for (k, p) in f.points.iter().enumerate() {
                out.push(Row {
                    name: format!("{fb}.seg_{k}"),
                    of: "silmaril.shapes.c.compiles_to.segment.open",
                    args: format!("{{ F = \"{ft}.{n}\", k = {k} }}"),
                    title: format!("{n} at {}, segment {k} (line {})", b.tag, p.line),
                    task: Some(format!("{ft}.Task.{n}_seg_{k}")),
                    direct: None,
                });
            }
            let pargs = format!(
                "{{ p = \"{ft}.{n}Placement\", frame = {}, F = \"{ns}.{n}Fn\" }}",
                f.frame
            );
            out.push(Row {
                name: format!("{fb}.function"),
                of: "silmaril.shapes.c.compiles_to.open",
                args: pargs.clone(),
                title: format!("{n} at {} implements its C function", b.tag),
                task: Some(format!("{ft}.Task.{n}_compiles_to")),
                direct: None,
            });
            out.push(Row {
                name: format!("{fb}.canonical"),
                of: "silmaril.shapes.c.compiles_to.canonical_entry.open",
                args: pargs,
                title: format!(
                    "{n} at {} implements its C function from the canonical entry",
                    b.tag
                ),
                task: Some(format!("{ft}.Task.{n}_canonical")),
                direct: None,
            });
        }
    }
    for (n, _) in goal_functions(h) {
        out.push(Row {
            name: format!("{base}.{n}.builds"),
            of: "silmaril.shapes.c.compiles_to.builds",
            args: format!(
                "{{ M = \"Silmaril.X86.Open.isa\", F = \"{ns}.{n}Fn\", builds = \"{ns}.{n}Builds\" }}"
            ),
            title: format!("every build of {n} implements it"),
            task: Some(format!("{ns}.Task.{n}_builds")),
            direct: None,
        });
    }
    out
}

/// `silmaril/compiles-to/<name>.toml`: the source and objects as values and the rows of the C
/// file, under the group `silmaril.compiles_to.<name>` (`None` without rows).
pub fn records(h: &Header, name: &str, proofs: &[ProofFile]) -> Option<String> {
    let rows = rows(h, name);
    if rows.is_empty() {
        return None;
    }
    let proved: Vec<&String> = proofs.iter().flat_map(|p| p.proves.iter()).collect();
    let mut o = String::new();
    let _ = writeln!(
        o,
        "# GENERATED by tools/c-tv ({}). Do not edit by hand; regenerate with tools/c-tv/regen.sh.\n# The rows of `{}`: per function, per build and per segment (docs/projects/compiles-to.md).\nschema = \"silmaril.records.v0.2\"\n",
        h.tool_rev, h.c_path
    );
    let _ = writeln!(
        o,
        "[[value]]\nname = \"silmaril.compiles_to.{name}.src\"\nformat = \"bytes\"\nsource = \"{}\"\n",
        source_artifact(name)
    );
    for b in &h.builds {
        if goal_fns(h, b).is_empty() {
            continue;
        }
        let _ = writeln!(
            o,
            "[[value]]\nname = \"silmaril.compiles_to.{name}.{}.obj\"\nformat = \"bytes\"\nsource = \"{}\"\n",
            b.tag.to_lowercase(),
            object_artifact(name, &b.tag)
        );
    }
    // The values' `parses` problems, solved in the rows module.
    let mut children = vec![format!("\"silmaril.compiles_to.{name}.src.parses\"")];
    for b in &h.builds {
        if !goal_fns(h, b).is_empty() {
            children.push(format!(
                "\"silmaril.compiles_to.{name}.{}.obj.parses\"",
                b.tag.to_lowercase()
            ));
        }
    }
    for r in &rows {
        let expect = if r.direct.is_some() || r.task.as_ref().is_some_and(|t| proved.contains(&t)) {
            "THM"
        } else {
            "OPN"
        };
        let _ = writeln!(
            o,
            "[[instance]]\nname = \"{}\"\nof = \"{}\"\nargs = {}\nexpect = \"{expect}\"\ntitle = {}\n",
            r.name,
            r.of,
            r.args,
            lean_string(&r.title)
        );
        children.push(format!("\"{}\"", r.name));
    }
    let _ = writeln!(
        o,
        "[[group]]\nname = \"silmaril.compiles_to.{name}\"\ntitle = {}\nchildren = [\n  {},\n]",
        lean_string(&format!("{} compiles to its object files", h.c_path)),
        children.join(",\n  ")
    );
    Some(o)
}

/// `CompilesToExamples/<File>/Rows.lean`: loads the records and solves each row whose `Task` a
/// proof module proves, and the object rows directly (`None` without rows).
pub fn rows_module(h: &Header, name: &str, proofs: &[ProofFile]) -> Option<String> {
    let rows = rows(h, name);
    if rows.is_empty() {
        return None;
    }
    let ns = &h.module;
    let proved: Vec<&String> = proofs.iter().flat_map(|p| p.proves.iter()).collect();
    let mut o = String::new();
    let _ = writeln!(
        o,
        "module\n\n-- GENERATED by tools/c-tv. Do not edit by hand.\n\npublic import ProjectSelfTest\npublic import {ns}.Thms\npublic import Silmaril.Project.Shapes.CompilesTo.Thms\npublic import Silmaril.Project.Shapes.Elf.Thms\n"
    );
    let _ = writeln!(
        o,
        "/-!\n# `{}`: the rows\n\n`silmaril/compiles-to/{name}.toml` registers the source and the object files (artifacts of\n`silmaril/artifacts.toml`, imported with `ProjectSelfTest`) as values and the rows; a row is solved here when a proof module of `{ns}.Thms` proves its `Task`. An\nobject row ties the header's bytes to the registered object by the kernel\n(`ObjectFn.of_blob`, `blob_of_decode`).\n-/\n",
        h.c_path
    );
    let _ = writeln!(o, "silmaril load \"silmaril/compiles-to/{name}.toml\"\n");
    let _ = writeln!(o, "namespace {ns}.Rows\n");
    let mut values = vec![format!("silmaril.compiles_to.{name}.src")];
    for b in &h.builds {
        if !goal_fns(h, b).is_empty() {
            values.push(format!(
                "silmaril.compiles_to.{name}.{}.obj",
                b.tag.to_lowercase()
            ));
        }
    }
    for v in &values {
        let thm = v
            .replace(&format!("silmaril.compiles_to.{name}."), "")
            .replace('.', "_");
        let _ = writeln!(
            o,
            "@[solves \"{v}.parses\"] public theorem {thm}_parses : {v}.parses := by\n  silmaril_decide\n"
        );
    }
    for r in &rows {
        let proof = match (&r.direct, &r.task) {
            (Some(d), _) => d.clone(),
            (None, Some(t)) if proved.contains(&t) => t.replace(".Task.", "."),
            _ => continue,
        };
        let thm = r
            .name
            .replace(&format!("silmaril.compiles_to.{name}."), "")
            .replace('.', "_");
        let _ = writeln!(
            o,
            "@[solves \"{}\"] public theorem {thm} : {} :=\n  {proof}\n",
            r.name, r.name
        );
    }
    let _ = writeln!(o, "end {ns}.Rows");
    Some(o)
}

/// `silmaril/compiles-to.toml` and `CompilesToExamples.lean`: the group over the C files that
/// have rows (`names`), and the module that loads them all.
pub fn root(names: &[String]) -> (String, String) {
    let mut t = String::new();
    let _ = writeln!(
        t,
        "# GENERATED by tools/c-tv. Do not edit by hand; regenerate with tools/c-tv/regen.sh.\n# The compiles-to rows (`silmaril/compiles-to/*.toml`, docs/projects/compiles-to.md), a child\n# of the root group in `silmaril/selftest.toml`.\nschema = \"silmaril.records.v0.2\"\n\n[[group]]\nname = \"silmaril.compiles_to.all\"\ntitle = \"C files compile to their object files (examples/compiles-to)\"\nchildren = [\n  {},\n]",
        names
            .iter()
            .map(|n| format!("\"silmaril.compiles_to.{n}\""))
            .collect::<Vec<_>>()
            .join(",\n  ")
    );
    let mut l = String::new();
    let _ = writeln!(
        l,
        "module\n\n-- GENERATED by tools/c-tv. Do not edit by hand.\n"
    );
    for n in names {
        let _ = writeln!(l, "public import {LIB}.{}.Rows", camel(n));
    }
    let _ = writeln!(
        l,
        "\n/-! The compiles-to rows of every C file of `examples/compiles-to` and their group\n`silmaril.compiles_to.all` (`silmaril/compiles-to.toml`). -/\n\nsilmaril load \"silmaril/compiles-to.toml\""
    );
    (t, l)
}

/// The proof modules of a C file that the tool did not write (by hand or by a prover), sorted:
/// every `public theorem x : Task.g` they state, in their first namespace.
pub fn found_proofs(
    lib_root: &std::path::Path,
    dir: &str,
    generated: &[String],
) -> anyhow::Result<Vec<ProofFile>> {
    let path = lib_root.join(dir);
    let mut out = Vec::new();
    let Ok(entries) = std::fs::read_dir(&path) else {
        return Ok(out);
    };
    let mut names: Vec<String> = entries
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().into_owned())
        .filter(|n| n.ends_with(".lean"))
        .collect();
    names.sort();
    for n in names {
        let rel = format!("{dir}/{n}");
        if generated.contains(&rel) {
            continue;
        }
        let text = std::fs::read_to_string(path.join(&n))?;
        let ns = text
            .lines()
            .find_map(|l| l.strip_prefix("namespace "))
            .unwrap_or("")
            .trim()
            .to_string();
        let proves: Vec<String> = text
            .lines()
            .filter_map(|l| l.trim().strip_prefix("public theorem "))
            .filter_map(|l| l.split_once(" : Task."))
            // a theorem with hypotheses is conditional: it proves no goal
            .filter(|(name, _)| !name.contains('('))
            .map(|(_, g)| {
                let g = g.split_whitespace().next().unwrap_or("");
                format!("{ns}.Task.{g}")
            })
            .collect();
        if proves.is_empty() {
            continue;
        }
        out.push(ProofFile {
            rel,
            content: String::new(),
            proves,
        });
    }
    Ok(out)
}

/// The module that collects the proofs of a C file.
pub fn thms(h: &Header, proofs: &[ProofFile]) -> String {
    let ns = &h.module;
    let mut o = String::new();
    let _ = writeln!(
        o,
        "module\n\n-- GENERATED by tools/c-tv. Do not edit by hand.\n\npublic import {ns}.Defs"
    );
    for p in proofs {
        let _ = writeln!(o, "public import {}", proof_module(&p.rel));
    }
    let _ = writeln!(
        o,
        "\n/-!\n# `{}`: the proved goals\n\n| goal | proof module |\n|---|---|",
        h.c_path
    );
    for p in proofs {
        for g in &p.proves {
            let _ = writeln!(o, "| `{g}` | `{}` |", proof_module(&p.rel));
        }
    }
    let _ = writeln!(o, "\nEvery other `Task` of `{ns}.Defs` is open. -/");
    o
}
