#!/usr/bin/env bash
# Regenerate tools/wasm-tools/WasmTools/CompletionData.lean: the shell completion scripts and
# help texts of `wasm-tools completion`, captured verbatim from the pinned wasm-tools 1.262.0.
# The scripts are clap_complete's rendering of upstream's whole command grammar; this build
# reproduces them as data (see tools/wasm-tools/README.md, completion).
#   Usage: tools/wasm-tools/tests/gen-completion.sh
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
source "$here/pins.sh"
wt_require_upstream
python3 -I - "$WT_UPSTREAM" "$here/../WasmTools/CompletionData.lean" <<'PY'
import json, subprocess, sys
w, out = sys.argv[1], sys.argv[2]
parts = ['/-! Shell completion scripts and help of upstream wasm-tools 1.262.0, verbatim\n'
         '(generated by `tools/wasm-tools/tests/gen-completion.sh`; do not edit). -/\n\n'
         'namespace WasmTools.CompletionData\n']
for flag, nm in [('-h', 'short'), ('--help', 'long')]:
    t = subprocess.run([w, 'completion', flag], capture_output=True, text=True).stdout
    parts.append(f'def help_{nm} : String := {json.dumps(t, ensure_ascii=False)}\n')
for sh in ['bash', 'elvish', 'fish', 'powershell', 'zsh']:
    t = subprocess.run([w, 'completion', sh], capture_output=True, text=True, check=True).stdout
    parts.append(f'def {sh} : String := {json.dumps(t, ensure_ascii=False)}\n')
parts.append('\nend WasmTools.CompletionData\n')
open(out, 'w').write('\n'.join(parts))
PY
