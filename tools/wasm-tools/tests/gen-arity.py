"""Regenerate Silmaril/Wasm/Tools/Print/Arity.lean: the fixed operand arities of the operators
(wasmparser's `for_each_operator!`, `arity a -> b`) keyed by their text names (wasmprinter's
`(name Op) => ("text")`), from the wasm-tools 1.262.0 source archive.

  python3 -I tools/wasm-tools/tests/gen-arity.py SRC_DIR OUT.lean
"""
import re, sys
src, out = sys.argv[1], sys.argv[2]
lib = open(f"{src}/crates/wasmparser/src/lib.rs").read()
ops = open(f"{src}/crates/wasmprinter/src/operator.rs").read()
arity = {}
for m in re.finditer(r"^\s*(\w+)(?:\s*\{[^}]*\})?\s*=>\s*visit_\w+\s*\(arity (\d+) -> (\d+)\)", lib, re.M):
    arity[m.group(1)] = (int(m.group(2)), int(m.group(3)))
names = {}
for m in re.finditer(r'\(name (\w+)\) => \("([^"]+)"\)', ops):
    names[m.group(1)] = m.group(2)
table = {}
for op, txt in names.items():
    if op in arity:
        a = arity[op]
        if txt in table and table[txt] != a:
            table[txt] = None  # ambiguous: computed specially
        elif txt not in table:
            table[txt] = a
rows = sorted((t, a) for t, a in table.items() if a is not None)
lines = ["module", "", "/-! Fixed operand arities (params, results) of the operators by text name, from wasmparser's",
         "`for_each_operator!` and wasmprinter's operator names (wasm-tools 1.262.0); generated by",
         "`tools/wasm-tools/tests/gen-arity.py`, do not edit. Operators of variable arity are computed",
         "by `Silmaril.Wasm.Tools.Print.opArity`. -/", "", "@[expose] public section", "",
         "namespace Silmaril.Wasm.Tools.Print.Arity", "",
         "def table : List (String × Nat × Nat) := ["]
lines += [f'  ("{t}", {a[0]}, {a[1]}),' for t, a in rows]
lines[-1] = lines[-1].rstrip(",")
lines += ["]", "", "end Silmaril.Wasm.Tools.Print.Arity", ""]
open(out, "w").write("\n".join(lines))
print(len(rows), "operators;", sum(1 for a in table.values() if a is None), "ambiguous")
