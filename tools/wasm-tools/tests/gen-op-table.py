# Generate Silmaril/Wasm/Tools/OpTable/Defs.lean from wasmparser 0.262's sources (wasm-tools 1.262.0):
#   python3 -I tools/wasm-tools/tests/gen-op-table.py WASMPARSER_SRC > Silmaril/Wasm/Tools/OpTable/Defs.lean
# WASMPARSER_SRC is crates/wasmparser/src of the wasm-tools 1.262.0 source archive. Reads the
# operator dispatch of binary_reader.rs (visit_operator, visit_0xf{b,c,d,e}_operator) and the
# argument names and types of for_each_operator! (lib.rs). Arms whose reading is irregular are
# listed in SPECIAL and implemented by hand in Silmaril/Wasm/Tools/DumpFlat/Defs.lean.
import re, sys
src = sys.argv[1]
br = open(src + "/binary_reader.rs").read()
lib = open(src + "/lib.rs").read()

args = {}
for m in re.finditer(r"^\s*(\w+)[ \t]*(?:\{([^}]*)\})?[ \t]*=>[ \t]*visit_(\w+)[ \t]*\(", lib, re.M):
    body = m.group(2) or ""
    al = []
    for a in body.split(","):
        a = a.strip()
        if not a: continue
        n, t = a.split(":", 1)
        al.append((n.strip(), t.strip().replace("$crate::", "")))
    args[m.group(3)] = al

def func_body(name):
    i = br.index("fn " + name)
    j = br.index("Ok(match code {", i) + len("Ok(match code {")
    depth = 1; k = j
    while depth:
        c = br[k]
        if c == "{": depth += 1
        elif c == "}": depth -= 1
        k += 1
    return re.sub(r"//[^\n]*", "", br[j:k-1])

def arms(body):
    pos = [m.start() for m in re.finditer(r"^\s*(0x[0-9a-fA-F]+)\s*=>", body, re.M)]
    ends = [m.start() for m in re.finditer(r"^\s*_\s*=>", body, re.M)]
    ends = [e for e in ends if e > pos[-1]]
    pos.append(ends[0] if ends else len(body))
    for a, b in zip(pos, pos[1:]):
        t = body[a:b]
        code = int(re.match(r"\s*(0x[0-9a-fA-F]+)", t).group(1), 16)
        yield code, t

SPECIAL = {(0, 0x05), (0, 0x07), (0, 0x0b), (0, 0x18), (0, 0x19), (0, 0x1c),
           (0xfb, 0x18), (0xfb, 0x19), (0xfb, 0x25), (0xfb, 0x26), (0xfd, 0x0d), (0xfe, 0x03)}

def kind(expr, ty):
    e = expr.strip()
    if e.startswith("self.read_memarg("):
        return "(.memarg %s)" % re.match(r"self\.read_memarg\((\d+)\)", e).group(1)
    tbl = {"self.read_var_u32()?": ".u32", "self.read_var_i32()?": ".i32", "self.read_var_i64()?": ".i64",
           "self.read_f32()?": ".f32", "self.read_f64()?": ".f64", "self.read_v128()?": ".v128",
           "self.read_block_type()?": ".blockty", "self.read_br_table()?": ".brtable",
           "self.read_lane_index()?": ".lane", "self.read_ordering()?": ".ordering",
           "self.read_memory_index_or_zero_if_not_multi_memory()?": ".u32",
           "self.read_call_indirect_table_immediate()?": ".u32"}
    if e in tbl: return tbl[e]
    if e == "self.read()?":
        return {"u32": ".u32", "HeapType": ".heap", "ValType": ".val", "RefType": ".ref",
                "TryTable": ".trytable", "ResumeTable": ".resumetable", "BlockType": ".blockty"}[ty]
    raise SystemExit("unknown reader %r (%s)" % (e, ty))

def split_args(s):
    out, depth, cur = [], 0, ""
    for c in s:
        if c in "([{": depth += 1
        if c in ")]}": depth -= 1
        if c == "," and depth == 0:
            out.append(cur); cur = ""
        else: cur += c
    if cur.strip(): out.append(cur)
    return out

rows = []
for prefix, fn in [(0, "visit_operator<T>"), (0xfb, "visit_0xfb_operator"), (0xfc, "visit_0xfc_operator"),
                   (0xfd, "visit_0xfd_operator"), (0xfe, "visit_0xfe_operator")]:
    for code, t in arms(func_body(fn)):
        if (prefix, code) in SPECIAL: continue
        if prefix == 0 and code in (0xfb, 0xfc, 0xfd, 0xfe): continue
        m = re.search(r"visitor\.visit_(\w+)\((.*)\)\s*,?\s*\}?\s*$", t.strip(), re.S)
        if not m:
            raise SystemExit("cannot parse arm %x %x: %s" % (prefix, code, t))
        name, a = m.group(1), m.group(2)
        lets = dict((v, e) for v, e in re.findall(r"let (\w+) = (self\.[\w]+\([^;]*\)\?);", t))
        al = args.get(name)
        if al is None: raise SystemExit("no args for " + name)
        exprs = [x.strip() for x in split_args(a)]
        if len(exprs) != len(al): raise SystemExit("arity %s: %r vs %r" % (name, exprs, al))
        imms = []
        for (an, at), ex in zip(al, exprs):
            ex = lets.get(ex, ex)
            imms.append('("%s", %s)' % (an, kind(ex, at)))
        rows.append((prefix, code, name, imms))

print("""module

public import Std.Data.HashMap

/-!
# wasmparser 0.262's operator table

Generated by `tools/wasm-tools/tests/gen-op-table.py` from wasmparser's `binary_reader.rs`
(the opcode dispatch) and `lib.rs` (`for_each_operator!`: argument names and types). Every row:
the prefix byte (`0` for single-byte opcodes), the (sub)opcode, the `visit_` name without its
prefix, and the immediates in reading order with their argument names. The arms read
irregularly (`else`, `end`, `catch`, `catch_all`, `delegate`, typed `select`, the four cast
branches, `i8x16.shuffle`, `atomic.fence`) are not in the table; `DumpFlat` implements them.

Do not edit: regenerate.
-/

@[expose] public section

namespace Silmaril.Wasm.Tools.OpTable

/-- How an immediate is read and printed (by wasmparser's reader and its `Debug`). -/
inductive Imm where
  | u32 | i32 | i64 | f32 | f64 | v128 | blockty | brtable | lane | ordering
  | memarg (maxAlign : Nat) | heap | val | ref | trytable | resumetable
  deriving Repr, Inhabited, BEq
""")
chunks = [rows[i:i+80] for i in range(0, len(rows), 80)]
for ci, ch in enumerate(chunks):
    print("/-- Rows, part %d. -/" % ci)
    print("def rows%d : List (Nat × Nat × String × List (String × Imm)) := [" % ci)
    print(",\n".join('  (0x%x, 0x%x, "%s", [%s])' % (p, c, n, ", ".join(i)) for p, c, n, i in ch))
    print("]\n")
print("/-- All rows. -/")
print("def rows : List (Nat × Nat × String × List (String × Imm)) :=")
print("  " + " ++ ".join("rows%d" % i for i in range(len(chunks))))
print("""
/-- The table, keyed by (prefix, opcode). -/
def table : Std.HashMap (Nat × Nat) (String × List (String × Imm)) :=
  rows.foldl (fun m (p, c, n, is) => m.insert (p, c) (n, is)) {}

end Silmaril.Wasm.Tools.OpTable""")
print(len(rows), file=sys.stderr)
