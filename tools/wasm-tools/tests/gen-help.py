#!/usr/bin/env python3
"""Write Silmaril/Wasm/Tools/Meta/Help/Defs.lean from the captured upstream help texts.

The texts in tools/wasm-tools/tests/help/ are what wasm-tools 1.262.0 prints with COLUMNS
unset and stdout not a terminal (capture-help.sh). Usage: gen-help.py REPO_ROOT
"""
import os, sys

root = sys.argv[1]
src = os.path.join(root, "tools/wasm-tools/tests/help")
names = sorted(f[:-4] for f in os.listdir(src) if f.endswith(".txt"))

def lean_str(s):
    out = []
    for ch in s:
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\t": out.append("\\t")
        else: out.append(ch)
    return '"' + "".join(out) + '"'

def ident(n):
    parts = n.replace("-", " ").split()
    return "help" + "".join(p[:1].upper() + p[1:] for p in parts)

lines = ["module", "", "/-!", "# Help texts of the meta subcommands", "",
         "Generated by `tools/wasm-tools/tests/gen-help.py` from the texts `wasm-tools 1.262.0`",
         "prints (`tools/wasm-tools/tests/help/`, captured by `capture-help.sh` with `COLUMNS`",
         "unset and stdout not a terminal). Do not edit by hand.", "-/", "",
         "@[expose] public section", "", "namespace Silmaril.Wasm.Tools.Meta.Help", ""]
for n in names:
    with open(os.path.join(src, n + ".txt"), encoding="utf-8") as f:
        text = f.read()
    lines.append(f"/-- `{n}.txt`. -/")
    lines.append(f"def {ident(n)} : String :=")
    lines.append("  " + lean_str(text))
    lines.append("")
lines += ["end Silmaril.Wasm.Tools.Meta.Help", "", "end", ""]
with open(os.path.join(root, "Silmaril/Wasm/Tools/Meta/Help/Defs.lean"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
