#!/usr/bin/env python3
"""Write Silmaril/Wasm/Tools/Meta/Spdx/Data/Defs.lean: the SPDX license and exception identifiers
of spdx 0.13.5 (license list 3.28.0), the version wasm-tools 1.262.0 links (Cargo.lock).

Usage: gen-spdx.py SPDX_CRATE_DIR REPO_ROOT, where SPDX_CRATE_DIR is the unpacked spdx-0.13.5
crate (for example ~/.cargo/registry/src/index.crates.io-*/spdx-0.13.5). The crate file is
read as text only.
"""
import os, re, sys

src = open(os.path.join(sys.argv[1], "src/identifiers.rs"), encoding="utf-8").read()
version = re.search(r'pub const VERSION: &str = "([^"]+)"', src).group(1)
lic_part = src[src.index("pub const LICENSES"):src.index("pub const IMPRECISE_NAMES")]
exc_part = src[src.index("pub const EXCEPTIONS"):]
flagval = {"IS_FSF_LIBRE": 1, "IS_OSI_APPROVED": 2, "IS_DEPRECATED": 4, "IS_COPYLEFT": 8, "IS_GNU": 16}

def entries(part):
    out = []
    for m in re.finditer(r'name: "([^"]+)",.*?flags: ([^,]+),', part, re.S):
        name, flags = m.group(1), m.group(2).strip()
        v = 0
        if flags.startswith("0x"):
            v = int(flags, 16)
        else:
            for f in flags.split("|"):
                f = f.strip()
                v |= int(f) if f.isdigit() else flagval[f]
        out.append((name, v))
    return out

lics, excs = entries(lic_part), entries(exc_part)
assert [n for n, _ in lics] == sorted(n for n, _ in lics), "licenses not sorted"
lines = ["module", "", "/-!", f"# SPDX identifiers (license list {version})", "",
         "Generated by `tools/wasm-tools/tests/gen-spdx.py` from spdx 0.13.5's `identifiers.rs`.",
         "One identifier per line, then a space and its flags (4: deprecated, 16: GNU). Do not edit.",
         "-/", "", "@[expose] public section", "", "namespace Silmaril.Wasm.Tools.Meta.Spdx", "",
         f'/-- The SPDX license list version. -/\ndef listVersion : String := "{version}"', "",
         "/-- The licenses, sorted by name. -/",
         'def licenseData : String := "' + "\\n".join(f"{n} {v}" for n, v in lics) + '"', "",
         "/-- The exceptions, sorted by name. -/",
         'def exceptionData : String := "' + "\\n".join(f"{n} {v}" for n, v in excs) + '"', "",
         "end Silmaril.Wasm.Tools.Meta.Spdx", "", "end", ""]
os.makedirs(os.path.join(sys.argv[2], "Silmaril/Wasm/Tools/Meta/Spdx/Data"), exist_ok=True)
open(os.path.join(sys.argv[2], "Silmaril/Wasm/Tools/Meta/Spdx/Data/Defs.lean"), "w").write("\n".join(lines))
print(len(lics), "licenses,", len(excs), "exceptions")
