# ------------------------------------------------------------------ values

M64 = (1 << 64) - 1


def f80(s, e, sig):
    return (s << 79) | (e << 64) | sig


def rand_norm(rng, lo=1, hi=0x7FFE):
    return f80(rng.getrandbits(1), rng.randint(lo, hi), (1 << 63) | rng.getrandbits(63))


def rand_short(rng, bits, lo=16383 - 40, hi=16383 + 40):
    """A normal value with only `bits` significant bits."""
    sig = (1 << 63) | (rng.getrandbits(bits - 1) << (64 - bits))
    return f80(rng.getrandbits(1), rng.randint(lo, hi), sig)


def special80(rng):
    s = rng.getrandbits(1)
    return rng.choice([
        f80(s, 0, 0),                                      # zero
        f80(s, 16383, 1 << 63),                            # 1
        f80(s, 16384, 1 << 63),                            # 2
        f80(s, 16383, 3 << 62),                            # 1.5
        f80(s, 16382, 1 << 63),                            # 0.5
        f80(s, 1, 1 << 63),                                # min normal
        f80(s, 0x7FFE, M64),                               # max
        f80(s, 0, rng.getrandbits(63) | 1),                # denormal
        f80(s, 0, (1 << 63) | rng.getrandbits(63)),        # pseudo-denormal
        f80(s, 0x7FFF, 1 << 63),                           # infinity
        f80(s, 0x7FFF, (3 << 62) | rng.getrandbits(62)),   # QNaN
        f80(s, 0x7FFF, (1 << 63) | rng.getrandbits(62) | 1),  # SNaN
        f80(1, 0x7FFF, 3 << 62),                           # indefinite
        f80(s, rng.randint(1, 0x7FFE), rng.getrandbits(63)),  # unnormal
        f80(s, 0x7FFF, 0),                                 # pseudo-infinity
        f80(s, 0x7FFF, rng.getrandbits(63) | 1),           # pseudo-NaN
        f80(s, rng.randint(1, 60), (1 << 63) | rng.getrandbits(63)),       # tiny
        f80(s, rng.randint(0x7FFE - 60, 0x7FFE), (1 << 63) | rng.getrandbits(63)),  # huge
        f80(s, 16383 + rng.randint(0, 62), 1 << 63),        # power of two
        int_val(rng.randint(-1000, 1000)),
        half_val(rng),
    ])


def int_val(n):
    if n == 0:
        return 0
    s = 1 if n < 0 else 0
    m = abs(n)
    b = m.bit_length()
    return f80(s, 16383 + b - 1, m << (64 - b))


def half_val(rng):
    """k + 1/2, k + 1/4, ... for rounding-to-integer ties."""
    k = rng.randint(0, 1 << rng.choice([3, 20, 62]))
    frac = rng.choice([1, 2, 3])  # quarters
    num = 4 * k + frac
    s = rng.getrandbits(1)
    b = num.bit_length()
    if b > 64:
        num >>= b - 64
        b = 64
    return f80(s, 16383 + b - 1 - 2, num << (64 - b))


def value(rng):
    r = rng.random()
    if r < 0.35:
        return special80(rng)
    if r < 0.55:
        return rand_short(rng, rng.choice([8, 24, 25, 53, 54]))
    if r < 0.8:
        return rand_norm(rng, 16383 - 70, 16383 + 70)
    return rand_norm(rng)


def near(rng, x):
    """A value close in exponent to `x`, for cancellation and carries."""
    e = (x >> 64) & 0x7FFF
    if e in (0, 0x7FFF) or rng.random() < 0.3:
        return value(rng)
    e2 = max(1, min(0x7FFE, e + rng.randint(-3, 3)))
    sig = (x & M64) ^ rng.getrandbits(rng.choice([1, 8, 30, 63]))
    sig |= 1 << 63
    return f80(rng.getrandbits(1), e2, sig)


def ieee_special(rng, p, w):
    s = rng.getrandbits(1) << (p - 1 + w)
    emax = (1 << w) - 1
    fr = lambda: rng.getrandbits(p - 1)  # noqa: E731
    return s | rng.choice([
        0, 1, fr() or 1,                                   # zero, denormals
        (1 << (p - 1)) - 1,                                # max denormal
        1 << (p - 1),                                      # min normal
        (emax << (p - 1)),                                 # infinity
        (emax << (p - 1)) | (1 << (p - 2)) | fr(),         # QNaN
        (emax << (p - 1)) | ((fr() >> 1) | 1),             # SNaN
        ((emax - 1) << (p - 1)) | fr(),                    # huge
        (rng.randint(1, emax - 1) << (p - 1)) | fr(),      # random
        ((emax >> 1) << (p - 1)) | fr(),                   # near 1
    ])


def ieee_value(rng, p, w):
    if rng.random() < 0.5:
        return ieee_special(rng, p, w)
    e = rng.randint((1 << (w - 1)) - 40, (1 << (w - 1)) + 40)
    return (rng.getrandbits(1) << (p - 1 + w)) | (e << (p - 1)) | rng.getrandbits(p - 1)


def int_mem(rng, bits):
    r = rng.random()
    if r < 0.4:
        v = rng.choice([0, 1, -1, 2, -2, 3, (1 << (bits - 1)) - 1, -(1 << (bits - 1)),
                        (1 << (bits - 2)), rng.randint(-100, 100)])
    else:
        v = rng.getrandbits(bits) - (1 << (bits - 1))
    return v % (1 << bits)


def int_like80(rng, bits):
    """A register value near the integer range limits of an n-bit integer."""
    lim = 1 << (bits - 1)
    n = rng.choice([lim, lim - 1, -lim, -lim - 1, lim + 1, rng.randint(-lim, lim)])
    v = int_val(n)
    if rng.random() < 0.5:
        # add a fraction
        e = (v >> 64) & 0x7FFF
        if v and e - 16383 < 63:
            v |= rng.getrandbits(max(0, 63 - (e - 16383)))
    return v


# ------------------------------------------------------------------ states

TAG = {"valid": 0, "zero": 1, "special": 2, "empty": 3}


def tag_of(v):
    e = (v >> 64) & 0x7FFF
    sig = v & M64
    if e == 0 and sig == 0:
        return 1
    if e == 0 or e == 0x7FFF or not (sig >> 63):
        return 2
    return 0


def control(rng, unmask=0.15):
    pc = rng.choice([0, 2, 3, 3])
    rcw = rng.randrange(4)
    masks = 0x3F
    if rng.random() < unmask:
        masks = rng.getrandbits(6)
    return masks | 0x40 | (pc << 8) | (rcw << 10) | (rng.getrandbits(1) << 12)


def state(rng, need=(0,), push=False, full=False, unmask=0.15, pending=False):
    """A random FRSTOR state. `need` are the ST indices that should usually be
    non-empty; with `push`, ST(7) is usually empty."""
    cw = control(rng, unmask)
    top = rng.randrange(8)
    regs = [value(rng) for _ in range(8)]
    empty = [rng.random() < 0.7 for _ in range(8)]
    for i in need:
        empty[i] = rng.random() < 0.06
    if push:
        empty[7] = rng.random() < 0.85
    if full:
        empty = [rng.random() < 0.04 for _ in range(8)]
    if rng.random() < 0.85:
        for i in range(8):
            if empty[i]:
                regs[i] = 0
    flags = rng.getrandbits(6) & (cw & 0x3F)
    sw = flags | (rng.getrandbits(1) << 6 if flags & 1 else 0)
    sw |= (top << 11) | (rng.getrandbits(1) << 8) | (rng.getrandbits(1) << 9) | \
        (rng.getrandbits(1) << 10) | (rng.getrandbits(1) << 14)
    if pending:
        sw |= 0x8080 | 0x20
    tw = 0
    for i in range(8):
        p = (top + i) % 8
        t = 3 if empty[i] else tag_of(regs[i])
        tw |= t << (2 * p)
    return cw, sw, tw, regs


def rflags(rng):
    return 0x2 | (rng.getrandbits(1) << 0) | (rng.getrandbits(1) << 2) | (rng.getrandbits(1) << 4) \
        | (rng.getrandbits(1) << 6) | (rng.getrandbits(1) << 7) | (rng.getrandbits(1) << 11)


# ------------------------------------------------------------------ forms

def modrm(md, reg, rm):
    return (md << 6) | (reg << 3) | rm


def mem_form(esc, digit):
    return [0xD8 + esc, modrm(0, digit, 7)]  # [rdi]


def reg_form(esc, reg, i):
    return [0xD8 + esc, modrm(3, reg, i)]


ARITH = {"add": 0, "mul": 1, "sub": 4, "subr": 5, "div": 6, "divr": 7}
ARITH_R = {"add": 0, "mul": 1, "sub": 5, "subr": 4, "div": 7, "divr": 6}


def le(v, n):
    return v.to_bytes(n, "little")


def forms():
    """(name, bytes, memory length, input generator)."""
    F = []

    def add(name, bs, memlen, gen):
        F.append((name, bs, memlen, gen))

    def st2(i):
        def gen(rng):
            cw, sw, tw, regs = state(rng, need=(0, i))
            if rng.random() < 0.6:
                regs[i] = near(rng, regs[0])
                tw = retag(tw, sw, regs)
            return (cw, sw, tw, regs), b""
        return gen

    for op in ARITH:
        for i in (0, 1, 3):
            add(f"{op} st0,st{i}", reg_form(0, ARITH[op], i), 0, st2(i))
        for i in (1, 2):
            add(f"{op} st{i},st0", reg_form(4, ARITH_R[op], i), 0, st2(i))
            add(f"{op}p st{i},st0", reg_form(6, ARITH_R[op], i), 0, st2(i))
        add(f"{op} m32", mem_form(0, ARITH[op]), 4, mem_f(24, 8))
        add(f"{op} m64", mem_form(4, ARITH[op]), 8, mem_f(53, 11))
        add(f"i{op} m16", mem_form(6, ARITH[op]), 2, mem_i(16))
        add(f"i{op} m32", mem_form(2, ARITH[op]), 4, mem_i(32))
    # compares
    for pop in (0, 1):
        add(f"fcom{'p' * pop} m32", mem_form(0, 2 + pop), 4, mem_f(24, 8))
        add(f"fcom{'p' * pop} m64", mem_form(4, 2 + pop), 8, mem_f(53, 11))
        add(f"ficom{'p' * pop} m16", mem_form(6, 2 + pop), 2, mem_i(16))
        add(f"ficom{'p' * pop} m32", mem_form(2, 2 + pop), 4, mem_i(32))
        for i in (1, 2):
            add(f"fcom{'p' * pop} st{i}", reg_form(0, 2 + pop, i), 0, st2(i))
            add(f"fucom{'p' * pop} st{i}", reg_form(5, 4 + pop, i), 0, st2(i))
            add(f"fcomi{'p' * pop} st{i}", reg_form(3 + 4 * pop, 6, i), 0, st2(i))
            add(f"fucomi{'p' * pop} st{i}", reg_form(3 + 4 * pop, 5, i), 0, st2(i))
    add("fcompp", [0xDE, 0xD9], 0, st2(1))
    add("fucompp", [0xDA, 0xE9], 0, st2(1))
    add("ftst", [0xD9, 0xE4], 0, st1())
    add("fxam", [0xD9, 0xE5], 0, st1())
    # loads
    add("fld m32", mem_form(1, 0), 4, mem_f(24, 8, push=True))
    add("fld m64", mem_form(5, 0), 8, mem_f(53, 11, push=True))
    add("fld m80", mem_form(3, 5), 10, mem_80(push=True))
    for i in (0, 1, 5):
        add(f"fld st{i}", reg_form(1, 0, i), 0, st1(push=True, need=(i,)))
    add("fild m16", mem_form(7, 0), 2, mem_i(16, push=True))
    add("fild m32", mem_form(3, 0), 4, mem_i(32, push=True))
    add("fild m64", mem_form(7, 5), 8, mem_i(64, push=True))
    for k, c in enumerate([0xE8, 0xE9, 0xEA, 0xEB, 0xEC, 0xED, 0xEE]):
        add(f"fldconst {c:x}", [0xD9, c], 0, st1(push=True, need=()))
    # stores
    add("fst m32", mem_form(1, 2), 4, st1())
    add("fstp m32", mem_form(1, 3), 4, st1())
    add("fst m64", mem_form(5, 2), 8, st1())
    add("fstp m64", mem_form(5, 3), 8, st1())
    add("fstp m80", mem_form(3, 7), 10, st1())
    for i in (0, 1, 4):
        add(f"fst st{i}", reg_form(5, 2, i), 0, st1())
        add(f"fstp st{i}", reg_form(5, 3, i), 0, st1())
    for name, esc, dg, bits in [("fist m16", 7, 2, 16), ("fist m32", 3, 2, 32),
                                ("fistp m16", 7, 3, 16), ("fistp m32", 3, 3, 32),
                                ("fistp m64", 7, 7, 64), ("fisttp m16", 7, 1, 16),
                                ("fisttp m32", 3, 1, 32), ("fisttp m64", 5, 1, 64)]:
        add(name, mem_form(esc, dg), bits // 8, st_int(bits))
    # stack and control
    for i in (0, 1, 3):
        add(f"fxch st{i}", reg_form(1, 1, i), 0, st2(i))
        add(f"ffree st{i}", reg_form(5, 0, i), 0, st1())
    for k, (esc, reg) in enumerate([(2, 0), (2, 1), (2, 2), (2, 3), (3, 0), (3, 1), (3, 2), (3, 3)]):
        for i in (1, 2):
            add(f"fcmov{k} st{i}", reg_form(esc, reg, i), 0, st2(i))
    add("fincstp", [0xD9, 0xF7], 0, st1())
    add("fdecstp", [0xD9, 0xF6], 0, st1())
    add("fnop", [0xD9, 0xD0], 0, st1())
    add("fwait", [0x9B], 0, st1())
    add("fnclex", [0xDB, 0xE2], 0, st1(unmask=0.6))
    add("fninit", [0xDB, 0xE3], 0, st1())
    add("fnstsw ax", [0xDF, 0xE0], 0, st1(unmask=0.6))
    add("fnstsw m16", mem_form(5, 7), 2, st1(unmask=0.6))
    add("fnstcw m16", mem_form(1, 7), 2, st1())
    add("fldcw m16", mem_form(1, 5), 2, mem_cw())
    add("fldenv m28", mem_form(1, 4), 28, mem_env(28))
    add("frstor m108", mem_form(5, 4), 108, mem_env(108))
    # unary
    for name, c in [("fchs", 0xE0), ("fabs", 0xE1), ("fsqrt", 0xFA), ("frndint", 0xFC)]:
        add(name, [0xD9, c], 0, st1())
    add("fscale", [0xD9, 0xFD], 0, st_scale())
    add("fxtract", [0xD9, 0xF4], 0, st1(push=True))
    add("fprem", [0xD9, 0xF8], 0, st_prem())
    add("fprem1", [0xD9, 0xF5], 0, st_prem())
    return F


def retag(tw, sw, regs):
    top = (sw >> 11) & 7
    out = 0
    for i in range(8):
        p = (top + i) % 8
        t = (tw >> (2 * p)) & 3
        if t != 3:
            t = tag_of(regs[i])
        out |= t << (2 * p)
    return out


def st1(push=False, need=(0,), unmask=0.15):
    def gen(rng):
        return state(rng, need=need, push=push, unmask=unmask), b""
    return gen


def st_int(bits):
    def gen(rng):
        cw, sw, tw, regs = state(rng)
        if rng.random() < 0.6:
            regs[0] = int_like80(rng, bits)
            tw = retag(tw, sw, regs)
        return (cw, sw, tw, regs), bytes(bits // 8)
    return gen


def st_scale():
    def gen(rng):
        cw, sw, tw, regs = state(rng, need=(0, 1))
        if rng.random() < 0.7:
            regs[1] = int_val(rng.choice([rng.randint(-70, 70), rng.randint(-20000, 20000),
                                          rng.randint(-40000, 40000)]))
            if rng.random() < 0.3:
                regs[1] = near(rng, regs[1]) if regs[1] else regs[1]
            tw = retag(tw, sw, regs)
        return (cw, sw, tw, regs), b""
    return gen


def st_prem():
    def gen(rng):
        cw, sw, tw, regs = state(rng, need=(0, 1))
        if rng.random() < 0.7:
            e1 = rng.randint(100, 0x7FFE - 200)
            d = rng.choice([rng.randint(-3, 70), rng.randint(60, 140), rng.randint(0, 20000)])
            regs[1] = f80(rng.getrandbits(1), e1, (1 << 63) | rng.getrandbits(63))
            regs[0] = f80(rng.getrandbits(1), max(1, min(0x7FFE, e1 + d)),
                          (1 << 63) | rng.getrandbits(63))
            tw = retag(tw, sw, regs)
        return (cw, sw, tw, regs), b""
    return gen


def mem_f(p, w, push=False):
    n = (p + w) // 8

    def gen(rng):
        st = state(rng, need=() if push else (0,), push=push)
        return st, le(ieee_value(rng, p, w), n)
    return gen


def mem_80(push=False):
    def gen(rng):
        return state(rng, need=(), push=push), le(value(rng), 10)
    return gen


def mem_i(bits, push=False):
    def gen(rng):
        st = state(rng, need=() if push else (0,), push=push)
        return st, le(int_mem(rng, bits), bits // 8)
    return gen


def mem_cw():
    def gen(rng):
        st = state(rng, unmask=0.0)
        v = rng.choice([control(rng, 0.5), rng.getrandbits(16), 0x037F, 0x027F, 0x0F7F])
        return st, le(v, 2)
    return gen


def mem_env(n):
    def gen(rng):
        st = state(rng)
        cw, sw, tw, regs = state(rng, unmask=0.3)
        img = H.image(cw, sw, tw, regs)
        if n == 28:
            img = img[:28]
        return st, img
    return gen


# ------------------------------------------------------------------ running

def vectors(seed, scale):
    rng = random.Random(seed)
    F = forms()
    exe = H.build([bs for _, bs, _, _ in F])
    cases, meta = [], []
    for idx, (name, bs, memlen, gen) in enumerate(F):
        for _ in range(scale):
            (cw, sw, tw, regs), mem = gen(rng)
            pending = rng.random() < 0.02
            if pending:
                sw |= 0x80A0
                cw &= ~0x20
            cases.append((idx, cw, sw, tw, regs, mem, memlen, rng.getrandbits(64), rflags(rng)))
            meta.append(bs)
    res = H.run(exe, cases)
    return [(bs, c, r) for bs, c, r in zip(meta, cases, res)]


def phys(sw, regs):
    """ST(0)..ST(7) to physical registers R0..R7."""
    top = (sw >> 11) & 7
    return [regs[(p - top) % 8] for p in range(8)]


def line(bs, c, r):
    _, cw, sw, tw, regs, mem, memlen, rax, fl = c
    enc = "".join("%02x" % b for b in bs)
    memv = int.from_bytes(mem.ljust(memlen, b"\0"), "little") if memlen else 0
    ins = [cw, sw, tw] + phys(sw, regs) + [memlen, memv, rax, fl]
    head = [enc] + ["%x" % v for v in ins]
    if r is None:
        return " ".join(head + ["0"])
    cw2, sw2, tw2, regs2, mem2, rax2, fl2 = r
    memv2 = int.from_bytes(mem2[:memlen], "little") if memlen else 0
    outs = [cw2, sw2, tw2] + phys(sw2, regs2) + [memv2, rax2, fl2]
    same = ins[:11] + ins[12:]
    tail = ["." if o == i else "%x" % o for o, i in zip(outs, same)]
    return " ".join(head + ["1"] + tail)


def write_vectors(vecs, chunk):
    groups = [vecs[i:i + chunk] for i in range(0, len(vecs), chunk)]
    names = []
    for k, g in enumerate(groups):
        name = "Exec%d" % k
        names.append(name)
        lines = [HEADER, "/-! x87 instructions executed natively (see the generator); each line is",
                 "checked by `Fpu.Checks.checkLine`. -/", "",
                 f"namespace Silmaril.X86.Features.Fpu.Vectors.{name}", "",
                 "open Silmaril.X86.Features.Fpu.Checks", "",
                 "def vectors : String := \""]
        lines += [line(*v) for v in g]
        lines[-1] += "\""
        lines += ["", "#guard (vectorLines vectors).length = %d" % len(g), "",
                  "#guard (vectorLines vectors).all checkLine", "",
                  "/-- Vectors on which the model is `unmodeled` (the biased results of",
                  "unmasked overflow and underflow, and reserved precision control). -/",
                  "def unmodeledCount : Nat := ((vectorLines vectors).filter unmodeledLine).length",
                  "",
                  f"end Silmaril.X86.Features.Fpu.Vectors.{name}", ""]
        with open(os.path.join(OUT, name + ".lean"), "w") as f:
            f.write("\n".join(lines))
    return names


