#!/usr/bin/env python3
"""Generate the x87 differential test vectors of Silmaril/X86/Features/Ext/X87/Vectors.

Oracle: the host processor (an Intel Core i7-8700 when the committed vectors
were generated), executing every instruction form natively through
`x87_harness.py`: FRSTOR loads a random x87 state (control word with every
precision and rounding control, masked and unmasked exceptions, status word
with random TOP and condition codes, tag word, register contents including
denormals, pseudo-denormals, unnormals, NaNs, infinities and values near the
exponent limits), the instruction runs on a memory operand at [rdi], and
FNSAVE records the resulting state. The instruction bytes are emitted with
`.byte`, so they are exactly the SDM encodings; Lean decodes them with
`Fpu.byteDecoder` and executes them with `Fpu.ext.exec`.

Each vector line is, in hex:

    enc cw sw tw st0..st7 memlen mem rax rflags ok [cw' sw' tw' st0'..st7' mem' rax' rflags']

`enc` is the instruction bytes (big-endian), `mem` the memory operand bytes as a
little-endian number, `ok` is 1 when the instruction retired and 0 when it
raised #MF (SIGFPE; then nothing follows).

A second file checks the encoder against the GNU assembler: for a list of
Intel-syntax instructions with varied memory operands, `Fpu.encode` of the Lean
term equals the bytes `as` produced.

Usage: gen_x87_vectors.py [--seed N] [--scale K]
"""

