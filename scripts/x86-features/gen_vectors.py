#!/usr/bin/env python3
"""Generate the differential test vectors of Silmaril/X86/Features/Vectors.

Two oracles, both executed for real:

* CPUID: `cpuid_dump.c` prints the CPUID leaves `FeatureSet.ofCpuid` reads, XCR0
  (XGETBV) and the features libgcc's `__builtin_cpu_supports` reports. It runs
  natively and under qemu-x86_64 (TCG) for several CPU models. Lean checks that
  `ofCpuid` of the dumped leaves equals libgcc's answer.
* ROUNDSS/ROUNDSD (SSE4.1, the transport counterexample): a generated C harness
  executes `roundss/roundsd xmm0, xmm1, imm8` for all sixteen imm8 values, every
  MXCSR rounding mode with DAZ/FZ, over edge-case and random operands, natively
  (the host must have SSE4.1). Lean checks that `floatExt.exec` on the extended
  state yields the same XMM0 (with bits 511:128 kept) and MXCSR.

Usage: gen_vectors.py [--qemu PATH] [--seed N]
Writes Silmaril/X86/Features/Vectors/{Cpuid,Round}.lean.
"""

import argparse
import os
import random
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "Silmaril", "X86", "Features", "Vectors")

GCC_TO_LEAN = {
    "sse": "sse", "sse2": "sse2", "sse3": "sse3", "ssse3": "ssse3", "sse4.1": "sse41",
    "sse4.2": "sse42", "popcnt": "popcnt", "lzcnt": "lzcnt", "bmi": "bmi1", "bmi2": "bmi2",
    "adx": "adx", "movbe": "movbe", "rdrnd": "rdrand", "rdseed": "rdseed", "aes": "aes",
    "pclmul": "pclmulqdq", "sha": "sha", "gfni": "gfni", "avx": "avx", "avx2": "avx2",
    "fma": "fma", "f16c": "f16c", "vaes": "vaes", "vpclmulqdq": "vpclmulqdq",
    "avx512f": "avx512f", "avx512cd": "avx512cd", "avx512bw": "avx512bw",
    "avx512dq": "avx512dq", "avx512vl": "avx512vl", "avx512ifma": "avx512ifma",
    "avx512vbmi": "avx512vbmi", "avx512vbmi2": "avx512vbmi2", "avx512vnni": "avx512vnni",
    "avx512bitalg": "avx512bitalg", "avx512vpopcntdq": "avx512vpopcntdq",
}

QEMU_MODELS = ["max", "qemu64", "core2duo", "Nehalem", "Westmere", "SandyBridge", "Haswell",
               "Broadwell", "Skylake-Client", "Skylake-Server", "Icelake-Server", "EPYC"]

HEADER = """-- Generated by scripts/x86-features/gen_vectors.py; do not edit.
module

public import Silmaril.X86.Features.Checks
public meta import Silmaril.X86.Features.Checks

"""


def run(cmd, **kw):
    return subprocess.run(cmd, check=True, capture_output=True, text=True, **kw).stdout


def cpuid_vectors(qemu):
    exe = os.path.join(tempfile.mkdtemp(), "cpuid_dump")
    run(["gcc", "-O1", "-o", exe, os.path.join(HERE, "cpuid_dump.c")])
    cases = [("native", [exe])]
    if qemu:
        cases += [(f"qemu -cpu {m}", [qemu, "-cpu", m, exe]) for m in QEMU_MODELS]
    out = []
    for name, cmd in cases:
        try:
            text = run(cmd)
        except subprocess.CalledProcessError as e:
            print(f"skip {name}: {e}", file=sys.stderr)
            continue
        rows, xcr0, feats = [], 0, []
        for line in text.splitlines():
            parts = line.split()
            if parts[0] == "xcr0":
                xcr0 = int(parts[1], 16)
            elif parts[0] == "gcc":
                feats = [GCC_TO_LEAN[p] for p in parts[1:]]
            else:
                rows.append(tuple(int(p, 16) for p in parts))
        # x87 (CPUID.1:EDX[0]) has no libgcc name; every x86-64 processor has it.
        out.append((name, rows, xcr0, ["x87"] + feats))
    return out


def write_cpuid(cases):
    lines = [HEADER, "/-! CPUID dumps (native and qemu-x86_64 TCG models) with libgcc's",
             "`__builtin_cpu_supports` as the expected feature set. -/", "",
             "@[expose] public section", "",
             "namespace Silmaril.X86.Features.Vectors.Cpuid", "",
             "open Silmaril.X86.Features", "",
             "/-- (name, CPUID rows (leaf, subleaf, eax, ebx, ecx, edx), XCR0, expected). -/",
             "def cases : List (String × List (Nat × Nat × Nat × Nat × Nat × Nat) × Nat ×",
             "    List Feature) := ["]
    for i, (name, rows, xcr0, feats) in enumerate(cases):
        rs = ", ".join("(0x%x, 0x%x, 0x%x, 0x%x, 0x%x, 0x%x)" % r for r in rows)
        fs = ", ".join("." + f for f in feats)
        sep = "," if i + 1 < len(cases) else ""
        lines.append(f'  ("{name}", [{rs}],\n    0x{xcr0:x}, [{fs}]){sep}')
    lines += ["]", "", "#guard cases.length = %d" % len(cases), "",
              "#guard cases.all fun (_, rows, xcr0, expected) => checkCpuid rows xcr0 expected", "",
              "end Silmaril.X86.Features.Vectors.Cpuid", ""]
    with open(os.path.join(OUT, "Cpuid.lean"), "w") as f:
        f.write("\n".join(lines))


# ---------------------------------------------------------------- ROUNDSS/SD

F32_EDGE = [0x00000000, 0x80000000, 0x00000001, 0x80000001, 0x007fffff, 0x00800000,
            0x3f000000, 0xbf000000, 0x3fc00000, 0xbfc00000, 0x40200000, 0xc0200000,
            0x3f800001, 0x4b000000, 0x4b000001, 0x4affffff, 0x7f7fffff, 0x7f800000,
            0xff800000, 0x7fc00000, 0xffc00001, 0x7f800001, 0xff800123, 0x3effffff]
F64_EDGE = [0x0, 0x8000000000000000, 0x1, 0x8000000000000001, 0x000fffffffffffff,
            0x0010000000000000, 0x3fe0000000000000, 0xbfe0000000000000, 0x3ff8000000000000,
            0xbff8000000000000, 0x4004000000000000, 0xc004000000000000, 0x3ff0000000000001,
            0x4330000000000000, 0x4330000000000001, 0x432fffffffffffff, 0x7fefffffffffffff,
            0x7ff0000000000000, 0xfff0000000000000, 0x7ff8000000000000, 0xfff8000000000001,
            0x7ff0000000000001, 0xfff0000000000123, 0x3fdfffffffffffff]
MXCSRS = [0x1F80, 0x3F80, 0x5F80, 0x7F80, 0x1FC0, 0x9F80, 0xFFC0]


def rand_f32(rng):
    e = rng.choice([rng.randrange(0, 256), rng.randrange(110, 160)])
    return (rng.getrandbits(1) << 31) | (e << 23) | rng.getrandbits(23)


def rand_f64(rng):
    e = rng.choice([rng.randrange(0, 2048), rng.randrange(1000, 1100)])
    return (rng.getrandbits(1) << 63) | (e << 52) | rng.getrandbits(52)


ROUND_C = r"""
#include <stdint.h>
#include <stdio.h>
#include <string.h>
#include <immintrin.h>

#define CASE(I) case I: \
  if (dbl) __asm__ volatile("ldmxcsr %3\n\troundsd $" #I ", %2, %0\n\tstmxcsr %1" \
                            : "+x"(d), "=m"(out) : "x"(s), "m"(mx)); \
  else __asm__ volatile("ldmxcsr %3\n\troundss $" #I ", %2, %0\n\tstmxcsr %1" \
                            : "+x"(d), "=m"(out) : "x"(s), "m"(mx)); \
  break;

int main(void) {
  unsigned dbl, imm, mx;
  unsigned long long src, dlo, dhi;
  while (scanf("%u %u %x %llx %llx %llx", &dbl, &imm, &mx, &src, &dlo, &dhi) == 6) {
    __m128i d = _mm_set_epi64x((long long)dhi, (long long)dlo);
    __m128i s = _mm_set_epi64x(0x0123456789abcdefLL, (long long)src);
    unsigned out = 0;
    switch (imm) {
      CASE(0) CASE(1) CASE(2) CASE(3) CASE(4) CASE(5) CASE(6) CASE(7)
      CASE(8) CASE(9) CASE(10) CASE(11) CASE(12) CASE(13) CASE(14) CASE(15)
    }
    unsigned reset = 0x1F80;
    __asm__ volatile("ldmxcsr %0" : : "m"(reset));
    unsigned long long r[2];
    memcpy(r, &d, 16);
    printf("%llx %llx %x\n", r[0], r[1], out);
  }
  return 0;
}
"""


def round_vectors(seed):
    rng = random.Random(seed)
    tmp = tempfile.mkdtemp()
    src = os.path.join(tmp, "round.c")
    exe = os.path.join(tmp, "round")
    with open(src, "w") as f:
        f.write(ROUND_C)
    run(["gcc", "-O1", "-msse4.1", "-o", exe, src])
    inputs = []
    for dbl, edge, rnd in [(0, F32_EDGE, rand_f32), (1, F64_EDGE, rand_f64)]:
        operands = edge + [rnd(rng) for _ in range(8)]
        for x in operands:
            for imm in range(16):
                for mx in MXCSRS:
                    dlo, dhi = rng.getrandbits(64), rng.getrandbits(64)
                    inputs.append((dbl, imm, mx, x, dlo, dhi))
    text = "".join("%d %d %x %x %x %x\n" % v for v in inputs)
    res = subprocess.run([exe], input=text, check=True, capture_output=True, text=True).stdout
    outs = [tuple(int(p, 16) for p in l.split()) for l in res.splitlines()]
    assert len(outs) == len(inputs)
    return [(i, o) for i, o in zip(inputs, outs)]


def write_round(vecs):
    lines = [HEADER, "/-! ROUNDSS/ROUNDSD executed natively (see the generator). Each line is",
             "`double? imm8 MXCSR source dst.lo dst.hi result.lo result.hi MXCSR-after`, in hex",
             "(`checkRoundLine`). -/", "",
             "namespace Silmaril.X86.Features.Vectors.Round", "",
             "open Silmaril.X86.Features", "",
             "public def vectors : String := \""]
    for (dbl, imm, mx, x, dlo, dhi), (rlo, rhi, mo) in vecs:
        lines.append("%x %x %x %x %x %x %x %x %x" % (dbl, imm, mx, x, dlo, dhi, rlo, rhi, mo))
    lines[-1] += "\""
    lines += ["", "#guard (hexFields vectors).length = %d" % len(vecs), "",
              "#guard (hexFields vectors).all checkRoundLine", "",
              "end Silmaril.X86.Features.Vectors.Round", ""]
    with open(os.path.join(OUT, "Round.lean"), "w") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--qemu", default=os.environ.get("QEMU_X86_64"))
    ap.add_argument("--seed", type=int, default=20261025)
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    write_cpuid(cpuid_vectors(args.qemu))
    write_round(round_vectors(args.seed))


if __name__ == "__main__":
    main()
