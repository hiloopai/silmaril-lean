#!/usr/bin/env python3
"""Write Silmaril/X86/Features/Ext/Avx/Ops.lean from the table in avx_ops.py."""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from avx_ops import ROWS  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "Silmaril", "X86", "Features", "Ext", "Avx", "Ops.lean")

PP = {"": 0, "66": 1, "F3": 2, "F2": 3}


def opt(v, f=str):
    return "none" if v is None else f"some {f(v)}"


def main():
    names = [r["name"] for r in ROWS]
    assert len(set(names)) == len(names), "duplicate constructor"
    out = []
    out.append("""-- Generated by scripts/x86-features/gen_avx_ops.py from avx_ops.py; do not edit.
module

public import Silmaril.X86.Features.Feature

/-!
# The VEX opcode table of the `avx` lane

One constructor per instruction form, with the fields of its SDM Vol. 2 opcode
column `VEX.L.pp.map.W opcode` (`Op.info`): the implied prefix `pp` (0 none,
1 `66`, 2 `F3`, 3 `F2`), the opcode map `mmmmm` (1 `0F`, 2 `0F38`, 3 `0F3A`), the
opcode byte, a fixed VEX.W or VEX.L (`none` when the field is ignored or selects
the form), the ModRM.reg extension of `/digit` forms, what ModRM.rm may be, whether
VEX.vvvv names an operand, and the CPUID rule (`FeatClass`).
-/

@[expose] public section

namespace Silmaril.X86.Features.Avx

/-- What the ModRM.rm operand of a form may be. -/
inductive Kind where
  /-- A register or memory. -/
  | any
  /-- A register only (`mod = 11`). -/
  | reg
  /-- Memory only. -/
  | mem
  /-- No ModRM byte (VZEROUPPER, VZEROALL). -/
  | none
  deriving DecidableEq, Repr

/-- The CPUID rule of a form (SDM Vol. 2, the CPUID feature flag column):

* `int`: VEX.128 needs AVX, VEX.256 needs AVX2 (the integer instructions);
* `avx`, `avx2`, `fma`, `f16c`: that feature at every length;
* `bcast`: VBROADCASTSS/SD: AVX for a memory source, AVX2 for a register;
* `aes`: AES and AVX for VEX.128, VAES for VEX.256;
* `clmul`: PCLMULQDQ and AVX for VEX.128, VPCLMULQDQ for VEX.256;
* `gfni`: GFNI and AVX. -/
inductive FeatClass where
  | int | avx | avx2 | bcast | aes | clmul | gfni | fma | f16c
  deriving DecidableEq, Repr

/-- The opcode fields of a form. -/
structure OpInfo where
  pp : BitVec 2
  map : BitVec 5
  opc : BitVec 8
  w : Option Bool
  l : Option Bool
  digit : Option (BitVec 3)
  kind : Kind
  vvvv : Bool
  feat : FeatClass
  deriving DecidableEq, Repr

/-- The instruction forms of the lane. -/
inductive Op where""")
    for r in ROWS:
        out.append(f"  /-- `{r['mnem']}` -/")
        out.append(f"  | {r['name']}")
    out.append("  deriving DecidableEq, Repr")
    out.append("")
    out.append("namespace Op")
    out.append("")
    out.append("/-- The opcode fields of each form. -/")
    out.append("def info : Op → OpInfo")
    for r in ROWS:
        w = opt(r["w"], lambda v: "true" if v else "false")
        l = opt(r["l"], lambda v: "true" if v else "false")
        d = opt(r["digit"], lambda v: f"{v}#3")
        vv = "true" if r["vvvv"] else "false"
        out.append(f"  | {r['name']} => ⟨{PP[r['pp']]}#2, {r['map']}#5, 0x{r['opc']:02X}#8, {w}, {l}, "
                   f"{d}, .{r['kind']}, {vv}, .{r['feat']}⟩")
    out.append("")
    out.append("/-- The assembler mnemonic (without the `d`/`q`/`s` suffix that VEX.W selects). -/")
    out.append("def mnemonic : Op → String")
    for r in ROWS:
        out.append(f"  | {r['name']} => \"{r['mnem']}\"")
    out.append("")
    out.append("set_option maxRecDepth 8000 in")
    out.append("/-- Every form, once. -/")
    out.append("def all : List Op := [")
    line = "  "
    items = [f"{r['name']}" for r in ROWS]
    for i, it in enumerate(items):
        piece = it + (", " if i + 1 < len(items) else "")
        if len(line) + len(piece) > 98:
            out.append(line.rstrip())
            line = "  "
        line += piece
    out.append(line.rstrip() + "]")
    out.append("")
    out.append("set_option maxRecDepth 8000 in")
    out.append(f"theorem length_all : all.length = {len(ROWS)} := rfl")
    out.append("")
    out.append("end Op")
    out.append("")
    out.append("end Silmaril.X86.Features.Avx")
    out.append("")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print(f"wrote {OUT}: {len(ROWS)} forms")


if __name__ == "__main__":
    main()
