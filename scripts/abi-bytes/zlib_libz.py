#!/usr/bin/env python3
"""Emit the code and read-only data bytes of the libz.so.1.3 conformance rows as a Lean module.

Reads the pinned `examples/elf/pinned/zlib-libz.so.1.3` (its SHA-256 is checked), finds the four
checksum entry points in `.dynsym` and the read-only `PT_LOAD` at 0x14000, checks their values and
sizes against the ones the rows state, and writes `Silmaril.Machine.Abi.Conformance.ZlibLibz.Bytes`:
each byte string as a literal `List (BitVec 8)`. The literals are untrusted data: the theorems of
`Silmaril.Elf.Abi.ZlibLibz.Thms` check them against the file's kernel bytes.

usage: python3 -I scripts/abi-bytes/zlib_libz.py [--check]
"""
import hashlib, pathlib, struct, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
ELF = "examples/elf/pinned/zlib-libz.so.1.3"
SHA256 = "f61677c7bdb7c2aa2a243ea781bfd16afcb361cede7b4ef76127a9d8eb9a5242"
OUT = "Silmaril/Machine/Abi/Conformance/ZlibLibz/Bytes.lean"
NS = "Silmaril.Machine.Abi.Conformance.ZlibLibz"

# (symbol, st_value, st_size), as `readelf --dyn-syms` prints them.
FUNCS = [("crc32_z", 0x7440, 2798), ("crc32", 0x7f30, 11),
         ("adler32_z", 0x6ba0, 1716), ("adler32", 0x7260, 11)]
# The read-only data segment: (p_vaddr, p_memsz).
RODATA = (0x14000, 0x5e74)


def parse(data):
    if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        sys.exit(f"{ELF}: not a little-endian ELF64 file")
    (_, _, _, _, phoff, shoff, _, _, phentsize, phnum, shentsize, shnum, _) = struct.unpack_from(
        "<HHIQQQIHHHHHH", data, 16)
    phdrs = [struct.unpack_from("<IIQQQQQQ", data, phoff + i * phentsize) for i in range(phnum)]
    shdrs = [struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * shentsize) for i in range(shnum)]
    syms = {}
    for sh in shdrs:
        if sh[1] != 11:  # SHT_DYNSYM
            continue
        strtab = shdrs[sh[6]]
        for k in range(sh[5] // sh[9]):
            name, info, _, shndx, value, size = struct.unpack_from("<IBBHQQ", data, sh[4] + k * sh[9])
            off = strtab[4] + name
            nm = data[off:data.index(b"\0", off)].decode()
            if shndx != 0 and info & 0xf == 2:  # defined STT_FUNC
                syms.setdefault(nm, []).append((value, size))
    return phdrs, syms


def read(data, phdrs, vaddr, n, flags):
    """The `n` bytes at `vaddr` from the `PT_LOAD` with exactly `flags` mapping them from the file."""
    for kind, fl, off, va, _, filesz, _, _ in phdrs:
        if kind == 1 and fl == flags and va <= vaddr and vaddr + n <= va + filesz:
            return data[off + vaddr - va:off + vaddr - va + n]
    sys.exit(f"{ELF}: no PT_LOAD with flags {flags} maps [{vaddr:#x}, {vaddr + n:#x})")


def lean_bytes(name, doc, bs):
    out = [f"/-- {doc} -/", f"def {name} : List (BitVec 8) := ["]
    rows = [bs[i:i + 16] for i in range(0, len(bs), 16)]
    for k, row in enumerate(rows):
        sep = "," if k + 1 < len(rows) else ""
        out.append("  " + ", ".join(f"0x{b:02x}" for b in row) + sep)
    out += ["]", ""]
    return out


def main(argv):
    check = "--check" in argv
    data = (ROOT / ELF).read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        sys.exit(f"{ELF}: SHA-256 differs from the pin {SHA256}")
    phdrs, syms = parse(data)
    for name, value, size in FUNCS:
        if syms.get(name) != [(value, size)]:
            sys.exit(f"{ELF}: .dynsym {name} is {syms.get(name)}, expected [({value:#x}, {size})]")
    (cz, czv, czn), (cw, cwv, cwn), (az, azv, azn), (aw, awv, awn) = FUNCS
    rx = 5  # PF_R | PF_X
    body = [
        "module", "",
        f"/-! # zlib 1.3 `libz.so.1.3` (Ubuntu zlib1g 1:1.3.dfsg-3.1ubuntu2.3): the bytes of the conformance rows",
        "",
        "GENERATED by `scripts/abi-bytes/zlib_libz.py` from `examples/elf/pinned/zlib-libz.so.1.3`",
        f"(SHA-256 `{SHA256}`); do not edit.",
        "",
        "Untrusted data: the code of the four checksum entry points (by their `.dynsym` values and",
        "sizes), the bytes between each `_z` function and its wrapper, and the read-only `PT_LOAD` at",
        "`0x14000` (`.rodata`, `.eh_frame_hdr`, `.eh_frame`; the CRC tables). Nothing here is believed",
        "until a theorem of `Silmaril.Elf.Abi.ZlibLibz.Thms` checks it against the file's bytes. -/",
        "", "set_option maxRecDepth 100000", "", "@[expose] public section", "", f"namespace {NS}", "",
    ]
    body += lean_bytes("crc32zBytes", f"`{cz}` (`{czv:#x}`, {czn} bytes).", read(data, phdrs, czv, czn, rx))
    body += lean_bytes("crcGap", f"The bytes between `{cz}`'s end (`{czv + czn:#x}`) and `{cw}` (`{cwv:#x}`).",
                       read(data, phdrs, czv + czn, cwv - czv - czn, rx))
    body += lean_bytes("crc32Bytes", f"`{cw}` (`{cwv:#x}`, {cwn} bytes): `endbr64; mov %edx,%edx; jmp {cz}`.",
                       read(data, phdrs, cwv, cwn, rx))
    body += lean_bytes("adler32zBytes", f"`{az}` (`{azv:#x}`, {azn} bytes).", read(data, phdrs, azv, azn, rx))
    body += lean_bytes("adlerGap", f"The bytes between `{az}`'s end (`{azv + azn:#x}`) and `{aw}` (`{awv:#x}`).",
                       read(data, phdrs, azv + azn, awv - azv - azn, rx))
    body += lean_bytes("adler32Bytes", f"`{aw}` (`{awv:#x}`, {awn} bytes): `endbr64; mov %edx,%edx; jmp {az}`.",
                       read(data, phdrs, awv, awn, rx))
    body += lean_bytes("rodata", f"The read-only `PT_LOAD` at `{RODATA[0]:#x}` ({RODATA[1]} bytes).",
                       read(data, phdrs, RODATA[0], RODATA[1], 4))
    body += [f"end {NS}", ""]
    text = "\n".join(body)
    out = ROOT / OUT
    if check:
        if not out.exists() or out.read_text() != text:
            sys.exit(f"{OUT}: out of date (python3 -I scripts/abi-bytes/zlib_libz.py)")
        print(f"{OUT}: up to date")
        return
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)


if __name__ == "__main__":
    main(sys.argv[1:])
