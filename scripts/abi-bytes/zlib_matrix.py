#!/usr/bin/env python3
"""Emit the code and read-only data of the zlib library-matrix conformance rows as Lean modules.

For each pinned binary below (its SHA-256 is checked), finds the claimed entry points in
`.dynsym`, checks their values, sizes, symbol types and versions against the configuration, and
writes `Silmaril/Machine/Abi/Conformance/ZlibMatrix/<Name>/Bytes.lean` (each byte string as a
literal `List (BitVec 8)`) and `.../<Name>/Defs.lean` (the `Code` regions). The literals are
untrusted data: the theorems of `Silmaril.Elf.Abi.ZlibMatrix.Thms` check them against the file's
kernel bytes.

usage: python3 -I scripts/abi-bytes/zlib_matrix.py [--check]
"""
import hashlib, pathlib, struct, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
NS = "Silmaril.Machine.Abi.Conformance.ZlibMatrix"
OUT = "Silmaril/Machine/Abi/Conformance/ZlibMatrix"

# Each binary: Lean name, file, SHA-256, description, and the claimed regions. A region is
# (Lean name, symbol, st_value, st_size, versioned, wrapper-of): a wrapper `jmp`s directly to the
# `_z` function named and its region starts there (the bytes in between are carried).
BINARIES = [
    dict(name="Libz1211", file="examples/elf/pinned/zlib-libz.so.1.2.11",
         sha="64c206f0146cc58bbddc4f22054436f4ff278f5a554aa3ce6921ddf7e9133370",
         what="zlib 1.2.11 `libz.so.1.2.11` (Ubuntu zlib1g 1:1.2.11.dfsg-2ubuntu9.2)",
         funcs=[("adler32z", "adler32_z", 0x6d10, 1742, True, None),
                ("adler32", "adler32", 0x73e0, 11, False, "adler32_z")],
         crc=False),
    dict(name="Libz131Gcc", file="examples/libs/zlib/pinned/libz.so.1.3.1-gcc-13",
         sha="cc4d841d56109a1c8f2271a6c33e304128aee44e7e822f81458e3b4f82f160c8",
         what="zlib 1.3.1 `libz.so.1.3.1` built by GCC 13.3 `-O2` (`examples/libs/zlib`)",
         funcs=[("crc32z", "crc32_z", 0x3d60, 1041, True, None),
                ("adler32z", "adler32_z", 0x36e0, 1137, True, None)],
         crc=True),
    dict(name="Libz131Clang", file="examples/libs/zlib/pinned/libz.so.1.3.1-clang-18",
         sha="d4e99da347fa22efa759cbb2f9fa47d9199ff898e6927841bb4543d0c21f83a6",
         what="zlib 1.3.1 `libz.so.1.3.1` built by Clang 18.1 `-O2` (`examples/libs/zlib`)",
         funcs=[("crc32z", "crc32_z", 0x39a0, 2176, True, None),
                ("adler32z", "adler32_z", 0x3370, 1067, True, None)],
         crc=True),
]

PF_X, PF_R = 1, 4


def parse(data, path):
    if data[:4] != b"\x7fELF" or data[4] != 2 or data[5] != 1:
        sys.exit(f"{path}: not a little-endian ELF64 file")
    (_, _, _, _, phoff, shoff, _, _, phentsize, phnum, shentsize, shnum, _) = struct.unpack_from(
        "<HHIQQQIHHHHHH", data, 16)
    phdrs = [struct.unpack_from("<IIQQQQQQ", data, phoff + i * phentsize) for i in range(phnum)]
    shdrs = [struct.unpack_from("<IIQQQQIIQQ", data, shoff + i * shentsize) for i in range(shnum)]
    syms, versym = {}, None
    for sh in shdrs:
        if sh[1] == 0x6fffffff:  # SHT_GNU_versym
            versym = sh
    for sh in shdrs:
        if sh[1] != 11:  # SHT_DYNSYM
            continue
        strtab = shdrs[sh[6]]
        for k in range(sh[5] // sh[9]):
            name, info, _, shndx, value, size = struct.unpack_from("<IBBHQQ", data, sh[4] + k * sh[9])
            off = strtab[4] + name
            nm = data[off:data.index(b"\0", off)].decode()
            ver = struct.unpack_from("<H", data, versym[4] + 2 * k)[0] & 0x7fff if versym else 1
            if shndx != 0:
                syms.setdefault(nm, []).append((value, size, info & 0xf, ver > 1))
    return phdrs, syms


def read(data, phdrs, vaddr, n, flags, path):
    """The `n` bytes at `vaddr` from the `PT_LOAD` with exactly `flags` mapping them from the file."""
    for kind, fl, off, va, _, filesz, _, _ in phdrs:
        if kind == 1 and fl == flags and va <= vaddr and vaddr + n <= va + filesz:
            return data[off + vaddr - va:off + vaddr - va + n]
    sys.exit(f"{path}: no PT_LOAD with flags {flags} maps [{vaddr:#x}, {vaddr + n:#x})")


def lean_bytes(name, doc, bs):
    out = [f"/-- {doc} -/", f"def {name} : List (BitVec 8) := ["]
    rows = [bs[i:i + 16] for i in range(0, len(bs), 16)]
    for k, row in enumerate(rows):
        sep = "," if k + 1 < len(rows) else ""
        out.append("  " + ", ".join(f"0x{b:02x}" for b in row) + sep)
    out += ["]", ""]
    return out


def header(b, kind):
    return ["module", "",
            *(["public import Silmaril.Machine.Abi.Conformance.Defs",
               f"public import {NS}.{b['name']}.Bytes", ""] if kind == "Defs" else []),
            f"/-! # {b['what']}: the {'bytes' if kind == 'Bytes' else 'code'} of the conformance rows",
            "",
            f"GENERATED by `scripts/abi-bytes/zlib_matrix.py` from `{b['file']}`",
            f"(SHA-256 `{b['sha']}`); do not edit.", ""]


def emit(b):
    path = b["file"]
    data = (ROOT / path).read_bytes()
    if hashlib.sha256(data).hexdigest() != b["sha"]:
        sys.exit(f"{path}: SHA-256 differs from the pin {b['sha']}")
    phdrs, syms = parse(data, path)
    loads = [p for p in phdrs if p[0] == 1]
    ro = [p for p in loads if p[1] == PF_R and p[3] != 0]
    if len(ro) != 1:
        sys.exit(f"{path}: expected one read-only data PT_LOAD above 0, found {len(ro)}")
    rova, rosz = ro[0][3], ro[0][5]
    byname = {f[1]: f for f in b["funcs"]}
    for lean, sym, value, size, versioned, _ in b["funcs"]:
        if syms.get(sym) != [(value, size, 2, versioned)]:
            sys.exit(f"{path}: .dynsym {sym} is {syms.get(sym)}, "
                     f"expected [({value:#x}, {size}, STT_FUNC, versioned={versioned})]")
    rx = PF_R | PF_X
    by = header(b, "Bytes") + [
        "Untrusted data: the code of the claimed entry points (by their `.dynsym` values and sizes),",
        "the bytes between a `_z` function and its wrapper, and the read-only data `PT_LOAD` (the",
        f"CRC tables). Nothing here is believed until a theorem of `Silmaril.Elf.Abi.ZlibMatrix.Thms`",
        "checks it against the file's bytes. -/", "",
        "set_option maxRecDepth 100000", "", "@[expose] public section", "",
        f"namespace {NS}.{b['name']}", ""]
    codes = []
    for lean, sym, value, size, versioned, wraps in b["funcs"]:
        by += lean_bytes(f"{lean}Bytes", f"`{sym}` (`{value:#x}`, {size} bytes).",
                         read(data, phdrs, value, size, rx, path))
    image = ", ".join(f"({p[3]:#x}, {p[6]:#x})" for p in loads)  # (p_vaddr, p_memsz)
    if b["crc"]:
        by += lean_bytes("rodata", f"The read-only data `PT_LOAD` at `{rova:#x}` ({rosz} bytes).",
                         read(data, phdrs, rova, rosz, PF_R, path))
    df = header(b, "Defs") + [
        "Each region at its link-time addresses (the rows rebase it, `Code.rebase`). A CRC function",
        "carries the read-only data segment, where its `%rip`-relative tables are; the image is the",
        "file's `PT_LOAD` ranges. -/", "",
        "@[expose] public section", "", f"namespace {NS}.{b['name']}", "",
        "open Silmaril.X86 (Word Byte)", "open Silmaril.Machine.Abi.Conformance", "",
        "/-- The image of the pinned file: its `PT_LOAD` ranges `(p_vaddr, p_memsz)`. -/",
        f"def image : List (Word × Nat) := [{image}]", ""]
    if b["crc"]:
        df += [f"/-- The read-only data `PT_LOAD` at `{rova:#x}`, the CRC tables in it. -/",
               f"def crcData : List (Word × List Byte) := [({rova:#x}, rodata)]", ""]
    for lean, sym, value, size, versioned, wraps in b["funcs"]:
        data_ = "crcData" if (b["crc"] and sym.startswith("crc")) else "[]"
        if wraps is None:
            df += [f"/-- `{sym}`: `{value:#x}`, {size} bytes. -/",
                   f"def {lean}Code : Code := ⟨{value:#x}, {lean}Bytes, 0, {size}, {data_}, image⟩", ""]
        else:
            zl, _, zv, zn, _, _ = byname[wraps]
            gap = value - zv - zn
            gapb = read(data, phdrs, zv + zn, gap, rx, path)
            by += lean_bytes(f"{lean}Gap", f"The bytes between `{wraps}`'s end (`{zv + zn:#x}`) and `{sym}`.", gapb)
            df += [f"/-- `{sym}`: `{value:#x}`, {size} bytes, a `jmp` to `{wraps}`; the region starts there. -/",
                   f"def {lean}Code : Code :=",
                   f"  ⟨{zv:#x}, {zl}Bytes ++ {lean}Gap ++ {lean}Bytes, {value - zv:#x}, {size}, {data_}, image⟩", ""]
    by += [f"end {NS}.{b['name']}", ""]
    df += [f"end {NS}.{b['name']}", "", "end", ""]
    by += ["end", ""]
    return {f"{OUT}/{b['name']}/Bytes.lean": "\n".join(by), f"{OUT}/{b['name']}/Defs.lean": "\n".join(df)}


def main(argv):
    check = "--check" in argv
    files = {}
    for b in BINARIES:
        files.update(emit(b))
    for rel, text in files.items():
        out = ROOT / rel
        if check:
            if not out.exists() or out.read_text() != text:
                sys.exit(f"{rel}: out of date (python3 -I scripts/abi-bytes/zlib_matrix.py)")
        else:
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text(text)
    print("zlib_matrix.py: " + ("up to date" if check else f"wrote {len(files)} modules"))


if __name__ == "__main__":
    main(sys.argv[1:])
