#!/usr/bin/env python3
"""Replay bounded Brotli dictionary meta-blocks against pinned libbrotli."""
import argparse
from hashlib import sha256
import json
from pathlib import Path
import runpy
from tempfile import TemporaryDirectory

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE.parent
COMMAND = runpy.run_path(str(SCRIPTS / "brotli-dictionary-command/check.py"))
MAPS, PIN, check, run = (COMMAND[name] for name in ("MAPS", "PIN", "check", "run"))
COMMAND_PINS = json.loads((SCRIPTS / "brotli-dictionary-command/fixtures.json").read_text())["fixtures"]


def assemble_empty_then_grow():
    """Author an RFC block, with two dictionary commands and no inserted literals."""
    bits = runpy.run_path(str(SCRIPTS / "brotli-insert-copy-switch/check.py"))["Bits"]()
    bits.code("01000")  # Window 16, final nonempty, 16-bit MLEN.
    bits.integer(6, 16)  # Seven regenerated bytes.
    bits.code("001000")  # One L type, one I type, two D types.
    bits.simple(4, [0, 1])
    bits.simple(26, [0])
    bits.integer(0, 2)  # First distance run has one symbol.
    bits.code("000000" "00" "00")  # NPOSTFIX/NDIRECT zero, LSB6, one tree per map.
    bits.simple(256, [65])
    bits.simple(704, [130])  # Explicit distance, zero insert, parsed copy length four.
    bits.simple(64, [43])  # Fourteen distance extra bits for each command.
    bits.integer(6148, 14)  # Word "time", ordinal 54 (omit-first-nine): empty.
    bits.code("1")  # Increment the distance block type.
    bits.integer(0, 2)  # The second distance run also has one symbol.
    bits.integer(1028, 14)  # Same history size, word "time", ordinal 49: "timing ".
    return bits.pack()


def lean(work, wire, cap, bits, commands):
    path = work / "payload.br"
    path.write_bytes(wire)
    return json.loads(run("lake", "env", "lean", "-DautoImplicit=false", "-DwarningAsError=true",
                          "--run", HERE / "Interop.lean", path, str(cap), str(bits), str(commands)).stdout)


def fail(work, wire, name, index, bit, kind, cause, cap, bits, slots):
    expected = {"index": index, "kind": kind, "cause": cause, "bit": bit}
    found = lean(work, wire, cap, bits, slots)
    check(found == {"failure": expected}, f"{name}: {found}")
    return expected


def compare(work, wire, reference, traced, native=True):
    output = run(reference, "-d", "-c", data=wire).stdout
    header, payload, commands, dictionaries = COMMAND["observe"](wire, reference, traced, output, native)
    last = commands[-1]
    rows = MAPS["native_trace"](wire, reference, traced)
    types = [int(row.split()[2]) for row in rows if row.startswith("types ")]
    check(types == ([1, 1, 1] if native else [1, 1, 2]), "expected native type counts")
    explicit = sum(row.startswith("distance_code ") for row in rows)
    native_quotas = [sum(cmd[1] for cmd in commands), len(commands), explicit]
    # For the single-type profile, Lean normalizes both type IDs to zero.
    runs = [[0, 0, (1 << 24) - used] for used in native_quotas]
    if types[2] == 2:
        runs[2] = next([int(value) for value in row.split()[1:]]
                       for row in reversed(rows) if row.startswith("distance_run "))
    expected = {"bytes": list(output), "payload": payload, "end": last[5], "ring": last[6],
                "runs": runs, "nextByte": None, "oldRefuses": True}
    exact = lean(work, wire, len(output), last[5], len(commands))
    check(exact == expected, f"exact result at all three caps: {str(exact)[:400]}")
    suffixed = lean(work, wire + b"\xa5", len(output), last[5], len(commands))
    check(suffixed == dict(expected, nextByte=0xa5), "first aligned suffix byte preserved")
    return header, payload, commands, dictionaries, output, runs


def collect(work, reference, traced):
    pins = {}
    for name, quality, plaintext in COMMAND["producer_inputs"]():
        wire = run(reference, "-q", str(quality), "-w", "18", "-c", data=plaintext).stdout
        header, payload, commands, dictionaries, output, runs = compare(work, wire, reference, traced)
        original = COMMAND_PINS[name]
        check(output == plaintext and sha256(wire).hexdigest() == original["wire_sha256"], "pinned producer")
        check(sha256(json.dumps(commands, separators=(",", ":")).encode()).hexdigest() == original["trace_sha256"],
              "pinned original command trace")
        end, slots = commands[-1][5], len(commands)
        failures = {"one-slot-short": fail(work, wire, name, slots - 1, commands[-2][5], "fuel", "",
                                           len(output), end, slots - 1)}
        if quality == 11:
            growth = next(row for row in dictionaries if row["actualLength"] > row["baseLength"])
            cap = growth["sizeBeforeCopy"] + growth["actualLength"] - 1
            shorter = COMMAND["change_extent"](wire, header, len(output), cap)
            tests = [
                ("caller-cap", wire, cap, end, growth["end"], "copy", "outputLimit"),
                ("shortened-mlen", shorter, cap, end, growth["end"], "copy", "metaBlockExtent"),
                ("short-distance-bits", wire, len(output), growth["end"] - 1, growth["begin"], "distance", "extraBitLimit"),
            ]
            for control, source, output_cap, bits, bit, kind, cause in tests:
                failures[control] = fail(work, source, control, growth["command"], bit, kind, cause,
                                         output_cap, bits, slots)
        pins[name] = {"payload": payload, "end": end, "commands": slots, "runs": runs, "failures": failures}
        print(f"{name}: {len(output)} bytes, {slots} command slots, original payload [{payload}, {end})")

    wire = assemble_empty_then_grow()
    _, payload, commands, dictionaries, output, runs = compare(work, wire, reference, traced, native=False)
    check(output == b"timing " and [row["actualLength"] for row in dictionaries] == [0, 7],
          "native empty transform then seven-byte transform")
    first, second = commands
    check(first[4] == 0 and first[5] > payload and first[6] == second[6] == [4, 11, 15, 16],
          "empty transform consumes source and keeps the ring")
    trace = MAPS["native_trace"](wire, reference, traced)
    [switch] = [[int(value) for value in row.split()[1:]] for row in trace if row.startswith("switch ")]
    check(switch[:5] == [2, 1, 0, 1, 1] and 8 * len(wire) - switch[5] == first[5],
          "independent distance switch after the empty output")
    at_code = 8 * len(wire) - switch[-1]
    size, end = len(output), second[5]
    failures = {
        "no-command-slots": fail(work, wire, "zero slots", 0, payload, "fuel", "", size, end, 0),
        "zero-output-spends-slot": fail(work, wire, "one slot", 1, first[5], "fuel", "", size, end, 1),
        "second-command-short-bits": fail(work, wire, "short bits", 1, at_code, "distance", "extraBitLimit",
                                          size, end - 1, 2),
        "second-command-short-output": fail(work, wire, "short output", 1, end, "copy", "outputLimit",
                                            size - 1, end, 2),
        "second-command-truncation": fail(work, wire[:-1], "truncated", 1, at_code, "distance", "truncatedExtra",
                                          size, end, 2),
    }
    pins["assembled-empty"] = {"wire_hex": wire.hex(), "output_hex": output.hex(), "commands": commands,
                                "dictionary": dictionaries, "runs": runs, "switch": [first[5], at_code], "failures": failures}
    print(f"assembled-empty: first command consumes [{payload}, {first[5]}) and emits zero bytes")
    print(f"assembled-empty: two slots succeed at bit {end}; one slot fails at bit {first[5]}")
    return {"libbrotli_commit": PIN, "fixtures": pins}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--brotli-source", type=Path)
    args = parser.parse_args()
    harness = runpy.run_path(str(SCRIPTS / "parquet-brotli-raw/check.py"))
    check(harness["PIN"] == PIN, "libbrotli pin")
    with TemporaryDirectory(prefix="silmaril-brotli-dictionary-block-") as directory:
        work = Path(directory)
        clean = work / "clean"
        clean.mkdir()
        source = args.brotli_source.resolve() if args.brotli_source else None
        reference = harness["build_reference"](source, clean)
        traced = MAPS["setup_trace"](source or clean / "brotli", work,
                                     SCRIPTS / "brotli-dictionary-command/trace-reference.py")
        actual = collect(work, reference, traced)
        check(actual == json.loads((HERE / "fixtures.json").read_text()), "pinned dictionary block replay")
        print(f"Fixture manifest matched libbrotli {PIN}")


if __name__ == "__main__":
    main()
