import re, sys
cases_h, gcc_t, ms_t, out = sys.argv[1:5]
ty = {"char": ".int .char .plain", "signed char": ".int .char .signed", "unsigned char": ".int .char .unsigned",
      "short": ".int .short .signed", "unsigned short": ".int .short .unsigned", "int": ".int .int .signed",
      "unsigned int": ".int .int .unsigned", "long": ".int .long .signed", "long long": ".int .longLong .signed",
      "_Bool": ".bool", "long double": ".float .longDouble", "enum e3": '.enum "e3" none', "void *": ".ptr .void"}
decls = []
for line in open(cases_h):
    m = re.match(r'^(struct|union) (\w+) \{(.*)\};', line.strip())
    if not m: continue
    kind, tag, body = m.groups()
    fields = []
    for d in [x.strip() for x in body.split(';') if x.strip()]:
        align = None
        am = re.match(r'_Alignas\((\d+)\)\s*(.*)', d)
        if am: align, d = int(am.group(1)), am.group(2)
        bits = None
        if ':' in d:
            d, w = d.split(':'); bits = int(w); d = d.strip()
        words = d.replace('*', ' * ').split()
        if bits is not None and ' '.join(words) in ty: name, tyw = "", ' '.join(words)
        else:
            name = words[-1]; tyw = ' '.join(words[:-1])
        arr = None
        am2 = re.match(r'(\w+)\[(\d+)\]', name)
        if am2: name, arr = am2.group(1), int(am2.group(2))
        t = ty[tyw.strip()]
        if arr: t = f".array ({t}) {arr}"
        fields.append((name, t, align, bits))
    decls.append((kind, tag, fields))
def table(path):
    res, cur = {}, None
    for line in open(path):
        if line.startswith('#') or not line.strip(): continue
        if not line.startswith('  '):
            tag, sz, al = line.split(); cur = tag; res[tag] = (int(sz), int(al), [])
        else:
            n, o, w = line.split()
            res[cur][2].append((None if o == '?' else int(o), None if w == '?' else int(w)))
    return res
G, M = table(gcc_t), table(ms_t)
def opt(x): return "none" if x is None else f"some {x}"
L = []
L.append('''module

public import Silmaril.Data.Layout.Bitfield.Defs

/-! # Bit-field layouts against real compilers: the cases

GENERATED by `examples/layout/gen-lean.sh` from `examples/layout/cases.h` (the declarations) and the
compiler measurements `examples/layout/gcc-x86_64.txt` (gcc 13.3, x86-64 System V) and
`examples/layout/msvc-x64.txt` (clang 18.1, `--target=x86_64-pc-windows-msvc`, MSVC record
layout); do not edit. The tables are data: `Examples.Thms` proves that `bitLayout` agrees with
every value they record. A value a compiler does not report (the offset of an unnamed bit-field
under gcc's run-time probe, an ordinary member's width in clang's dump) is `none` and constrains
nothing. -/

@[expose] public section

namespace Silmaril.Data.Layout.Examples

open Silmaril.Data.Layout

/-- A measured record: size, alignment, and per member (bit offset, bit width) if reported. -/
structure Measured where
  size : Nat
  align : Nat
  members : List (Option Nat × Option Nat)
  deriving DecidableEq, Repr

/-- **The computed layout agrees with a measurement**: same size and alignment, and every reported
member offset and width. -/
def agrees (m : Measured) : Except String (List BitSlot × Shape) → Bool
  | .error _ => false
  | .ok (ss, sh) => sh.size == m.size && sh.align == m.align && ss.length == m.members.length &&
      (ss.zip m.members).all fun (s, o, w) => (o.all (· == s.off)) && (w.all (· == s.width))
''')
def align_members(fields, ms):
    """Measured members in declaration order; a zero-width bit-field a table omits is (None, None)."""
    out, i = [], 0
    for (n, t, a, b) in fields:
        if b == 0 and not (i < len(ms) and ms[i][1] == 0):
            out.append((None, None)); continue
        out.append(ms[i]); i += 1
    assert i == len(ms), (fields, ms)
    return out
for kind, tag, fields in decls:
    fs = ", ".join(f'⟨"{n}", {t}, {opt(a)}, {opt(b)}⟩' for (n, t, a, b) in fields)
    L.append(f"/-- `{kind} {tag}` -/\ndef {tag} : Decl := ⟨.{kind}, \"{tag}\", [{fs}]⟩\n")
    for nm, T in (("gcc", G), ("msvc", M)):
        sz, al, ms = T[tag]
        ms = align_members(fields, ms)
        mem = ", ".join(f"({opt(o)}, {opt(w)})" for (o, w) in ms)
        L.append(f"def {tag}_{nm} : Measured := ⟨{sz}, {al}, [{mem}]⟩\n")
L.append("/-- The cases. -/\ndef cases : List (Decl × Measured × Measured) :=\n  [" +
         ",\n   ".join(f"({t}, {t}_gcc, {t}_msvc)" for (_, t, _) in decls) + "]\n")
L.append("end Silmaril.Data.Layout.Examples\n")
open(out, 'w').write("\n".join(L))
