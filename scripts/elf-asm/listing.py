#!/usr/bin/env python3
"""Emit the display listing lines of functions of a pinned ELF file as a Lean module.

The lines are what `objdump -d` prints: display data for `Silmaril.Elf.Asm.Line`, never evidence
(no proposition reads `Line.text`; `LinesTile` checks only their byte ranges). The byte ranges
come from objdump's addresses and byte columns; the theorems check that they tile the bytes.

usage: listing.py ELF NAMESPACE OUT.lean NAME=SYMBOL:VADDR:SIZE ... [--check]
"""
import subprocess, sys, re

def lean_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'

def lines_of(elf, symbol, vaddr, size):
    out = subprocess.run(
        ["objdump", "-d", "--no-show-raw-insn", "--insn-width=16",
         f"--start-address={vaddr:#x}", f"--stop-address={vaddr + size:#x}", elf],
        check=True, capture_output=True, text=True).stdout
    rows = []
    for line in out.splitlines():
        m = re.match(r"^\s+([0-9a-f]+):\t(.*)$", line)
        if m:
            rows.append((int(m.group(1), 16), " ".join(m.group(2).split())))
    res = []
    for k, (addr, text) in enumerate(rows):
        end = rows[k + 1][0] if k + 1 < len(rows) else vaddr + size
        res.append((addr - vaddr, end - addr, text, symbol if addr == vaddr else None))
    return res

def main(argv):
    check = "--check" in argv
    argv = [a for a in argv if a != "--check"]
    elf, ns, out_path, specs = argv[0], argv[1], argv[2], argv[3:]
    version = subprocess.run(["objdump", "--version"], check=True, capture_output=True,
                             text=True).stdout.splitlines()[0]
    body = [
        "module", "", "public import Silmaril.Elf.Asm.Defs", "",
        f"/-! # Display listings (`objdump -d`) of functions of `{elf}`", "",
        f"GENERATED by `scripts/elf-asm/listing.py` with `{version}`; do not edit.", "",
        "Display data only: no proposition reads `Line.text` (`Silmaril.Elf.Asm`). The byte",
        "ranges are objdump's instruction boundaries; `LinesTile` checks that they tile the bytes,",
        "nothing checks that the text describes them. -/", "",
        "@[expose] public section", "", f"namespace {ns}", "",
        "open Silmaril.Elf.Asm", "",
    ]
    for spec in specs:
        name, rest = spec.split("=")
        symbol, vaddr, size = rest.split(":")
        vaddr, size = int(vaddr, 0), int(size, 0)
        body.append(f"/-- `{symbol}` (`{vaddr:#x}`, {size} bytes), as `objdump -d` prints it. -/")
        body.append(f"def {name} : List Line := [")
        rows = lines_of(elf, symbol, vaddr, size)
        for k, (off, ln, text, label) in enumerate(rows):
            lab = f", label := some {lean_str(label)}" if label else ""
            sep = "," if k + 1 < len(rows) else ""
            body.append(f"  {{ off := {off}, len := {ln}, text := {lean_str(text)}{lab} }}{sep}")
        body += ["]", ""]
    body += [f"end {ns}", ""]
    text = "\n".join(body)
    if check:
        if open(out_path).read() != text:
            sys.exit(f"{out_path}: out of date (scripts/elf-asm/listing.py)")
        return
    open(out_path, "w").write(text)

if __name__ == "__main__":
    main(sys.argv[1:])
