#!/usr/bin/env python3
"""Compare bounded Brotli distance-switched commands with pinned libbrotli."""
import argparse
from hashlib import sha256
import json
from pathlib import Path
import runpy
import subprocess
from tempfile import TemporaryDirectory

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE.parent
SWITCH = runpy.run_path(str(SCRIPTS / "brotli-insert-copy-switch/check.py"))
PIN, check, run, MAPS = SWITCH["PIN"], SWITCH["check"], SWITCH["run"], SWITCH["MAPS"]


def assemble():
    """Independently write an RFC 7932 block with explicit and implicit distances."""
    bits = SWITCH["Bits"]()
    bits.code("010")  # Window 16 and one last, nonempty meta-block.
    bits.integer(0, 2)
    bits.integer(16, 16)  # 17 regenerated bytes.
    bits.code("001000")  # One L type, one I type, two D types.
    bits.simple(4, [0, 1])
    bits.simple(26, [0])
    bits.integer(0, 2)  # One explicit distance before the first switch.
    bits.integer(0, 2)
    bits.integer(4, 4)
    bits.integer(0, 2)
    bits.code("010000")  # Implicit L map, two D trees, no D zero-run encoding.
    bits.simple(2, [0, 1])
    bits.code("00001010")  # Type 1 selects tree 1 in contexts 0 and 2.
    bits.code("0")  # No inverse MTF.
    bits.simple(256, [65, 67])
    bits.simple(704, [2, 130, 136, 144])
    bits.code("0")  # Four codes of width two.
    bits.simple(68, [17, 18])
    bits.simple(68, [16, 20])
    bits.code("11" "01" "0")      # Insert AC and copy two at direct distance 2.
    bits.code("00")                # Implicit distance 2 leaves the exhausted D run alone.
    bits.code("01" "1" "00" "1" "0")  # Increment type, select tree 1, regular distance 5.
    bits.code("01" "0" "00" "1")      # Previous type, tree 0, direct distance 3.
    bits.code("10" "0")            # Final literal A uses no distance, even with explicit command form.
    return bits.pack()


def observe(wire, reference, traced):
    extent = 8 * len(wire)
    rows = MAPS["native_trace"](wire, reference, traced)
    commands, switches, types = [], [], []
    copy = None
    for row in rows:
        kind, *values = row.split()
        values = list(map(int, values))
        if kind == "types":
            types.append(values[1])
        elif kind == "command":
            _, symbol, _, _, _, before, after = values
            command = {"symbol": symbol, "before": extent - before, "atLiterals": extent - after}
            copy = None
        elif kind == "distance_begin":
            unread, explicit, context = values
            begin = extent - unread
            at_code = begin
            selection = code = None
        elif kind == "switch":
            category, symbol, previous, current, length, start, after_type, stop = values
            check(category == 2 and extent - start == begin, "native D switch occurs before value")
            at_code = extent - stop
            switches.append([len(commands), symbol, previous, current, length,
                             begin, extent - after_type, at_code])
        elif kind == "distance_code":
            value, extra, tree = values
            selection = [context, tree]
            code = [value, extra]
        elif kind == "distance_run":
            active = values
        elif kind == "distance_end":
            unread, produced, _, distance, length = values
            check(bool(selection) == bool(explicit), "native distance mode")
            copy = dict(command, atDistance=begin, atCode=at_code, end=extent - unread, selection=selection,
                        code=code, run=active, distance=distance, outputLength=produced + length)
        elif kind == "back":
            commands.append(dict(copy, ring=values))
        elif kind == "envelope_end":
            end = extent - values[0]
    check(copy is None and len(commands) == 4 and types == [1, 1, 2], "native profile and terminal insertion")
    commands.append(dict(command, atDistance=end, atCode=end, end=end, selection=None, code=None,
                         run=commands[-1]["run"], distance=None, outputLength=17, ring=commands[-1]["ring"]))
    return commands, switches


def lean_decode(work, wire, output, bits):
    path = work / "wire.br"
    path.write_bytes(wire)
    reply = run("lake", "env", "lean", "-DautoImplicit=false", "-DwarningAsError=true", "--run",
                HERE / "Interop.lean", path, str(output), str(bits))
    return json.loads(reply.stdout)


def collect(reference, traced, work):
    wire = assemble()
    extent = 8 * len(wire)
    plain = run(reference, "-d", "-c", data=wire).stdout
    commands, switches = observe(wire, reference, traced)
    actual = lean_decode(work, wire, len(plain), extent)
    check(actual == {"output": list(plain), "ring": commands[-1]["ring"], "commands": commands,
                     "previousRefusals": True}, f"Lean command trace and output: {actual}")
    check([(row["distance"], row["run"], row["selection"]) for row in commands] ==
          [(2, [0, 1, 0], [0, 0]), (2, [0, 1, 0], None), (5, [1, 0, 0], [2, 1]),
           (3, [0, 1, 0], [2, 0]), (None, [0, 1, 0], None)], "distance run and context rows")
    check([row[1:4] for row in switches] == [[1, 0, 1], [0, 1, 0]], "increment and previous D switches")
    print(f"Assembled D specimen: {len(plain)} bytes, {len(commands)} commands, {len(switches)} switches")
    first, second = switches
    bad = wire[:-1]
    check(subprocess.run([reference, "-d", "-c"], input=bad, capture_output=True).returncode != 0,
          "native rejects byte truncation")
    cases = (
        ("D-type-cap", wire, len(plain), first[-3], "switch-type", 2, first[-3], "bitLimit"),
        ("D-count-cap", wire, len(plain), first[-2] + 1, "switch-length", 2, first[-2], "bitLimit"),
        ("D-symbol-cap", wire, len(plain), first[-1], "distance", 2, first[-1], "bitLimit"),
        ("D-extra-cap", wire, len(plain), commands[2]["end"] - 1, "distance", 2, first[-1], "extraBitLimit"),
        ("D-copy-output-cap", wire, commands[2]["outputLength"] - 1, extent, "copy", 2, commands[2]["end"],
         "outputLimit"),
        ("late-truncation", bad, len(plain), extent, "switch-type", 3, second[-3], "truncated"),
    )
    failures = {}
    for name, data, output, cap, stage, command, bit, reason in cases:
        actual = lean_decode(work, data, output, cap)["failure"]
        check((actual["stage"], actual["command"], actual["bit"]) == (stage, command, bit) and
              actual["cause"].rstrip(")").endswith("." + reason), f"{name}: {actual}")
        failures[name] = actual
        print(f"{name}: {stage} at bit {bit}, command {command}")

    dictionary_plain = b"".join(f"Reader {i % 23} checks compressed page {i} with a fixed output budget.\n".encode()
                                for i in range(99))
    dictionary = run(reference, "-q", "7", "-w", "18", "-c", data=dictionary_plain).stdout
    prior = json.loads((SCRIPTS / "brotli-literal-switch/fixtures.json").read_text())["unsupported"]["dictionary"]
    check(sha256(dictionary).hexdigest() == prior["sha256"], "pinned native-produced dictionary stream")
    check(run(reference, "-d", "-c", data=dictionary).stdout == dictionary_plain, "native dictionary output")
    rows = MAPS["native_trace"](dictionary, reference, traced)
    after = 8 * len(dictionary) - int(next(row.split()[1] for row in rows if row.startswith("distance_end ")))
    failed = lean_decode(work, dictionary, len(dictionary_plain), 8 * len(dictionary))["failure"]
    check(failed == {"stage": "dictionary", "command": 0, "bit": after, "cause": prior["failure"]["cause"]},
          f"native dictionary fails with typed address after decoding distance: {failed}")
    print(f"Native dictionary rejected at bit {after} after distance resolution")
    return {"libbrotli_commit": PIN, "provenance": "independent RFC 7932 assembly",
            "wire_hex": wire.hex(), "sha256": sha256(wire).hexdigest(), "plain_hex": plain.hex(),
            "commands": commands, "switches": switches, "failures": failures,
            "native_dictionary": {"sha256": sha256(dictionary).hexdigest(), "failure": failed}}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--brotli-source", type=Path)
    args = parser.parse_args()
    harness = runpy.run_path(str(SCRIPTS / "parquet-brotli-raw/check.py"))
    check(harness["PIN"] == PIN, "libbrotli pin")
    with TemporaryDirectory(prefix="silmaril-brotli-distance-switch-") as temp:
        work = Path(temp)
        clean = work / "clean"
        clean.mkdir()
        source = args.brotli_source.resolve() if args.brotli_source else None
        reference = harness["build_reference"](source, clean)
        source = source or clean / "brotli"
        traced = MAPS["setup_trace"](source, work, HERE / "trace-reference.py")
        report = collect(reference, traced, work)
        check(report == json.loads((HERE / "fixtures.json").read_text()), "pinned command replay")
        print(f"Fixture manifest matched libbrotli {PIN}")


if __name__ == "__main__":
    main()
