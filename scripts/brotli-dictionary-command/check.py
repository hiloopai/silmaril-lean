#!/usr/bin/env python3
"""Compare dictionary-dependent Brotli commands on pinned native producer streams."""
import argparse
from hashlib import sha256
import json
from pathlib import Path
import runpy
from tempfile import TemporaryDirectory

HERE = Path(__file__).resolve().parent
SCRIPTS = HERE.parent
MAPS = runpy.run_path(str(SCRIPTS / "brotli-context-maps/check.py"))
PIN, check, run = MAPS["PIN"], MAPS["check"], MAPS["run"]


def observe(wire, reference, traced, output, require_following_back=True):
    size = 8 * len(wire)
    trace = MAPS["native_trace"](wire, reference, traced)
    commands, dictionaries = [], []
    at = 0
    following_back = False
    for row in trace:
        label, *values = row.split()
        values = list(map(int, values))
        if label == "envelope":
            check(values[:4] == [1, 0, 0, len(output)], "one final compressed meta-block")
            header = size - values[4]
        elif label == "payload":
            payload = size - values[0]
        elif label == "command":
            _, symbol, literal, length, _, _, _ = values
        elif label == "distance_begin":
            at_distance = size - values[0]
        elif label == "ring_before":
            before_ring = values
        elif label == "dictionary":
            ring = values
        elif label == "distance_end":
            unread, produced, maximum, distance, base = values
            check(produced == at + literal and base == length, "native insertion and copy lengths")
            cursor = size - unread
        elif label == "dictionary_emit":
            word_id, ordinal, base, actual = values
            check(distance == maximum + 1 + word_id and distance > maximum and base == length
                  and ring == before_ring, "native dictionary route and ring")
            dictionaries.append({"command": len(commands), "wordId": word_id, "ordinal": ordinal,
                                 "baseLength": base, "actualLength": actual, "sizeBeforeCopy": produced,
                                 "begin": at_distance, "end": cursor,
                                 "bytes": output[produced:produced + actual].hex()})
            at = produced + actual
            commands.append([symbol, literal, base, distance, at, cursor, ring])
        elif label == "back":
            check(distance <= maximum, "native backward route")
            following_back = following_back or bool(dictionaries)
            at = produced + base
            commands.append([symbol, literal, base, distance, at, cursor, values])
        elif label == "terminal_command":
            unread, produced = values
            check(produced == at + literal, "native terminal literal extent")
            at, cursor = produced, size - unread
        elif label == "terminal_ring":
            commands.append([symbol, literal, length, None, at, cursor, values])
        elif label == "envelope_end":
            check(cursor == size - values[0] and at == len(output), "native exact block end")
    check(dictionaries and (following_back or not require_following_back), "dictionary-dependent command path")
    return header, payload, commands, dictionaries


def lean(work, wire, cap, bits=None):
    path = work / "stream.br"
    path.write_bytes(wire)
    return json.loads(run("lake", "env", "lean", "-DautoImplicit=false", "-DwarningAsError=true",
                          "--run", HERE / "Interop.lean", path, str(cap),
                          str(8 * len(wire) if bits is None else bits)).stdout)


def change_extent(wire, header, prior, extent):
    """Mutate the existing final compressed meta-block's 16-bit MLEN field."""
    encoded = int.from_bytes(wire, "little")
    shift = header - 16
    check((encoded >> (shift - 2)) & 3 == 0, "16-bit length selector")
    check((encoded >> shift) & 65535 == prior - 1, "original declared MLEN")
    changed = (encoded & ~(65535 << shift)) | ((extent - 1) << shift)
    return changed.to_bytes(len(wire), "little")


def producer_inputs():
    return [
        ("reader-q7", 7, b"".join(f"Reader {i % 23} checks compressed page {i} with a fixed output budget.\n".encode()
                                 for i in range(99))),
        ("weather-q11", 11, b"The quick brown fox jumps over the lazy dog. "
                            b"The temperature and forecast are available on the website.\n" * 6),
    ]


def collect(work, reference, traced):
    results, failures = {}, {}
    for name, quality, producer_input in producer_inputs():
        wire = run(reference, "-q", str(quality), "-w", "18", "-c", data=producer_input).stdout
        data = run(reference, "-d", "-c", data=wire).stdout
        check(data == producer_input, f"{name}: native regenerated bytes")
        header, payload, commands, dictionaries = observe(wire, reference, traced, data)
        expected = {"commands": commands, "payload": payload, "bytes": list(data), "oldRefuses": True}
        actual = lean(work, wire, len(data))
        check(actual == expected, f"{name}: command output, cursor, ring or predecessor refusal")
        changed = [(r["baseLength"], r["actualLength"]) for r in dictionaries]
        check(any(a > b for a, b in changed) if quality == 7 else any(a < b for a, b in changed),
              f"{name}: shrinking/growing dictionary witness")
        results[name] = {"quality": quality, "window": 18, "wire_sha256": sha256(wire).hexdigest(),
                         "output_sha256": sha256(data).hexdigest(), "output_bytes": len(data),
                         "commands": len(commands), "payload_bit": payload, "end_bit": commands[-1][5],
                         "trace_sha256": sha256(json.dumps(commands, separators=(",", ":")).encode()).hexdigest(),
                         "dictionary": dictionaries}
        print(f"{name}: {len(commands)} commands, {len(dictionaries)} dictionary copies, {len(data)} exact output bytes")
        if quality == 11:
            growth = next(row for row in dictionaries if row["actualLength"] > row["baseLength"])
            cap = growth["sizeBeforeCopy"] + growth["actualLength"] - 1
            shorter = change_extent(wire, header, len(data), cap)
            controls = [
                ("caller-cap", wire, cap, None, growth["end"], "copy", "outputLimit"),
                ("mlen-before-caller-cap", shorter, cap, None, growth["end"], "copy", "metaBlockExtent"),
                ("one-bit-short", wire, len(data), growth["end"] - 1, growth["begin"], "distance", "extraBitLimit"),
            ]
            for control, source, cap, bits, offset, stage, reason in controls:
                expected = {"command": growth["command"], "bit": offset, "stage": stage, "reason": reason}
                actual = lean(work, source, cap, bits)
                check(actual == {"failure": expected}, f"{control}: {actual}")
                failures[control] = expected
                print(f"{control}: {reason} at original bit {offset}")
    return {"libbrotli_commit": PIN, "fixtures": results, "failures": failures}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--brotli-source", type=Path)
    args = parser.parse_args()
    harness = runpy.run_path(str(SCRIPTS / "parquet-brotli-raw/check.py"))
    check(harness["PIN"] == PIN, "libbrotli pin")
    with TemporaryDirectory(prefix="silmaril-brotli-dictionary-command-") as directory:
        work = Path(directory)
        clean = work / "clean"
        clean.mkdir()
        source = args.brotli_source.resolve() if args.brotli_source else None
        reference = harness["build_reference"](source, clean)
        traced = MAPS["setup_trace"](source or clean / "brotli", work, HERE / "trace-reference.py")
        actual = collect(work, reference, traced)
        check(actual == json.loads((HERE / "fixtures.json").read_text()), "pinned dictionary command replay")
        print(f"Fixture manifest matched libbrotli {PIN}")


if __name__ == "__main__":
    main()
